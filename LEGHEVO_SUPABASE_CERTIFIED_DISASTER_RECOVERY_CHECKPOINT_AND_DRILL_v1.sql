      'fresh', coalesce((v_audit ->> 'fresh')::boolean, false),
      'auditGeneration', coalesce((v_audit ->> 'auditGeneration')::bigint, 0),
      'auditedThroughSequence', coalesce((v_audit ->> 'auditedThroughSequence')::bigint, 0),
