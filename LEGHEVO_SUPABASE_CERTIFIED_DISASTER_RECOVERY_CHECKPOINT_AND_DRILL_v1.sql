-- LEGHEVO v0.62.40
-- Checkpoint immutabile di disaster recovery e prova di ripristino certificata
-- Dipendenza: v0.62.39 validata con 20/20 controlli true.

begin;

do $preflight$
declare
  v_integrity jsonb;
  v_false text[];
begin
  if to_regprocedure('public.get_leghevo_disaster_recovery_deployment_integrity_v1()') is not null
    and exists (
      select 1 from public.leghevo_application_release_certificates certificate
      where certificate.application_version = '0.62.40'
    ) then
    return;
  end if;

  if to_regprocedure('public.get_leghevo_operational_delivery_audit_deployment_integrity_v1()') is null then
    raise exception 'Preflight v0.62.40 non superato: diagnostica v0.62.39 assente.';
  end if;

  v_integrity := public.get_leghevo_operational_delivery_audit_deployment_integrity_v1();
  select array_agg(item.key order by item.key) into v_false
  from pg_catalog.jsonb_each(v_integrity) item
  where pg_catalog.jsonb_typeof(item.value) is distinct from 'boolean'
     or item.value is distinct from 'true'::jsonb;

  if (select count(*) from pg_catalog.jsonb_each(v_integrity)) <> 20
    or cardinality(v_false) > 0 then
    raise exception 'Preflight v0.62.40 non superato: %. Dettaglio: %',
      coalesce(array_to_string(v_false, ', '), 'numero controlli diverso da 20'),
      v_integrity;
  end if;
end;
$preflight$;

