create or replace function public.guard_leghevo_disaster_recovery_immutable_v1()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if current_setting('leghevo.disaster_recovery_context', true) <> 'allowed' then
    raise exception 'Record disaster recovery immutabile: scrittura diretta vietata.';
  end if;
  if tg_op in ('UPDATE','DELETE') then
    raise exception 'Record disaster recovery append-only: modifica o cancellazione vietata.';
  end if;
  return new;
end;
$function$;

create or replace function public.guard_leghevo_disaster_recovery_head_v1()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if current_setting('leghevo.disaster_recovery_context', true) <> 'allowed' then
    raise exception 'Testa disaster recovery protetta: scrittura diretta vietata.';
  end if;
  if tg_op = 'DELETE' then
    raise exception 'Testa disaster recovery non cancellabile.';
  end if;
  if tg_op = 'UPDATE' then
    if new.checkpoint_generation < old.checkpoint_generation
      or new.drill_generation < old.drill_generation
      or new.revision <= old.revision then
      raise exception 'Regressione della testa disaster recovery vietata.';
    end if;
  end if;
  return new;
end;
$function$;

