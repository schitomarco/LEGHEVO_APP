create or replace function public.get_leghevo_disaster_recovery_model_v1(
  p_environment_key text default 'production'
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  v_environment text := lower(trim(coalesce(p_environment_key, '')));
  v_head public.leghevo_disaster_recovery_heads%rowtype;
  v_checkpoint public.leghevo_disaster_recovery_checkpoints%rowtype;
  v_drill public.leghevo_disaster_recovery_drills%rowtype;
  v_current_snapshot jsonb;
  v_checkpoint_stable boolean := false;
  v_drill_stable boolean := false;
  v_component_mismatch_count bigint := 0;
  v_fresh boolean := false;
  v_protected boolean := false;
  v_healthy boolean := false;
  v_status text := 'affected';
  v_reason text := 'disaster_recovery.missing';
begin
  if v_environment not in ('production','staging') then
    return jsonb_build_object(
      'protected', false, 'healthy', false, 'fresh', false,
      'status', 'affected', 'reasonCode', 'disaster_recovery.invalid_environment',
      'environment', v_environment
    );
  end if;

  select head.* into v_head
  from public.leghevo_disaster_recovery_heads head
  where head.environment_key = v_environment;
  if not found then
    return jsonb_build_object(
      'protected', false, 'healthy', false, 'fresh', false,
      'status', 'affected', 'reasonCode', 'disaster_recovery.missing',
      'environment', v_environment
    );
  end if;

  select checkpoint.* into v_checkpoint
  from public.leghevo_disaster_recovery_checkpoints checkpoint
  where checkpoint.id = v_head.checkpoint_id;
  if v_head.latest_drill_id is not null then
    select drill.* into v_drill
    from public.leghevo_disaster_recovery_drills drill
    where drill.id = v_head.latest_drill_id;
  end if;

  v_checkpoint_stable := v_checkpoint.id is not null
    and v_checkpoint.checkpoint_fingerprint =
      public.compute_leghevo_disaster_recovery_checkpoint_fingerprint_v1(
        v_checkpoint.environment_key, v_checkpoint.checkpoint_generation,
        v_checkpoint.snapshot_payload, v_checkpoint.status,
        v_checkpoint.contract_version);

  v_drill_stable := v_drill.id is not null
    and v_drill.drill_fingerprint =
      public.compute_leghevo_disaster_recovery_drill_fingerprint_v1(
        v_drill.checkpoint_id, v_drill.environment_key,
        v_drill.drill_generation, v_drill.status,
        v_drill.verified_component_count, v_drill.component_mismatch_count,
        v_drill.sequence_regression_count, v_drill.recovery_plan,
        v_drill.contract_version);

  select count(*) into v_component_mismatch_count
  from public.leghevo_disaster_recovery_checkpoint_components component
  where component.checkpoint_id = v_checkpoint.id
    and component.component_fingerprint <>
      public.compute_leghevo_disaster_recovery_component_fingerprint_v1(
        component.environment_key, component.checkpoint_generation,
        component.component_key, component.component_payload,
        component.contract_version);

  v_current_snapshot := public.get_leghevo_disaster_recovery_snapshot_v1(v_environment);
  v_fresh := v_checkpoint.snapshot_payload = v_current_snapshot;
  v_protected := v_checkpoint_stable and v_drill_stable
    and v_component_mismatch_count = 0
    and v_drill.status = 'passed'
    and v_drill.verified_component_count = 7
    and v_drill.component_mismatch_count = 0
    and v_drill.sequence_regression_count = 0
    and v_head.status in ('certified','revalidated');
  v_healthy := v_protected and v_fresh;
  v_status := case
    when not v_protected then 'affected'
    when not v_fresh then 'stale'
    else 'certified'
  end;
  v_reason := case
    when not v_checkpoint_stable then 'disaster_recovery.checkpoint_fingerprint_changed'
    when not v_drill_stable then 'disaster_recovery.drill_fingerprint_changed'
