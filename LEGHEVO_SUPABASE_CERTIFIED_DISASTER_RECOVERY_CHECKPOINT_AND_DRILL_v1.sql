create table if not exists public.leghevo_disaster_recovery_checkpoints (
  id bigint generated by default as identity primary key,
  environment_key text not null,
  checkpoint_generation bigint not null,
  request_id uuid not null unique,
  active_release_version text not null,
  release_generation bigint not null,
  rollout_generation bigint not null,
  exposure_percentage integer not null,
  telemetry_generation bigint not null,
  telemetry_window_sequence bigint not null,
  outbox_last_sequence bigint not null,
  consumer_last_sequence bigint not null,
  delivery_audit_generation bigint not null,
  audited_through_sequence bigint not null,
  component_count integer not null,
  snapshot_payload jsonb not null,
  status text not null,
  reason_code text not null,
  contract_version integer not null default 1,
  checkpoint_fingerprint text not null unique,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  created_by uuid null,
  constraint leghevo_dr_checkpoint_environment_check
    check (environment_key in ('production','staging')),
  constraint leghevo_dr_checkpoint_generation_check
    check (checkpoint_generation >= 1),
  constraint leghevo_dr_checkpoint_release_check
    check (char_length(trim(active_release_version)) between 3 and 64),
  constraint leghevo_dr_checkpoint_counters_check
    check (
      release_generation >= 1 and rollout_generation >= 1
      and exposure_percentage between 0 and 100
      and telemetry_generation >= 1 and telemetry_window_sequence >= 1
      and outbox_last_sequence >= 0 and consumer_last_sequence >= 0
      and delivery_audit_generation >= 1 and audited_through_sequence >= 0
      and component_count = 7
    ),
  constraint leghevo_dr_checkpoint_snapshot_check
    check (jsonb_typeof(snapshot_payload) = 'object'),
  constraint leghevo_dr_checkpoint_status_check
    check (status in ('certified','affected')),
  constraint leghevo_dr_checkpoint_reason_check
    check (char_length(trim(reason_code)) between 3 and 160),
  constraint leghevo_dr_checkpoint_contract_check
    check (contract_version >= 1),
  constraint leghevo_dr_checkpoint_fingerprint_check
    check (checkpoint_fingerprint ~ '^[0-9a-f]{64}$'),
  constraint leghevo_dr_checkpoint_details_check
    check (jsonb_typeof(details) = 'object'),
  constraint leghevo_dr_checkpoint_generation_unique
    unique (environment_key, checkpoint_generation)
);

