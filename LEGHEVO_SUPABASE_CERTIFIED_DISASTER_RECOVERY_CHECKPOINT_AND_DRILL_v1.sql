      not has_table_privilege('authenticated','public.leghevo_disaster_recovery_checkpoints','INSERT')
      and not has_table_privilege('service_role','public.leghevo_disaster_recovery_checkpoints','INSERT')
      and not has_table_privilege('authenticated','public.leghevo_disaster_recovery_heads','UPDATE'),
