create or replace function public.create_leghevo_disaster_recovery_checkpoint_v1(
  p_environment_key text,
  p_request_id uuid,
  p_reason_code text,
  p_details jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_environment text := lower(trim(coalesce(p_environment_key, '')));
  v_reason text := trim(coalesce(p_reason_code, ''));
  v_details jsonb := coalesce(p_details, '{}'::jsonb);
  v_existing public.leghevo_disaster_recovery_checkpoints%rowtype;
  v_checkpoint public.leghevo_disaster_recovery_checkpoints%rowtype;
  v_snapshot jsonb;
  v_component record;
  v_generation bigint;
  v_fingerprint text;
  v_event_fingerprint text;
  v_head public.leghevo_disaster_recovery_heads%rowtype;
begin
  if v_environment not in ('production','staging') then
    raise exception 'Ambiente disaster recovery non valido.';
  end if;
  if p_request_id is null then
    raise exception 'Request ID checkpoint obbligatorio.';
  end if;
  if char_length(v_reason) not between 3 and 160 then
    raise exception 'Reason code checkpoint non valido.';
  end if;
  if jsonb_typeof(v_details) <> 'object' then
    raise exception 'Details checkpoint deve essere un oggetto JSON.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('leghevo:disaster-recovery:' || v_environment, 0));

  select checkpoint.* into v_existing
  from public.leghevo_disaster_recovery_checkpoints checkpoint
  where checkpoint.request_id = p_request_id;
  if found then
    if v_existing.environment_key <> v_environment then
      raise exception 'Request ID checkpoint già usato con ambiente differente.';
    end if;
    return jsonb_build_object(
      'checkpointId', v_existing.id,
      'checkpointGeneration', v_existing.checkpoint_generation,
      'status', v_existing.status,
      'reused', true
    );
  end if;

  v_snapshot := public.get_leghevo_disaster_recovery_snapshot_v1(v_environment);
  if not coalesce((v_snapshot #>> '{application_integrity,protected}')::boolean, false)
    or not coalesce((v_snapshot #>> '{application_integrity,healthy}')::boolean, false)
    or not coalesce((v_snapshot #>> '{release,protected}')::boolean, false)
    or not coalesce((v_snapshot #>> '{release,healthy}')::boolean, false)
    or not coalesce((v_snapshot #>> '{rollout,protected}')::boolean, false)
    or not coalesce((v_snapshot #>> '{rollout,healthy}')::boolean, false)
    or not coalesce((v_snapshot #>> '{telemetry,protected}')::boolean, false)
    or not coalesce((v_snapshot #>> '{telemetry,healthy}')::boolean, false)
    or not coalesce((v_snapshot #>> '{outbox,protected}')::boolean, false)
    or not coalesce((v_snapshot #>> '{outbox,healthy}')::boolean, false)
    or not coalesce((v_snapshot #>> '{consumer_delivery,protected}')::boolean, false)
    or not coalesce((v_snapshot #>> '{consumer_delivery,healthy}')::boolean, false)
    or not coalesce((v_snapshot #>> '{delivery_audit,protected}')::boolean, false)
    or not coalesce((v_snapshot #>> '{delivery_audit,healthy}')::boolean, false)
    or not coalesce((v_snapshot #>> '{delivery_audit,fresh}')::boolean, false) then
    raise exception 'Checkpoint disaster recovery rifiutato: catena operativa non sana.';
  end if;

  select coalesce(max(checkpoint.checkpoint_generation), 0) + 1 into v_generation
  from public.leghevo_disaster_recovery_checkpoints checkpoint
  where checkpoint.environment_key = v_environment;

  v_fingerprint := public.compute_leghevo_disaster_recovery_checkpoint_fingerprint_v1(
    v_environment, v_generation, v_snapshot, 'certified', 1);

  perform pg_catalog.set_config('leghevo.disaster_recovery_context','allowed',true);
  insert into public.leghevo_disaster_recovery_checkpoints (
    environment_key, checkpoint_generation, request_id,
    active_release_version, release_generation, rollout_generation,
    exposure_percentage, telemetry_generation, telemetry_window_sequence,
    outbox_last_sequence, consumer_last_sequence,
    delivery_audit_generation, audited_through_sequence,
    component_count, snapshot_payload, status, reason_code,
    contract_version, checkpoint_fingerprint, details, created_by
  ) values (
    v_environment, v_generation, p_request_id,
    v_snapshot #>> '{release,activeVersion}',
    (v_snapshot #>> '{release,releaseGeneration}')::bigint,
    (v_snapshot #>> '{rollout,rolloutGeneration}')::bigint,
    (v_snapshot #>> '{rollout,exposurePercentage}')::integer,
    (v_snapshot #>> '{telemetry,telemetryGeneration}')::bigint,
    (v_snapshot #>> '{telemetry,lastWindowSequence}')::bigint,
    (v_snapshot #>> '{outbox,lastSequence}')::bigint,
    (v_snapshot #>> '{consumer_delivery,lastAcknowledgedSequence}')::bigint,
    (v_snapshot #>> '{delivery_audit,auditGeneration}')::bigint,
    (v_snapshot #>> '{delivery_audit,auditedThroughSequence}')::bigint,
    7, v_snapshot, 'certified', v_reason, 1, v_fingerprint,
    v_details, auth.uid()
  ) returning * into v_checkpoint;

  for v_component in
    select component.key as component_key, component.value as component_payload
    from pg_catalog.jsonb_each(v_snapshot) component
  loop
    insert into public.leghevo_disaster_recovery_checkpoint_components (
      checkpoint_id, environment_key, checkpoint_generation,
      component_key, component_payload, contract_version,
      component_fingerprint
    ) values (
      v_checkpoint.id, v_environment, v_generation,
      v_component.component_key, v_component.component_payload, 1,
      public.compute_leghevo_disaster_recovery_component_fingerprint_v1(
        v_environment, v_generation, v_component.component_key,
        v_component.component_payload, 1)
    );
  end loop;

  v_event_fingerprint := public.compute_leghevo_disaster_recovery_event_fingerprint_v1(
    v_environment, 'checkpoint_created', v_generation, 0,
    v_checkpoint.id, null, v_reason, v_details);
  insert into public.leghevo_disaster_recovery_events (
    environment_key, event_type, checkpoint_generation, drill_generation,
    checkpoint_id, drill_id, reason_code, details,
    event_fingerprint, created_by
  ) values (
    v_environment, 'checkpoint_created', v_generation, 0,
    v_checkpoint.id, null, v_reason, v_details,
    v_event_fingerprint, auth.uid()
  );

  select head.* into v_head
  from public.leghevo_disaster_recovery_heads head
  where head.environment_key = v_environment
  for update;

  insert into public.leghevo_disaster_recovery_heads (
    environment_key, checkpoint_id, checkpoint_generation,
    latest_drill_id, drill_generation, status, reason_code,
    revision, state_fingerprint, updated_at, affected_at
  ) values (
    v_environment, v_checkpoint.id, v_generation,
    null, coalesce(v_head.drill_generation, 0), 'affected', 'disaster_recovery.drill_required',
    coalesce(v_head.revision, 0) + 1,
    public.leghevo_sha256_hex_v1(
      v_environment || '|' || v_generation::text || '|' ||
      coalesce(v_head.drill_generation, 0)::text || '|affected|disaster_recovery.drill_required'),
    now(), now()
  )
  on conflict (environment_key) do update set
    checkpoint_id = excluded.checkpoint_id,
    checkpoint_generation = excluded.checkpoint_generation,
    latest_drill_id = excluded.latest_drill_id,
    drill_generation = excluded.drill_generation,
    status = excluded.status,
    reason_code = excluded.reason_code,
    revision = excluded.revision,
    state_fingerprint = excluded.state_fingerprint,
    updated_at = excluded.updated_at,
    affected_at = excluded.affected_at;

  return jsonb_build_object(
    'checkpointId', v_checkpoint.id,
    'checkpointGeneration', v_generation,
    'status', v_checkpoint.status,
    'checkpointFingerprint', v_checkpoint.checkpoint_fingerprint,
    'reused', false
  );
end;
$function$;

