create or replace function public.run_leghevo_disaster_recovery_drill_v1(
  p_environment_key text,
  p_checkpoint_id bigint,
  p_request_id uuid,
  p_details jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_environment text := lower(trim(coalesce(p_environment_key, '')));
  v_details jsonb := coalesce(p_details, '{}'::jsonb);
  v_checkpoint public.leghevo_disaster_recovery_checkpoints%rowtype;
  v_existing public.leghevo_disaster_recovery_drills%rowtype;
  v_drill public.leghevo_disaster_recovery_drills%rowtype;
  v_head public.leghevo_disaster_recovery_heads%rowtype;
  v_current_snapshot jsonb;
  v_drill_generation bigint;
  v_component_mismatch_count integer := 0;
  v_sequence_regression_count integer := 0;
  v_verified_component_count integer := 0;
  v_checkpoint_fingerprint_stable boolean := false;
  v_status text;
  v_reason text;
  v_recovery_plan jsonb;
  v_drill_fingerprint text;
  v_event_fingerprint text;
  v_started_at timestamptz := now();
begin
  if v_environment not in ('production','staging') then
    raise exception 'Ambiente disaster recovery non valido.';
  end if;
  if p_checkpoint_id is null or p_request_id is null then
    raise exception 'Checkpoint ID e request ID drill obbligatori.';
  end if;
  if jsonb_typeof(v_details) <> 'object' then
    raise exception 'Details drill deve essere un oggetto JSON.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('leghevo:disaster-recovery:' || v_environment, 0));

  select drill.* into v_existing
  from public.leghevo_disaster_recovery_drills drill
  where drill.request_id = p_request_id;
  if found then
    if v_existing.environment_key <> v_environment
      or v_existing.checkpoint_id <> p_checkpoint_id then
      raise exception 'Request ID drill già usato con parametri differenti.';
    end if;
    return jsonb_build_object(
      'drillId', v_existing.id,
      'drillGeneration', v_existing.drill_generation,
      'status', v_existing.status,
      'reused', true
    );
  end if;

  select checkpoint.* into v_checkpoint
  from public.leghevo_disaster_recovery_checkpoints checkpoint
  where checkpoint.id = p_checkpoint_id
    and checkpoint.environment_key = v_environment
  for share;
  if not found then
    raise exception 'Checkpoint disaster recovery non trovato.';
  end if;

  v_checkpoint_fingerprint_stable :=
    v_checkpoint.checkpoint_fingerprint =
      public.compute_leghevo_disaster_recovery_checkpoint_fingerprint_v1(
        v_checkpoint.environment_key, v_checkpoint.checkpoint_generation,
        v_checkpoint.snapshot_payload, v_checkpoint.status,
        v_checkpoint.contract_version);

  select count(*) into v_verified_component_count
  from public.leghevo_disaster_recovery_checkpoint_components component
  where component.checkpoint_id = v_checkpoint.id;

  select count(*) into v_component_mismatch_count
  from public.leghevo_disaster_recovery_checkpoint_components component
  where component.checkpoint_id = v_checkpoint.id
    and component.component_fingerprint <>
      public.compute_leghevo_disaster_recovery_component_fingerprint_v1(
        component.environment_key, component.checkpoint_generation,
        component.component_key, component.component_payload,
        component.contract_version);

  v_current_snapshot := public.get_leghevo_disaster_recovery_snapshot_v1(v_environment);

  select count(*) + v_component_mismatch_count into v_component_mismatch_count
  from (
    select stored_component.component_key
    from public.leghevo_disaster_recovery_checkpoint_components stored_component
    left join pg_catalog.jsonb_each(v_current_snapshot) current_component
      on current_component.key = stored_component.component_key
    where stored_component.checkpoint_id = v_checkpoint.id
      and current_component.value is distinct from stored_component.component_payload
  ) mismatched_component;

  v_sequence_regression_count :=
    case when (v_current_snapshot #>> '{outbox,lastSequence}')::bigint
      < v_checkpoint.outbox_last_sequence then 1 else 0 end
    + case when (v_current_snapshot #>> '{consumer_delivery,lastAcknowledgedSequence}')::bigint
      < v_checkpoint.consumer_last_sequence then 1 else 0 end
    + case when (v_current_snapshot #>> '{delivery_audit,auditedThroughSequence}')::bigint
      < v_checkpoint.audited_through_sequence then 1 else 0 end;

  if v_current_snapshot #>> '{release,activeVersion}' is distinct from v_checkpoint.active_release_version
    or (v_current_snapshot #>> '{release,releaseGeneration}')::bigint <> v_checkpoint.release_generation
    or (v_current_snapshot #>> '{rollout,rolloutGeneration}')::bigint <> v_checkpoint.rollout_generation
    or (v_current_snapshot #>> '{rollout,exposurePercentage}')::integer <> v_checkpoint.exposure_percentage
    or (v_current_snapshot #>> '{telemetry,telemetryGeneration}')::bigint <> v_checkpoint.telemetry_generation then
    v_component_mismatch_count := v_component_mismatch_count + 1;
  end if;

  v_status := case
    when v_checkpoint_fingerprint_stable
      and v_verified_component_count = 7
      and v_component_mismatch_count = 0
      and v_sequence_regression_count = 0 then 'passed'
    else 'failed'
  end;
  v_reason := case
    when not v_checkpoint_fingerprint_stable then 'disaster_recovery.checkpoint_fingerprint_changed'
    when v_verified_component_count <> 7 then 'disaster_recovery.component_set_incomplete'
    when v_component_mismatch_count > 0 then 'disaster_recovery.component_mismatch'
    when v_sequence_regression_count > 0 then 'disaster_recovery.sequence_regression'
    else 'disaster_recovery.drill_passed'
  end;

  select coalesce(max(drill.drill_generation), 0) + 1 into v_drill_generation
  from public.leghevo_disaster_recovery_drills drill
  where drill.environment_key = v_environment;

  v_recovery_plan := jsonb_build_object(
    'environment', v_environment,
    'checkpointId', v_checkpoint.id,
    'checkpointGeneration', v_checkpoint.checkpoint_generation,
    'activeReleaseVersion', v_checkpoint.active_release_version,
    'releaseGeneration', v_checkpoint.release_generation,
    'rolloutGeneration', v_checkpoint.rollout_generation,
    'exposurePercentage', v_checkpoint.exposure_percentage,
    'telemetryGeneration', v_checkpoint.telemetry_generation,
    'resumeTelemetryWindowSequence', v_checkpoint.telemetry_window_sequence + 1,
    'resumeOutboxAfterSequence', v_checkpoint.outbox_last_sequence,
    'resumeConsumerAfterSequence', v_checkpoint.consumer_last_sequence,
    'auditedThroughSequence', v_checkpoint.audited_through_sequence,
    'requiredActions', jsonb_build_array(
      'verify_database_backup_reference',
      'restore_schema_and_data_to_isolated_target',
      'recompute_fingerprints',
      'resume_workers_with_new_fencing_generation',
      'run_delivery_audit_before_traffic'
    )
  );

  v_drill_fingerprint := public.compute_leghevo_disaster_recovery_drill_fingerprint_v1(
    v_checkpoint.id, v_environment, v_drill_generation, v_status,
    v_verified_component_count, v_component_mismatch_count,
    v_sequence_regression_count, v_recovery_plan, 1);

  perform pg_catalog.set_config('leghevo.disaster_recovery_context','allowed',true);
  insert into public.leghevo_disaster_recovery_drills (
    checkpoint_id, environment_key, drill_generation, request_id,
    status, reason_code, verified_component_count,
    component_mismatch_count, sequence_regression_count,
    recovery_plan, contract_version, drill_fingerprint,
    details, started_at, completed_at, created_by
  ) values (
    v_checkpoint.id, v_environment, v_drill_generation, p_request_id,
    v_status, v_reason, v_verified_component_count,
    v_component_mismatch_count, v_sequence_regression_count,
    v_recovery_plan, 1, v_drill_fingerprint,
    v_details, v_started_at, now(), auth.uid()
  ) returning * into v_drill;

  select head.* into v_head
  from public.leghevo_disaster_recovery_heads head
  where head.environment_key = v_environment
  for update;

  insert into public.leghevo_disaster_recovery_heads (
    environment_key, checkpoint_id, checkpoint_generation,
    latest_drill_id, drill_generation, status, reason_code,
    revision, state_fingerprint, updated_at, affected_at
  ) values (
    v_environment, v_checkpoint.id, v_checkpoint.checkpoint_generation,
    v_drill.id, v_drill_generation,
    case when v_status = 'passed' and coalesce(v_head.status, '') = 'affected'
      and v_head.latest_drill_id is not null then 'revalidated'
      when v_status = 'passed' then 'certified'
      else 'affected' end,
    v_reason, coalesce(v_head.revision, 0) + 1,
    public.leghevo_sha256_hex_v1(
      v_environment || '|' || v_checkpoint.checkpoint_generation::text || '|' ||
      v_drill_generation::text || '|' || v_status || '|' || v_reason),
    now(), case when v_status = 'failed' then now() else null end
  )
  on conflict (environment_key) do update set
    checkpoint_id = excluded.checkpoint_id,
    checkpoint_generation = excluded.checkpoint_generation,
    latest_drill_id = excluded.latest_drill_id,
    drill_generation = excluded.drill_generation,
    status = excluded.status,
    reason_code = excluded.reason_code,
    revision = excluded.revision,
    state_fingerprint = excluded.state_fingerprint,
    updated_at = excluded.updated_at,
    affected_at = excluded.affected_at;

  v_event_fingerprint := public.compute_leghevo_disaster_recovery_event_fingerprint_v1(
    v_environment,
    case when v_status = 'passed' then 'drill_passed' else 'drill_failed' end,
    v_checkpoint.checkpoint_generation, v_drill_generation,
    v_checkpoint.id, v_drill.id, v_reason, v_details);
  insert into public.leghevo_disaster_recovery_events (
    environment_key, event_type, checkpoint_generation, drill_generation,
    checkpoint_id, drill_id, reason_code, details,
    event_fingerprint, created_by
  ) values (
    v_environment,
    case when v_status = 'passed' then 'drill_passed' else 'drill_failed' end,
    v_checkpoint.checkpoint_generation, v_drill_generation,
    v_checkpoint.id, v_drill.id, v_reason, v_details,
    v_event_fingerprint, auth.uid()
  );

  return jsonb_build_object(
    'drillId', v_drill.id,
    'drillGeneration', v_drill_generation,
    'status', v_status,
    'reasonCode', v_reason,
    'verifiedComponentCount', v_verified_component_count,
    'componentMismatchCount', v_component_mismatch_count,
    'sequenceRegressionCount', v_sequence_regression_count,
    'recoveryPlan', v_recovery_plan,
    'reused', false
  );
end;
$function$;

