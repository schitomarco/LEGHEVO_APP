  p_calendar_fingerprint text,
  p_opening_matchday_id uuid,
  p_opening_matchday_number smallint,
  p_fantasy_fixture_count integer,
  p_fantasy_matchday_count integer,
  p_fantasy_team_count integer,
  p_competition_started_at timestamptz
