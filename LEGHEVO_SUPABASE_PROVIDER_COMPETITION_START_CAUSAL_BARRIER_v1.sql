create table if not exists public.provider_competition_start_certificates (
  id bigint generated by default as identity primary key,
  league_id uuid not null unique
    references public.leagues(id) on delete restrict,
  bootstrap_certificate_id bigint not null
    references public.provider_season_bootstrap_certificates(id) on delete restrict,
  provider text not null,
  competition_code text not null,
  season integer not null,
  bootstrap_hash text not null,
  provider_fixture_fingerprint text not null,
  calendar_fingerprint text not null,
  opening_matchday_id uuid not null
    references public.matchdays(id) on delete restrict,
  opening_matchday_number smallint not null,
  fantasy_fixture_count integer not null,
  fantasy_matchday_count integer not null,
  fantasy_team_count integer not null,
  competition_started_at timestamptz not null,
  start_hash text not null,
  certified_by uuid references public.profiles(id) on delete set null,
  certified_at timestamptz not null default now(),
  result_payload jsonb not null default '{}'::jsonb,
  constraint provider_competition_start_cert_provider_check
    check(char_length(trim(provider)) between 1 and 100 and provider !~ E'[\r\n]'),
  constraint provider_competition_start_cert_competition_check
    check(competition_code = 'IT-SA'),
  constraint provider_competition_start_cert_season_check
    check(season between 2000 and 2200),
  constraint provider_competition_start_cert_bootstrap_hash_check
    check(bootstrap_hash ~ '^[0-9a-f]{32}$'),
  constraint provider_competition_start_cert_provider_hash_check
    check(provider_fixture_fingerprint ~ '^[0-9a-f]{32}$'),
  constraint provider_competition_start_cert_calendar_hash_check
    check(calendar_fingerprint ~ '^[0-9a-f]{32}$'),
  constraint provider_competition_start_cert_start_hash_check
    check(start_hash ~ '^[0-9a-f]{32}$'),
  constraint provider_competition_start_cert_matchday_check
    check(opening_matchday_number > 0),
  constraint provider_competition_start_cert_counts_check
    check(fantasy_fixture_count > 0 and fantasy_matchday_count > 0
      and fantasy_team_count >= 2),
  constraint provider_competition_start_cert_payload_check
    check(jsonb_typeof(result_payload) = 'object')
);

