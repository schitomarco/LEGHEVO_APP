    calendar_fingerprint, opening_matchday_id, opening_matchday_number,
    fantasy_fixture_count, fantasy_matchday_count, fantasy_team_count,
    competition_started_at, start_hash, certified_by, result_payload
  ) values(
    v_certificate_id,
    p_league_id,
    v_bootstrap_certificate.id,
    v_bootstrap_certificate.provider,
    v_bootstrap_certificate.competition_code,
    v_bootstrap_certificate.season,
    v_bootstrap_certificate.bootstrap_hash,
    v_bootstrap_certificate.fixture_fingerprint,
    v_gate ->> 'calendarFingerprint',
    (v_gate ->> 'openingMatchdayId')::uuid,
    (v_gate ->> 'openingMatchdayNumber')::smallint,
    (v_gate ->> 'fantasyFixtureCount')::integer,
    (v_gate ->> 'fantasyMatchdayCount')::integer,
    (v_gate ->> 'fantasyTeamCount')::integer,
