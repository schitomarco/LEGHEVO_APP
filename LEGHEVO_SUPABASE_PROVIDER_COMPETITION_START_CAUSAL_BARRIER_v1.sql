  v_bootstrap := public.reconcile_provider_season_bootstrap_v1(p_league_id, true);
  if coalesce((v_bootstrap ->> 'applicable')::boolean, false)
    and (
      coalesce(v_bootstrap ->> 'status', 'waiting') <> 'ready'
      or not coalesce((v_bootstrap ->> 'certified')::boolean, false)
      or coalesce((v_bootstrap ->> 'affected')::boolean, false)
    ) then
