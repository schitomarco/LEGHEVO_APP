create or replace function public.start_league_competition_guarded_v4(
  p_league_id uuid
)
returns jsonb language plpgsql security definer set search_path = '' as $function$
declare
  v_bootstrap jsonb;
  v_gate jsonb;
  v_base jsonb;
  v_certification jsonb;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;
  if not public.is_league_admin(p_league_id) then
    raise exception 'Solo la Direzione può avviare la competizione.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
    'league-season-rollover-lineage:' || p_league_id::text, 0));
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
    'provider-new-season-bootstrap:' || p_league_id::text, 0));
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
