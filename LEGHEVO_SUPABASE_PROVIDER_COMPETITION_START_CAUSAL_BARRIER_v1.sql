    reason_code = 'provider_competition_start.certified',
    observed_season = excluded.observed_season,
    observed_bootstrap_certificate_id = excluded.observed_bootstrap_certificate_id,
    observed_bootstrap_hash = excluded.observed_bootstrap_hash,
    observed_provider_fixture_fingerprint = excluded.observed_provider_fixture_fingerprint,
