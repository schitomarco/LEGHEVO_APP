create or replace function public.compute_provider_competition_start_gate_v1(
  p_league_id uuid,
  p_ignore_missing_certificate boolean default false
)
returns jsonb language plpgsql stable security definer set search_path = '' as $function$
declare
  v_league public.leagues%rowtype;
  v_bootstrap jsonb;
  v_bootstrap_certificate public.provider_season_bootstrap_certificates%rowtype;
  v_certificate public.provider_competition_start_certificates%rowtype;
  v_fixture_count integer := 0;
  v_matchday_count integer := 0;
  v_team_count integer := 0;
  v_scope_issue_count integer := 0;
  v_opening_matchday_id uuid;
  v_opening_matchday_number smallint;
  v_opening_matchday_valid boolean := false;
  v_calendar_fingerprint text;
  v_status text := 'waiting';
  v_reason text := 'provider_competition_start.waiting';
  v_applicable boolean := false;
  v_bootstrap_ready boolean := false;
  v_calendar_ready boolean := false;
  v_model_ready boolean := false;
  v_started boolean := false;
  v_healthy boolean := true;
  v_affected boolean := false;
  v_expected_hash text;
begin
  select league.* into v_league
  from public.leagues league
  where league.id = p_league_id;

  if not found then
    return jsonb_build_object(
      'available', false,
      'applicable', false,
      'protected', true,
      'healthy', false,
      'affected', true,
      'status', 'affected',
      'reasonCode', 'provider_competition_start.league_missing'
    );
  end if;

  v_started := v_league.competition_started_at is not null;
  v_bootstrap := public.compute_provider_season_bootstrap_gate_v1(p_league_id);
  v_applicable := coalesce((v_bootstrap ->> 'applicable')::boolean, false);

  if not v_applicable then
    return jsonb_build_object(
      'available', true,
      'applicable', false,
      'protected', true,
      'healthy', true,
      'affected', false,
      'status', case when v_started then 'official' else 'ready' end,
      'reasonCode', 'provider_competition_start.not_required',
      'started', v_started,
      'certified', false,
      'certificateId', null,
      'bootstrap', v_bootstrap
    );
  end if;

  select certificate.* into v_bootstrap_certificate
  from public.provider_season_bootstrap_certificates certificate
  where certificate.league_id = p_league_id;

  select certificate.* into v_certificate
  from public.provider_competition_start_certificates certificate
  where certificate.league_id = p_league_id;

  select
    count(*)::integer,
    count(distinct fixture.matchday_id)::integer
  into v_fixture_count, v_matchday_count
  from public.fantasy_fixtures fixture
  where fixture.league_id = p_league_id;

  select count(*)::integer into v_team_count
  from public.fantasy_teams team
  where team.league_id = p_league_id;

  select count(*)::integer into v_scope_issue_count
  from public.fantasy_fixtures fixture
  join public.matchdays matchday on matchday.id = fixture.matchday_id
  where fixture.league_id = p_league_id
    and (
      matchday.competition_code <> 'IT-SA'
      or matchday.season is distinct from v_league.calendar_season
    );

  if v_started then
    select event.matchday_id,
      nullif(event.payload ->> 'matchdayNumber', '')::smallint
    into v_opening_matchday_id, v_opening_matchday_number
    from public.league_competition_events event
    where event.league_id = p_league_id
      and event.dedupe_key = 'competition-opening:v1'
    limit 1;
  end if;

  if v_opening_matchday_id is null then
    select matchday.id, matchday.number
    into v_opening_matchday_id, v_opening_matchday_number
    from public.fantasy_fixtures fixture
    join public.matchdays matchday on matchday.id = fixture.matchday_id
    where fixture.league_id = p_league_id
    group by matchday.id, matchday.number, matchday.starts_at
    order by matchday.number, matchday.starts_at, matchday.id
    limit 1;
  end if;

  v_opening_matchday_valid := v_opening_matchday_id is not null
    and exists(
      select 1
      from public.fantasy_fixtures fixture
      join public.matchdays matchday on matchday.id = fixture.matchday_id
      where fixture.league_id = p_league_id
        and fixture.matchday_id = v_opening_matchday_id
        and matchday.number = v_opening_matchday_number
        and matchday.competition_code = 'IT-SA'
        and matchday.season = v_league.calendar_season
    );

  v_calendar_fingerprint := public.compute_league_calendar_fingerprint(p_league_id);
  v_bootstrap_ready := coalesce((v_bootstrap ->> 'certified')::boolean, false)
    and coalesce(v_bootstrap ->> 'status', 'waiting') = 'ready'
    and coalesce((v_bootstrap ->> 'healthy')::boolean, false)
    and not coalesce((v_bootstrap ->> 'affected')::boolean, false)
    and v_bootstrap_certificate.id is not null
    and v_bootstrap_certificate.bootstrap_hash = v_bootstrap ->> 'bootstrapHash';

  v_model_ready := not v_started or (
    v_league.competition_model_closed_at is not null
    and v_league.competition_opening_verified_at is not null
    and v_league.competition_calendar_fingerprint = v_calendar_fingerprint
  );

  v_calendar_ready := v_fixture_count > 0
    and v_matchday_count > 0
    and v_team_count >= 2
    and v_scope_issue_count = 0
    and v_opening_matchday_valid
    and v_calendar_fingerprint ~ '^[0-9a-f]{32}$'
    and coalesce(v_league.calendar_expected_fixture_count, v_fixture_count) = v_fixture_count
    and coalesce(v_league.calendar_expected_matchday_count, v_matchday_count) = v_matchday_count
    and (
      v_league.competition_calendar_fingerprint is null
      or v_league.competition_calendar_fingerprint = v_calendar_fingerprint
    )
    and v_model_ready;

  if not v_bootstrap_ready then
    v_status := case
      when coalesce((v_bootstrap ->> 'affected')::boolean, false)
        then 'affected'
      else 'waiting'
    end;
    v_reason := case
      when coalesce((v_bootstrap ->> 'affected')::boolean, false)
        then 'provider_competition_start.bootstrap_affected'
      else 'provider_competition_start.bootstrap_not_ready'
    end;
  elsif not v_calendar_ready then
    v_status := case when v_started then 'affected' else 'waiting' end;
    v_reason := case
      when v_scope_issue_count > 0
        then 'provider_competition_start.calendar_scope_mismatch'
      when not v_opening_matchday_valid
        then 'provider_competition_start.opening_matchday_invalid'
      when not v_model_ready
        then 'provider_competition_start.competition_model_not_closed'
      when v_league.competition_calendar_fingerprint is not null
        and v_league.competition_calendar_fingerprint <> v_calendar_fingerprint
        then 'provider_competition_start.calendar_fingerprint_changed'
      else 'provider_competition_start.calendar_not_ready'
    end;
  elsif not v_started then
    v_status := 'ready';
    v_reason := 'provider_competition_start.ready';
  elsif v_certificate.id is null then
    if p_ignore_missing_certificate then
      v_status := 'ready';
      v_reason := 'provider_competition_start.historical_start_adoptable';
    else
      v_status := 'affected';
      v_reason := 'provider_competition_start.certificate_missing';
    end if;
  else
    v_expected_hash := public.compute_provider_competition_start_hash_v1(
      p_league_id,
      v_certificate.bootstrap_certificate_id,
      v_certificate.bootstrap_hash,
      v_certificate.provider_fixture_fingerprint,
      v_certificate.calendar_fingerprint,
      v_certificate.opening_matchday_id,
      v_certificate.opening_matchday_number,
      v_certificate.fantasy_fixture_count,
      v_certificate.fantasy_matchday_count,
      v_certificate.fantasy_team_count,
      v_certificate.competition_started_at
    );

    if v_certificate.start_hash <> v_expected_hash then
      v_status := 'affected';
      v_reason := 'provider_competition_start.certificate_hash_invalid';
    elsif v_certificate.bootstrap_certificate_id <> v_bootstrap_certificate.id
      or v_certificate.bootstrap_hash <> v_bootstrap_certificate.bootstrap_hash then
      v_status := 'affected';
      v_reason := 'provider_competition_start.bootstrap_lineage_changed';
    elsif v_certificate.provider_fixture_fingerprint
      <> v_bootstrap_certificate.fixture_fingerprint then
      v_status := 'affected';
      v_reason := 'provider_competition_start.provider_scope_changed';
    elsif v_certificate.calendar_fingerprint <> v_calendar_fingerprint then
      v_status := 'affected';
      v_reason := 'provider_competition_start.calendar_fingerprint_changed';
    elsif v_certificate.opening_matchday_id <> v_opening_matchday_id
      or v_certificate.opening_matchday_number <> v_opening_matchday_number then
      v_status := 'affected';
      v_reason := 'provider_competition_start.opening_matchday_changed';
    elsif v_certificate.fantasy_fixture_count <> v_fixture_count
      or v_certificate.fantasy_matchday_count <> v_matchday_count
      or v_certificate.fantasy_team_count <> v_team_count then
      v_status := 'affected';
      v_reason := 'provider_competition_start.competition_structure_changed';
    elsif v_certificate.competition_started_at <> v_league.competition_started_at then
      v_status := 'affected';
      v_reason := 'provider_competition_start.started_at_changed';
    else
      v_status := 'official';
      v_reason := 'provider_competition_start.certified';
    end if;
  end if;

  v_affected := v_status = 'affected';
  v_healthy := not v_affected;

  return jsonb_build_object(
    'available', true,
    'applicable', true,
    'protected', true,
    'healthy', v_healthy,
    'affected', v_affected,
    'status', v_status,
    'reasonCode', v_reason,
    'started', v_started,
    'certified', v_certificate.id is not null and v_status = 'official',
    'certificateId', v_certificate.id,
    'startHash', v_certificate.start_hash,
    'season', case when coalesce(v_league.calendar_season, '') ~ '^[0-9]{4}$'
      then v_league.calendar_season::integer else null end,
    'bootstrapCertificateId', v_bootstrap_certificate.id,
    'bootstrapHash', v_bootstrap_certificate.bootstrap_hash,
    'provider', v_bootstrap_certificate.provider,
    'providerFixtureFingerprint', v_bootstrap_certificate.fixture_fingerprint,
    'calendarFingerprint', v_calendar_fingerprint,
    'openingMatchdayId', v_opening_matchday_id,
    'openingMatchdayNumber', v_opening_matchday_number,
    'fantasyFixtureCount', v_fixture_count,
    'fantasyMatchdayCount', v_matchday_count,
    'fantasyTeamCount', v_team_count,
    'calendarScopeIssueCount', v_scope_issue_count,
    'openingMatchdayValid', v_opening_matchday_valid,
    'bootstrapReady', v_bootstrap_ready,
    'calendarReady', v_calendar_ready,
    'competitionModelReady', v_model_ready,
    'competitionStartedAt', v_league.competition_started_at,
    'bootstrap', v_bootstrap
  );
