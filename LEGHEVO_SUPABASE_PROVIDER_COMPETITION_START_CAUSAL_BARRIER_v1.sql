      v_bootstrap ->> 'reasonCode';
  end if;

  v_gate := public.compute_provider_competition_start_gate_v1(p_league_id, false);
  if coalesce((v_gate ->> 'applicable')::boolean, false)
    and coalesce(v_gate ->> 'status', 'waiting') not in ('ready','official') then
    raise exception 'Avvio competizione non pronto [%].', v_gate ->> 'reasonCode';
  end if;

  perform set_config('leghevo.provider_competition_start_context', 'on', true);
  v_base := public.start_league_competition_guarded_v3(p_league_id);

  if coalesce((v_gate ->> 'applicable')::boolean, false) then
    v_certification := public.certify_provider_competition_start_v1(p_league_id);
  else
    v_certification := public.compute_provider_competition_start_gate_v1(
      p_league_id, false);
  end if;
  perform set_config('leghevo.provider_competition_start_context', '', true);

  return v_base || jsonb_build_object(
    'providerCompetitionStartProtected', true,
    'providerCompetitionStartApplicable',
