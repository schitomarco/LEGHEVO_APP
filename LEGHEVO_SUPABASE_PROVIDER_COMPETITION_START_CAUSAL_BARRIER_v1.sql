    p_league_id::text,
    p_bootstrap_certificate_id::text,
    p_bootstrap_hash,
    p_provider_fixture_fingerprint,
    p_calendar_fingerprint,
    p_opening_matchday_id::text,
    p_opening_matchday_number::text,
    p_fantasy_fixture_count::text,
    p_fantasy_matchday_count::text,
    p_fantasy_team_count::text,
    to_char(p_competition_started_at at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US')
  ));
$function$;
