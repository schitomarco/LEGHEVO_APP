    v_bootstrap_certificate.id,
    v_bootstrap_certificate.bootstrap_hash,
    v_bootstrap_certificate.fixture_fingerprint,
    v_gate ->> 'calendarFingerprint',
    (v_gate ->> 'openingMatchdayId')::uuid,
    (v_gate ->> 'openingMatchdayNumber')::smallint,
    (v_gate ->> 'fantasyFixtureCount')::integer,
    (v_gate ->> 'fantasyMatchdayCount')::integer,
    (v_gate ->> 'fantasyTeamCount')::integer,
