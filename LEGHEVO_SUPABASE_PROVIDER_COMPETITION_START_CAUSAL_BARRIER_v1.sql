create or replace function public.reconcile_provider_competition_start_v1(
  p_league_id uuid,
  p_auto_certify boolean default true
)
returns jsonb language plpgsql security definer set search_path = '' as $function$
declare
  v_gate jsonb;
  v_head public.provider_competition_start_heads%rowtype;
  v_status text;
  v_reason text;
  v_certificate_id bigint;
  v_event_type text;
  v_changed boolean := true;
  v_ever_affected boolean;
  v_first_affected_at timestamptz;
  v_candidate jsonb;
begin
  if p_auto_certify then
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
      'league-season-rollover-lineage:' || p_league_id::text, 0));
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
      'provider-new-season-bootstrap:' || p_league_id::text, 0));
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
      'competition:' || p_league_id::text, 0));
  end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
    'provider-competition-start:' || p_league_id::text, 0));

  v_gate := public.compute_provider_competition_start_gate_v1(p_league_id, false);
  if not coalesce((v_gate ->> 'applicable')::boolean, false) then
    return v_gate;
  end if;

  if p_auto_certify
    and coalesce((v_gate ->> 'started')::boolean, false)
    and nullif(v_gate ->> 'certificateId', '') is null then
    v_candidate := public.compute_provider_competition_start_gate_v1(
      p_league_id, true);
    if coalesce(v_candidate ->> 'status', 'waiting') = 'ready' then
      return public.certify_provider_competition_start_v1(p_league_id);
    end if;
  end if;

  v_status := coalesce(v_gate ->> 'status', 'waiting');
  v_reason := coalesce(v_gate ->> 'reasonCode',
    'provider_competition_start.waiting');
  v_certificate_id := nullif(v_gate ->> 'certificateId', '')::bigint;

  select head.* into v_head
  from public.provider_competition_start_heads head
  where head.league_id = p_league_id
  for update;

  if found then
    v_changed := v_head.start_status is distinct from v_status
      or v_head.reason_code is distinct from v_reason
      or v_head.certificate_id is distinct from v_certificate_id
      or v_head.observed_bootstrap_certificate_id is distinct from
        nullif(v_gate ->> 'bootstrapCertificateId', '')::bigint
      or v_head.observed_bootstrap_hash is distinct from v_gate ->> 'bootstrapHash'
      or v_head.observed_provider_fixture_fingerprint is distinct from
        v_gate ->> 'providerFixtureFingerprint'
      or v_head.observed_calendar_fingerprint is distinct from
        v_gate ->> 'calendarFingerprint'
      or v_head.observed_opening_matchday_id is distinct from
        nullif(v_gate ->> 'openingMatchdayId', '')::uuid
      or v_head.observed_opening_matchday_number is distinct from
        nullif(v_gate ->> 'openingMatchdayNumber', '')::smallint
      or v_head.observed_fantasy_fixture_count is distinct from
        coalesce((v_gate ->> 'fantasyFixtureCount')::integer, 0)
      or v_head.observed_fantasy_matchday_count is distinct from
        coalesce((v_gate ->> 'fantasyMatchdayCount')::integer, 0)
      or v_head.observed_fantasy_team_count is distinct from
        coalesce((v_gate ->> 'fantasyTeamCount')::integer, 0);
  end if;

  if not v_changed then
    return v_gate || jsonb_build_object(
      'everAffected', v_head.ever_affected,
      'firstAffectedAt', v_head.first_affected_at
    );
  end if;

  v_ever_affected := coalesce(v_head.ever_affected, false)
    or v_status = 'affected';
  v_first_affected_at := case
    when coalesce(v_head.ever_affected, false) then v_head.first_affected_at
    when v_status = 'affected' then now()
    else null
  end;

  v_event_type := case
    when v_status = 'affected' then 'affected'
    when coalesce(v_head.start_status, '') = 'affected'
      and v_status in ('ready','official') then 'revalidated'
    when v_status = 'official' then 'certified'
    when v_status = 'ready' then 'ready'
    else 'waiting'
  end;

  perform set_config('leghevo.provider_competition_start_context', 'on', true);
  insert into public.provider_competition_start_heads(
    league_id, certificate_id, start_status, reason_code,
    observed_season, observed_bootstrap_certificate_id,
    observed_bootstrap_hash, observed_provider_fixture_fingerprint,
    observed_calendar_fingerprint, observed_opening_matchday_id,
    observed_opening_matchday_number, observed_fantasy_fixture_count,
    observed_fantasy_matchday_count, observed_fantasy_team_count,
    ever_affected, first_affected_at, last_assessed_at, updated_at
  ) values(
    p_league_id, v_certificate_id, v_status, v_reason,
    nullif(v_gate ->> 'season', '')::integer,
    nullif(v_gate ->> 'bootstrapCertificateId', '')::bigint,
    v_gate ->> 'bootstrapHash',
    v_gate ->> 'providerFixtureFingerprint',
    v_gate ->> 'calendarFingerprint',
    nullif(v_gate ->> 'openingMatchdayId', '')::uuid,
    nullif(v_gate ->> 'openingMatchdayNumber', '')::smallint,
    coalesce((v_gate ->> 'fantasyFixtureCount')::integer, 0),
    coalesce((v_gate ->> 'fantasyMatchdayCount')::integer, 0),
    coalesce((v_gate ->> 'fantasyTeamCount')::integer, 0),
    v_ever_affected, v_first_affected_at, now(), now()
  ) on conflict(league_id) do update set
    certificate_id = excluded.certificate_id,
    start_status = excluded.start_status,
    reason_code = excluded.reason_code,
    observed_season = excluded.observed_season,
    observed_bootstrap_certificate_id = excluded.observed_bootstrap_certificate_id,
    observed_bootstrap_hash = excluded.observed_bootstrap_hash,
    observed_provider_fixture_fingerprint = excluded.observed_provider_fixture_fingerprint,
    observed_calendar_fingerprint = excluded.observed_calendar_fingerprint,
    observed_opening_matchday_id = excluded.observed_opening_matchday_id,
    observed_opening_matchday_number = excluded.observed_opening_matchday_number,
    observed_fantasy_fixture_count = excluded.observed_fantasy_fixture_count,
    observed_fantasy_matchday_count = excluded.observed_fantasy_matchday_count,
    observed_fantasy_team_count = excluded.observed_fantasy_team_count,
    ever_affected = excluded.ever_affected,
    first_affected_at = excluded.first_affected_at,
    last_assessed_at = now(),
    updated_at = now();

  insert into public.provider_competition_start_events(
    league_id, certificate_id, event_type, start_status, reason_code,
    observed_season, observed_bootstrap_certificate_id,
    observed_bootstrap_hash, observed_provider_fixture_fingerprint,
    observed_calendar_fingerprint, observed_opening_matchday_id,
    observed_opening_matchday_number, observed_fantasy_fixture_count,
    observed_fantasy_matchday_count, observed_fantasy_team_count,
    event_payload
  ) values(
    p_league_id, v_certificate_id, v_event_type, v_status, v_reason,
    nullif(v_gate ->> 'season', '')::integer,
    nullif(v_gate ->> 'bootstrapCertificateId', '')::bigint,
    v_gate ->> 'bootstrapHash',
    v_gate ->> 'providerFixtureFingerprint',
    v_gate ->> 'calendarFingerprint',
    nullif(v_gate ->> 'openingMatchdayId', '')::uuid,
    nullif(v_gate ->> 'openingMatchdayNumber', '')::smallint,
    coalesce((v_gate ->> 'fantasyFixtureCount')::integer, 0),
    coalesce((v_gate ->> 'fantasyMatchdayCount')::integer, 0),
    coalesce((v_gate ->> 'fantasyTeamCount')::integer, 0),
    jsonb_build_object('assessment', v_gate,
      'everAffected', v_ever_affected,
      'firstAffectedAt', v_first_affected_at)
  );
  perform set_config('leghevo.provider_competition_start_context', '', true);

  return v_gate || jsonb_build_object(
    'everAffected', v_ever_affected,
    'firstAffectedAt', v_first_affected_at
  );
end;
