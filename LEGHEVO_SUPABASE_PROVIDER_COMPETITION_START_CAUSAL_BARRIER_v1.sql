  observed_bootstrap_hash text,
  observed_provider_fixture_fingerprint text,
  observed_calendar_fingerprint text,
  observed_opening_matchday_id uuid,
  observed_opening_matchday_number smallint,
  observed_fantasy_fixture_count integer not null default 0,
  observed_fantasy_matchday_count integer not null default 0,
  observed_fantasy_team_count integer not null default 0,
  ever_affected boolean not null default false,
  first_affected_at timestamptz,
  last_assessed_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint provider_competition_start_heads_status_check
    check(start_status in ('waiting','ready','official','affected')),
  constraint provider_competition_start_heads_reason_check
    check(char_length(trim(reason_code)) between 3 and 180),
  constraint provider_competition_start_heads_season_check
    check(observed_season is null or observed_season between 2000 and 2200),
  constraint provider_competition_start_heads_bootstrap_hash_check
    check(observed_bootstrap_hash is null
      or observed_bootstrap_hash ~ '^[0-9a-f]{32}$'),
  constraint provider_competition_start_heads_provider_hash_check
    check(observed_provider_fixture_fingerprint is null
      or observed_provider_fixture_fingerprint ~ '^[0-9a-f]{32}$'),
  constraint provider_competition_start_heads_calendar_hash_check
    check(observed_calendar_fingerprint is null
      or observed_calendar_fingerprint ~ '^[0-9a-f]{32}$'),
  constraint provider_competition_start_heads_matchday_check
    check(observed_opening_matchday_number is null
      or observed_opening_matchday_number > 0),
  constraint provider_competition_start_heads_counts_check
    check(observed_fantasy_fixture_count >= 0
      and observed_fantasy_matchday_count >= 0
      and observed_fantasy_team_count >= 0),
  constraint provider_competition_start_heads_affected_check
    check((not ever_affected and first_affected_at is null)
      or (ever_affected and first_affected_at is not null)),
  constraint provider_competition_start_heads_state_check
    check(
      (start_status in ('waiting','ready') and certificate_id is null)
      or (start_status = 'official' and certificate_id is not null)
      or (start_status = 'affected')
    )
