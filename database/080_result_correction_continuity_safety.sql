create table if not exists public.result_correction_runs (
  id bigint generated by default as identity primary key,
  league_id uuid not null
    references public.leagues(id) on delete cascade,
  matchday_id uuid not null
    references public.matchdays(id) on delete cascade,
  fixture_id uuid
    references public.fantasy_fixtures(id) on delete cascade,
  request_id uuid not null unique,
  scope text not null,
  correction_revision integer not null,
  input_hash text not null,
  reason text not null,
  previous_officialization_id bigint
    references public.matchday_officialization_runs(id) on delete set null,
  affected_fixture_count integer not null,
  previous_official_fixture_count integer not null,
  result_payload jsonb not null default '{}'::jsonb,
  requested_by uuid references public.profiles(id) on delete set null,
  reopened_at timestamptz not null default now(),
  constraint result_correction_scope_check
    check (scope in ('fixture', 'matchday')),
  constraint result_correction_scope_fixture_check
    check (
      (scope = 'fixture' and fixture_id is not null)
      or (scope = 'matchday' and fixture_id is null)
    ),
  constraint result_correction_revision_check
    check (correction_revision >= 1),
  constraint result_correction_input_hash_check
    check (length(input_hash) = 32),
  constraint result_correction_reason_check
    check (char_length(trim(reason)) between 10 and 240),
  constraint result_correction_affected_check
    check (affected_fixture_count >= 1),
  constraint result_correction_previous_count_check
    check (previous_official_fixture_count >= affected_fixture_count),
  unique (matchday_id, correction_revision)
);

create index if not exists result_correction_league_matchday_idx
  on public.result_correction_runs (
    league_id,
    matchday_id,
    correction_revision desc
  );

create index if not exists result_correction_fixture_idx
  on public.result_correction_runs (fixture_id, reopened_at desc)
  where fixture_id is not null;

alter table public.result_correction_runs enable row level security;

drop policy if exists result_correction_read_members
on public.result_correction_runs;
create policy result_correction_read_members
on public.result_correction_runs
for select to authenticated
using (public.is_league_member(league_id));

revoke all on table public.result_correction_runs
from public, anon, authenticated;
grant select on table public.result_correction_runs
to authenticated;

alter table public.fantasy_fixtures
  add column if not exists correction_run_id bigint
    references public.result_correction_runs(id) on delete set null;

create index if not exists fantasy_fixtures_correction_run_idx
  on public.fantasy_fixtures (correction_run_id)
  where correction_run_id is not null;

alter table public.matchday_officialization_runs
  add column if not exists source_correction_run_ids jsonb
    not null default '[]'::jsonb;

create or replace function public.prevent_result_correction_mutation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if coalesce(
    current_setting('leghevo.result_correction_context', true),
    ''
  ) = 'on' then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  raise exception
    'Registro correzioni certificato: modifica diretta non consentita.';
end;
$$;

drop trigger if exists result_correction_immutable
on public.result_correction_runs;
create trigger result_correction_immutable
before update or delete on public.result_correction_runs
for each row
execute function public.prevent_result_correction_mutation();

create or replace function public.result_correction_input_hash_v1(
  p_league_id uuid,
  p_matchday_id uuid,
  p_fixture_id uuid,
  p_scope text,
  p_reason text
)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_hash text;
begin
  select md5(
    jsonb_build_object(
      'leagueId', league.id,
      'leagueStatus', league.status,
      'competitionStartedAt', league.competition_started_at,
      'matchdayId', matchday.id,
      'matchdayNumber', matchday.number,
      'scope', p_scope,
      'fixtureId', p_fixture_id,
      'reason', trim(coalesce(p_reason, '')),
      'activeOfficializationId', (
        select run.id
        from public.matchday_officialization_runs run
        where run.matchday_id = p_matchday_id
          and run.superseded_at is null
        order by run.id desc
        limit 1
      ),
      'fixtures', coalesce(
        (
          select jsonb_agg(
            jsonb_build_object(
              'fixtureId', fixture.id,
              'finalizedAt', fixture.finalized_at,
              'resultRevision', fixture.result_revision,
              'officializationRunId', fixture.officialization_run_id,
              'officialProjectionId', fixture.official_projection_id,
              'homePoints', fixture.home_points,
              'awayPoints', fixture.away_points,
              'homeGoals', fixture.home_goals,
              'awayGoals', fixture.away_goals,
              'homeCountedPlayers', fixture.home_counted_players,
              'awayCountedPlayers', fixture.away_counted_players
            )
            order by fixture.id
          )
          from public.fantasy_fixtures fixture
          where fixture.league_id = p_league_id
            and fixture.matchday_id = p_matchday_id
            and fixture.finalized_at is not null
            and (
              p_scope = 'matchday'
              or fixture.id = p_fixture_id
            )
        ),
        '[]'::jsonb
      )
    )::text
  )
  into v_hash
  from public.leagues league
  join public.matchdays matchday
    on matchday.id = p_matchday_id
  where league.id = p_league_id
    and exists (
      select 1
      from public.fantasy_fixtures fixture
      where fixture.league_id = p_league_id
        and fixture.matchday_id = p_matchday_id
    );

  return v_hash;
end;
$$;

create or replace function public.compute_matchday_officialization_v2(
  p_league_id uuid,
  p_matchday_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_league public.leagues%rowtype;
  v_matchday public.matchdays%rowtype;
  v_fixture_count integer := 0;
  v_projection_count integer := 0;
  v_ready_count integer := 0;
  v_certified_count integer := 0;
  v_already_official_count integer := 0;
  v_fixtures jsonb := '[]'::jsonb;
begin
  select league.*
  into v_league
  from public.leagues league
  where league.id = p_league_id;

  if not found then
    return jsonb_build_object(
      'available', false,
      'integrityError', 'league_not_found'
    );
  end if;

  select matchday.*
  into v_matchday
  from public.matchdays matchday
  where matchday.id = p_matchday_id
    and exists (
      select 1
      from public.fantasy_fixtures fixture
      where fixture.league_id = p_league_id
        and fixture.matchday_id = p_matchday_id
    );

  if not found then
    return jsonb_build_object(
      'available', false,
      'integrityError', 'matchday_not_found'
    );
  end if;

  select
    count(*)::integer,
    count(coalesce(official_projection.id, current_projection.id))::integer,
    count(*) filter (
      where coalesce(official_projection.home_ready, current_projection.home_ready)
        and coalesce(official_projection.away_ready, current_projection.away_ready)
        and coalesce(official_projection.home_points, current_projection.home_points) is not null
        and coalesce(official_projection.away_points, current_projection.away_points) is not null
        and coalesce(official_projection.home_goals, current_projection.home_goals) is not null
        and coalesce(official_projection.away_goals, current_projection.away_goals) is not null
    )::integer,
    count(*) filter (
      where coalesce(official_projection.certified, current_projection.certified, false)
    )::integer,
    count(*) filter (where fixture.finalized_at is not null)::integer,
    coalesce(
      jsonb_agg(
        jsonb_build_object(
          'fixtureId', fixture.id,
          'homeTeamId', fixture.home_team_id,
          'awayTeamId', fixture.away_team_id,
          'alreadyOfficial', fixture.finalized_at is not null,
          'correctionRunId', fixture.correction_run_id,
          'projectionId', coalesce(
            official_projection.id,
            current_projection.id
          ),
          'projectionRevision', coalesce(
            official_projection.projection_revision,
            current_projection.projection_revision
          ),
          'projectionHash', coalesce(
            official_projection.result_hash,
            current_projection.result_hash
          ),
          'status', coalesce(
            official_projection.status,
            current_projection.status
          ),
          'certified', coalesce(
            official_projection.certified,
            current_projection.certified,
            false
          ),
          'home', coalesce(
            official_projection.projection_payload -> 'home',
            current_projection.projection_payload -> 'home',
            '{}'::jsonb
          ),
          'away', coalesce(
            official_projection.projection_payload -> 'away',
            current_projection.projection_payload -> 'away',
            '{}'::jsonb
          ),
          'goalMargin', coalesce(
            official_projection.projection_payload -> 'goalMargin',
            current_projection.projection_payload -> 'goalMargin',
            '{}'::jsonb
          )
        )
        order by fixture.id
      ),
      '[]'::jsonb
    )
  into
    v_fixture_count,
    v_projection_count,
    v_ready_count,
    v_certified_count,
    v_already_official_count,
    v_fixtures
  from public.fantasy_fixtures fixture
  left join public.live_fixture_projection_runs official_projection
    on fixture.finalized_at is not null
   and official_projection.id = fixture.official_projection_id
  left join public.live_fixture_projection_runs current_projection
    on fixture.finalized_at is null
   and current_projection.fixture_id = fixture.id
   and current_projection.superseded_at is null
  where fixture.league_id = p_league_id
    and fixture.matchday_id = p_matchday_id;

  return jsonb_build_object(
    'available', v_fixture_count > 0,
    'leagueId', p_league_id,
    'matchdayId', p_matchday_id,
    'matchdayNumber', v_matchday.number,
    'fixtureCount', v_fixture_count,
    'projectionCount', v_projection_count,
    'readyCount', v_ready_count,
    'certifiedCount', v_certified_count,
    'alreadyOfficialCount', v_already_official_count,
    'pendingOfficialCount', greatest(
      v_fixture_count - v_already_official_count,
      0
    ),
    'allReady',
      v_fixture_count > 0
      and v_projection_count = v_fixture_count
      and v_ready_count = v_fixture_count
      and v_certified_count = v_fixture_count,
    'providerComplete',
      coalesce(v_matchday.provider_fixture_count, 0) = 0
      or coalesce(v_matchday.provider_final_fixture_count, 0)
        >= coalesce(v_matchday.provider_fixture_count, 0),
    'fixtures', v_fixtures
  );
end;
$$;

create or replace function public.matchday_officialization_input_hash_v2(
  p_league_id uuid,
  p_matchday_id uuid
)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_payload jsonb;
begin
  v_payload := public.compute_matchday_officialization_v2(
    p_league_id,
    p_matchday_id
  );

  if not coalesce((v_payload ->> 'available')::boolean, false) then
    return null;
  end if;

  return md5(
    jsonb_build_object(
      'policy', 'correction_continuity_v1',
      'leagueId', p_league_id,
      'matchdayId', p_matchday_id,
      'payload', v_payload,
      'fixtureState', coalesce(
        (
          select jsonb_agg(
            jsonb_build_object(
              'fixtureId', fixture.id,
              'finalizedAt', fixture.finalized_at,
              'resultRevision', fixture.result_revision,
              'officializationRunId', fixture.officialization_run_id,
              'officialProjectionId', fixture.official_projection_id,
              'correctionRunId', fixture.correction_run_id
            )
            order by fixture.id
          )
          from public.fantasy_fixtures fixture
          where fixture.league_id = p_league_id
            and fixture.matchday_id = p_matchday_id
        ),
        '[]'::jsonb
      )
    )::text
  );
end;
$$;

create or replace function public.reopen_league_fixture_guarded_v1(
  p_league_id uuid,
  p_fixture_id uuid,
  p_reason text,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_league public.leagues%rowtype;
  v_fixture public.fantasy_fixtures%rowtype;
  v_existing public.result_correction_runs%rowtype;
  v_run public.result_correction_runs%rowtype;
  v_reason text := trim(coalesce(p_reason, ''));
  v_input_hash text;
  v_previous_officialization_id bigint;
  v_previous_official_count integer := 0;
  v_revision integer := 1;
  v_matchday_number integer;
  v_home_team_name text;
  v_away_team_name text;
  v_member_user_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if p_request_id is null then
    raise exception 'Identificativo di correzione mancante.';
  end if;

  if char_length(v_reason) < 10
    or char_length(v_reason) > 240 then
    raise exception
      'La motivazione deve contenere da 10 a 240 caratteri.';
  end if;

  select run.*
  into v_existing
  from public.result_correction_runs run
  where run.request_id = p_request_id;

  if found then
    if v_existing.league_id <> p_league_id
      or v_existing.fixture_id is distinct from p_fixture_id
      or v_existing.scope <> 'fixture'
      or v_existing.reason <> v_reason then
      raise exception 'La chiave di correzione è già stata utilizzata.';
    end if;

    return v_existing.result_payload || jsonb_build_object(
      'correctionId', v_existing.id,
      'correctionRevision', v_existing.correction_revision,
      'reopenedAt', v_existing.reopened_at,
      'affectedFixtureCount', v_existing.affected_fixture_count,
      'idempotentReplay', true
    );
  end if;

  select fixture.*
  into v_fixture
  from public.fantasy_fixtures fixture
  where fixture.id = p_fixture_id
    and fixture.league_id = p_league_id;

  if not found then
    raise exception 'Partita non trovata nel calendario della lega.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'matchday-officialization:'
        || p_league_id::text
        || ':'
        || v_fixture.matchday_id::text,
      0
    )
  );

  select run.*
  into v_existing
  from public.result_correction_runs run
  where run.request_id = p_request_id;

  if found then
    if v_existing.league_id <> p_league_id
      or v_existing.fixture_id is distinct from p_fixture_id
      or v_existing.scope <> 'fixture'
      or v_existing.reason <> v_reason then
      raise exception 'La chiave di correzione è già stata utilizzata.';
    end if;

    return v_existing.result_payload || jsonb_build_object(
      'correctionId', v_existing.id,
      'correctionRevision', v_existing.correction_revision,
      'reopenedAt', v_existing.reopened_at,
      'affectedFixtureCount', v_existing.affected_fixture_count,
      'idempotentReplay', true
    );
  end if;

  select league.*
  into v_league
  from public.leagues league
  where league.id = p_league_id
  for update;

  if not found then
    raise exception 'Lega non trovata.';
  end if;

  if v_league.owner_id <> auth.uid() then
    raise exception 'Solo il Presidente può correggere un risultato.';
  end if;

  if v_league.status in ('completed', 'archived') then
    raise exception 'La stagione è conclusa: i risultati sono congelati.';
  end if;

  select fixture.*
  into v_fixture
  from public.fantasy_fixtures fixture
  where fixture.id = p_fixture_id
    and fixture.league_id = p_league_id
  for update;

  if v_fixture.finalized_at is null then
    raise exception 'Il risultato selezionato non è ufficiale.';
  end if;

  select count(*) filter (where fixture.finalized_at is not null)::integer
  into v_previous_official_count
  from public.fantasy_fixtures fixture
  where fixture.league_id = p_league_id
    and fixture.matchday_id = v_fixture.matchday_id;

  select run.id
  into v_previous_officialization_id
  from public.matchday_officialization_runs run
  where run.matchday_id = v_fixture.matchday_id
    and run.superseded_at is null
  order by run.id desc
  limit 1;

  v_input_hash := public.result_correction_input_hash_v1(
    p_league_id,
    v_fixture.matchday_id,
    p_fixture_id,
    'fixture',
    v_reason
  );

  if v_input_hash is null then
    raise exception 'Impossibile calcolare l''impronta della correzione.';
  end if;

  select coalesce(max(run.correction_revision), 0) + 1
  into v_revision
  from public.result_correction_runs run
  where run.matchday_id = v_fixture.matchday_id;

  select
    matchday.number,
    home_team.name,
    away_team.name
  into
    v_matchday_number,
    v_home_team_name,
    v_away_team_name
  from public.matchdays matchday
  join public.fantasy_teams home_team
    on home_team.id = v_fixture.home_team_id
  join public.fantasy_teams away_team
    on away_team.id = v_fixture.away_team_id
  where matchday.id = v_fixture.matchday_id;

  insert into public.result_correction_runs (
    league_id,
    matchday_id,
    fixture_id,
    request_id,
    scope,
    correction_revision,
    input_hash,
    reason,
    previous_officialization_id,
    affected_fixture_count,
    previous_official_fixture_count,
    result_payload,
    requested_by
  )
  values (
    p_league_id,
    v_fixture.matchday_id,
    p_fixture_id,
    p_request_id,
    'fixture',
    v_revision,
    v_input_hash,
    v_reason,
    v_previous_officialization_id,
    1,
    v_previous_official_count,
    jsonb_build_object(
      'leagueId', p_league_id,
      'matchdayId', v_fixture.matchday_id,
      'matchdayNumber', v_matchday_number,
      'fixtureId', p_fixture_id,
      'scope', 'fixture',
      'reason', v_reason,
      'previousOfficializationId', v_previous_officialization_id
    ),
    auth.uid()
  )
  returning * into v_run;

  perform set_config(
    'leghevo.matchday_officialization_context',
    'on',
    true
  );

  update public.matchday_officialization_runs run
  set superseded_at = now()
  where run.matchday_id = v_fixture.matchday_id
    and run.superseded_at is null;

  update public.fantasy_fixtures fixture
  set
    finalized_at = null,
    finalized_by = null,
    reopened_at = now(),
    reopened_by = auth.uid(),
    correction_reason = v_reason,
    corrected_at = now(),
    corrected_by = auth.uid(),
    correction_run_id = v_run.id,
    officialization_run_id = null,
    official_projection_id = null
  where fixture.id = p_fixture_id;

  perform public.refresh_matchday_results_internal(v_fixture.matchday_id);

  for v_member_user_id in
    select member.user_id
    from public.league_members member
    where member.league_id = p_league_id
  loop
    perform public.create_user_notification(
      v_member_user_id,
      p_league_id,
      'result',
      'Risultato in correzione · Giornata ' || v_matchday_number,
      v_home_team_name
        || '–'
        || v_away_team_name
        || ' è stato riaperto. Motivo: '
        || v_reason,
      'standings',
      jsonb_build_object(
        'event', 'fixture_reopened_guarded',
        'fixture_id', p_fixture_id,
        'matchday_id', v_fixture.matchday_id,
        'matchday_number', v_matchday_number,
        'correction_id', v_run.id,
        'correction_revision', v_run.correction_revision,
        'reason', v_reason
      ),
      'result:fixture-reopened-guarded:'
        || v_run.id::text
        || ':'
        || v_member_user_id::text
    );
  end loop;

  return v_run.result_payload || jsonb_build_object(
    'correctionId', v_run.id,
    'correctionRevision', v_run.correction_revision,
    'correctionInputHash', v_run.input_hash,
    'reopenedAt', v_run.reopened_at,
    'affectedFixtureCount', 1,
    'idempotentReplay', false
  );
end;
$$;

