do $block$
declare
  v_item record;
begin
  for v_item in
    select playoff.id as playoff_id, run.id as run_id
    from public.league_playoffs playoff
    join public.league_playoff_rounds playoff_round
      on playoff_round.playoff_id = playoff.id
      and playoff_round.round_number = playoff.round_count
      and playoff_round.status = 'official'
    join lateral (
      select finalization.id
      from public.league_playoff_round_finalization_runs finalization
      where finalization.playoff_id = playoff.id
        and finalization.round_id = playoff_round.id
        and finalization.completed_playoffs
      order by finalization.id desc
      limit 1
    ) run on true
    where playoff.status = 'completed'
      and playoff.champion_team_id is not null
      and playoff.runner_up_team_id is not null
      and not exists (
        select 1
        from public.league_playoff_completion_certificates certificate
        where certificate.playoff_id = playoff.id
      )
  loop
    perform public.certify_league_playoff_completion_internal_v1(
      v_item.playoff_id,
      v_item.run_id
    );
  end loop;
end;
