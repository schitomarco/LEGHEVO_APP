create or replace function public.compute_league_playoff_completion_fingerprint_v1(
  p_playoff_id uuid
)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_playoff public.league_playoffs%rowtype;
  v_final_round public.league_playoff_rounds%rowtype;
  v_run public.league_playoff_round_finalization_runs%rowtype;
  v_ties text := '';
  v_entries text := '';
  v_payload text;
begin
  select playoff.*
  into v_playoff
  from public.league_playoffs playoff
  where playoff.id = p_playoff_id;

  if not found or v_playoff.status <> 'completed'
    or v_playoff.champion_team_id is null
    or v_playoff.runner_up_team_id is null then
    return null;
  end if;

  select playoff_round.*
  into v_final_round
  from public.league_playoff_rounds playoff_round
  where playoff_round.playoff_id = v_playoff.id
    and playoff_round.round_number = v_playoff.round_count;

  if not found or v_final_round.status <> 'official' then
    return null;
  end if;

  select run.*
  into v_run
  from public.league_playoff_round_finalization_runs run
  where run.playoff_id = v_playoff.id
    and run.round_id = v_final_round.id
    and run.completed_playoffs
  order by run.id desc
  limit 1;

  if not found
    or v_run.champion_team_id is distinct from v_playoff.champion_team_id
    or v_run.runner_up_team_id is distinct from v_playoff.runner_up_team_id then
    return null;
  end if;

  select coalesce(
    string_agg(
      tie.bracket_position::text || ':'
      || coalesce(tie.home_team_id::text, '-') || ':'
      || coalesce(tie.away_team_id::text, '-') || ':'
      || coalesce(tie.home_points::text, '-') || ':'
      || coalesce(tie.away_points::text, '-') || ':'
      || coalesce(tie.home_goals::text, '-') || ':'
      || coalesce(tie.away_goals::text, '-') || ':'
      || coalesce(tie.winner_team_id::text, '-') || ':'
      || coalesce(tie.decided_by, '-'),
      '|' order by tie.bracket_position
    ),
    ''
  )
  into v_ties
  from public.league_playoff_ties tie
  where tie.round_id = v_final_round.id;

  select coalesce(
    string_agg(
      entry.seed::text || ':'
      || entry.fantasy_team_id::text || ':'
      || entry.regular_season_position::text || ':'
      || coalesce(entry.eliminated_round::text, '-') || ':'
      || coalesce(entry.final_position::text, '-'),
      '|' order by entry.seed
    ),
    ''
  )
  into v_entries
  from public.league_playoff_entries entry
  where entry.playoff_id = v_playoff.id;

  v_payload :=
    v_playoff.id::text || '#'
    || v_playoff.league_id::text || '#'
    || v_playoff.status || '#'
    || v_playoff.participant_count::text || '#'
    || v_playoff.round_count::text || '#'
    || v_playoff.current_round::text || '#'
    || v_playoff.champion_team_id::text || '#'
    || v_playoff.runner_up_team_id::text || '#'
    || coalesce(v_playoff.completed_at::text, '-') || '#'
    || v_final_round.id::text || '#'
    || v_final_round.round_number::text || '#'
    || coalesce(v_final_round.finalized_at::text, '-') || '#'
    || v_run.id::text || '#'
    || v_run.result_hash || '#'
    || v_ties || '#'
    || v_entries;

  return public.leghevo_sha256_hex_v1(v_payload);
end;
$$;

revoke all on function public.compute_league_playoff_completion_fingerprint_v1(uuid)
from public, anon, authenticated;

create or replace function public.certify_league_playoff_completion_internal_v1(
  p_playoff_id uuid,
  p_finalization_run_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_playoff public.league_playoffs%rowtype;
  v_final_round public.league_playoff_rounds%rowtype;
  v_run public.league_playoff_round_finalization_runs%rowtype;
  v_certificate public.league_playoff_completion_certificates%rowtype;
  v_current_result_hash text;
  v_fingerprint text;
begin
  select playoff.*
  into v_playoff
  from public.league_playoffs playoff
  where playoff.id = p_playoff_id;

  if not found or v_playoff.status <> 'completed' then
    raise exception 'I Playoff non sono conclusi: certificazione non disponibile.';
  end if;

  if v_playoff.champion_team_id is null or v_playoff.runner_up_team_id is null then
    raise exception 'Podio finale dei Playoff incompleto.';
  end if;

  select playoff_round.*
  into v_final_round
  from public.league_playoff_rounds playoff_round
  where playoff_round.playoff_id = v_playoff.id
    and playoff_round.round_number = v_playoff.round_count;

  if not found or v_final_round.status <> 'official' then
    raise exception 'Finale dei Playoff non ufficiale.';
  end if;

  select run.*
  into v_run
  from public.league_playoff_round_finalization_runs run
  where run.id = p_finalization_run_id
    and run.playoff_id = v_playoff.id
    and run.round_id = v_final_round.id
    and run.completed_playoffs;

  if not found then
    raise exception 'Ufficializzazione certificata della finale non trovata.';
  end if;

  if v_run.champion_team_id is distinct from v_playoff.champion_team_id
    or v_run.runner_up_team_id is distinct from v_playoff.runner_up_team_id then
    raise exception 'Il podio non coincide con l''ufficializzazione della finale.';
  end if;

  v_current_result_hash := public.compute_league_playoff_round_result_hash_v1(
    v_playoff.id,
    v_final_round.round_number
  );

  if v_current_result_hash is null or v_current_result_hash <> v_run.result_hash then
    raise exception 'L''esito della finale non coincide con la revisione certificata.';
  end if;

  v_fingerprint := public.compute_league_playoff_completion_fingerprint_v1(v_playoff.id);

  if v_fingerprint is null or char_length(v_fingerprint) <> 64 then
    raise exception 'Impossibile calcolare l''impronta conclusiva dei Playoff.';
  end if;

  insert into public.league_playoff_completion_certificates (
    league_id,
    playoff_id,
    final_round_id,
    finalization_run_id,
    champion_team_id,
    runner_up_team_id,
    final_round_number,
    source_result_hash,
    completion_fingerprint,
    snapshot,
    certified_by,
    certified_at
  ) values (
    v_playoff.league_id,
    v_playoff.id,
    v_final_round.id,
    v_run.id,
    v_playoff.champion_team_id,
    v_playoff.runner_up_team_id,
    v_final_round.round_number,
    v_run.result_hash,
    v_fingerprint,
    jsonb_build_object(
      'policy', 'certified_v1',
      'leagueId', v_playoff.league_id,
      'playoffId', v_playoff.id,
      'finalRoundId', v_final_round.id,
      'finalRoundNumber', v_final_round.round_number,
      'finalizationRunId', v_run.id,
      'championTeamId', v_playoff.champion_team_id,
      'runnerUpTeamId', v_playoff.runner_up_team_id,
      'sourceResultHash', v_run.result_hash,
      'completionFingerprint', v_fingerprint
    ),
    v_run.requested_by,
    coalesce(v_run.finalized_at, v_playoff.completed_at, now())
  )
  on conflict (playoff_id) do nothing;

  select certificate.*
  into v_certificate
  from public.league_playoff_completion_certificates certificate
  where certificate.playoff_id = v_playoff.id;

  if not found then
    raise exception 'Certificato conclusivo dei Playoff non creato.';
  end if;

  if v_certificate.finalization_run_id <> v_run.id
    or v_certificate.completion_fingerprint <> v_fingerprint
    or v_certificate.source_result_hash <> v_run.result_hash then
    raise exception 'Esiste un certificato conclusivo incompatibile.';
  end if;

  return v_certificate.id;
end;
$$;

revoke all on function public.certify_league_playoff_completion_internal_v1(uuid, bigint)
from public, anon, authenticated;

