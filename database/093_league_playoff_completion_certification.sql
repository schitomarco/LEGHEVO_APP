create or replace function public.get_league_playoff_completion_integrity_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_completed_count integer := 0;
  v_certificate_count integer := 0;
  v_missing_count integer := 0;
  v_fingerprint_drift_count integer := 0;
  v_source_drift_count integer := 0;
  v_podium_issue_count integer := 0;
  v_link_issue_count integer := 0;
  v_healthy boolean := false;
begin
  if auth.uid() is null
    or (not public.is_league_member(p_league_id)
      and not public.is_league_admin(p_league_id)) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  select count(*)::integer
  into v_completed_count
  from public.league_playoffs playoff
  where playoff.league_id = p_league_id
    and playoff.status = 'completed';

  select count(*)::integer
  into v_certificate_count
  from public.league_playoff_completion_certificates certificate
  where certificate.league_id = p_league_id;

  select count(*)::integer
  into v_missing_count
  from public.league_playoffs playoff
  left join public.league_playoff_completion_certificates certificate
    on certificate.playoff_id = playoff.id
  where playoff.league_id = p_league_id
    and playoff.status = 'completed'
    and certificate.id is null;

  select count(*)::integer
  into v_fingerprint_drift_count
  from public.league_playoff_completion_certificates certificate
  where certificate.league_id = p_league_id
    and certificate.completion_fingerprint is distinct from
      public.compute_league_playoff_completion_fingerprint_v1(certificate.playoff_id);

  select count(*)::integer
  into v_source_drift_count
  from public.league_playoff_completion_certificates certificate
  join public.league_playoff_round_finalization_runs run
    on run.id = certificate.finalization_run_id
  where certificate.league_id = p_league_id
    and certificate.source_result_hash is distinct from run.result_hash;

  select count(*)::integer
  into v_podium_issue_count
  from public.league_playoff_completion_certificates certificate
  join public.league_playoffs playoff on playoff.id = certificate.playoff_id
  where certificate.league_id = p_league_id
    and (
      certificate.champion_team_id is distinct from playoff.champion_team_id
      or certificate.runner_up_team_id is distinct from playoff.runner_up_team_id
      or certificate.champion_team_id = certificate.runner_up_team_id
    );

  select count(*)::integer
  into v_link_issue_count
  from public.league_playoff_completion_certificates certificate
  join public.league_playoff_rounds playoff_round
    on playoff_round.id = certificate.final_round_id
  join public.league_playoff_round_finalization_runs run
    on run.id = certificate.finalization_run_id
  where certificate.league_id = p_league_id
    and (
      playoff_round.playoff_id <> certificate.playoff_id
      or playoff_round.round_number <> certificate.final_round_number
      or playoff_round.status <> 'official'
      or run.playoff_id <> certificate.playoff_id
      or run.round_id <> certificate.final_round_id
      or not run.completed_playoffs
    );

  v_healthy :=
    v_missing_count = 0
    and v_fingerprint_drift_count = 0
    and v_source_drift_count = 0
    and v_podium_issue_count = 0
    and v_link_issue_count = 0;

  return jsonb_build_object(
    'policy', 'certified_v1',
    'healthy', v_healthy,
    'completedPlayoffCount', v_completed_count,
    'certificateCount', v_certificate_count,
    'missingCertificateCount', v_missing_count,
    'fingerprintDriftCount', v_fingerprint_drift_count,
    'sourceDriftCount', v_source_drift_count,
    'podiumIssueCount', v_podium_issue_count,
    'linkIssueCount', v_link_issue_count
  );
end;
$$;

