create or replace function public.get_league_matchday_progression_integrity_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_league public.leagues%rowtype;
  v_run_count integer := 0;
  v_current_run_count integer := 0;
  v_invalid_link_count integer := 0;
  v_invalid_hash_count integer := 0;
  v_invalid_current_count integer := 0;
  v_revision_gap_count integer := 0;
  v_pointer_valid boolean := false;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if not public.is_league_member(p_league_id)
    and not public.is_league_admin(p_league_id) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  select league.*
  into v_league
  from public.leagues league
  where league.id = p_league_id;

  if not found then
    raise exception 'Lega non trovata.';
  end if;

  select
    count(*)::integer,
    count(*) filter (where run.superseded_at is null)::integer,
    count(*) filter (
      where officialization.id is null
        or officialization.league_id <> run.league_id
        or officialization.matchday_id <> run.matchday_id
    )::integer,
    count(*) filter (
      where run.standings_hash <> md5(run.standings_snapshot::text)
    )::integer,
    count(*) filter (
      where run.superseded_at is null
        and officialization.superseded_at is not null
    )::integer
  into
    v_run_count,
    v_current_run_count,
    v_invalid_link_count,
    v_invalid_hash_count,
    v_invalid_current_count
  from public.matchday_progression_runs run
  left join public.matchday_officialization_runs officialization
    on officialization.id = run.officialization_run_id
  where run.league_id = p_league_id;

  select count(*)::integer
  into v_revision_gap_count
  from (
    select run.matchday_id
    from public.matchday_progression_runs run
    where run.league_id = p_league_id
    group by run.matchday_id
    having min(run.progression_revision) <> 1
      or max(run.progression_revision) <> count(*)
      or count(distinct run.progression_revision) <> count(*)
  ) invalid_revision;

  v_pointer_valid :=
    v_league.current_matchday_id is not null
    and v_league.current_matchday_number is not null
    and exists (
      select 1
      from public.matchdays matchday
      join public.fantasy_fixtures fixture
        on fixture.matchday_id = matchday.id
      where matchday.id = v_league.current_matchday_id
        and matchday.number = v_league.current_matchday_number
        and fixture.league_id = p_league_id
    );

  return jsonb_build_object(
    'healthy',
      v_invalid_link_count = 0
      and v_invalid_hash_count = 0
      and v_invalid_current_count = 0
      and v_revision_gap_count = 0
      and v_pointer_valid,
    'runCount', v_run_count,
    'currentRunCount', v_current_run_count,
    'invalidLinkCount', v_invalid_link_count,
    'invalidHashCount', v_invalid_hash_count,
    'invalidCurrentCount', v_invalid_current_count,
    'revisionGapCount', v_revision_gap_count,
    'currentMatchdayId', v_league.current_matchday_id,
    'currentMatchdayNumber', v_league.current_matchday_number,
    'currentMatchdayPointerValid', v_pointer_valid,
    'progressionPolicy', 'protected_v1'
  );
end;
$$;

