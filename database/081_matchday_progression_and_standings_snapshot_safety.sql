create table if not exists public.matchday_progression_runs (
  id bigint generated by default as identity primary key,
  league_id uuid not null
    references public.leagues(id) on delete cascade,
  matchday_id uuid not null
    references public.matchdays(id) on delete cascade,
  officialization_run_id bigint not null
    references public.matchday_officialization_runs(id) on delete restrict,
  request_id uuid not null unique,
  progression_revision integer not null,
  input_hash text not null,
  standings_hash text not null,
  standings_snapshot jsonb not null default '[]'::jsonb,
  previous_matchday_id uuid
    references public.matchdays(id) on delete set null,
  previous_matchday_number smallint,
  next_matchday_id uuid
    references public.matchdays(id) on delete set null,
  next_matchday_number smallint,
  advanced boolean not null default false,
  season_ready_to_complete boolean not null default false,
  result_payload jsonb not null default '{}'::jsonb,
  progressed_by uuid references public.profiles(id) on delete set null,
  progressed_at timestamptz not null default now(),
  superseded_at timestamptz,
  constraint matchday_progression_revision_check
    check (progression_revision >= 1),
  constraint matchday_progression_input_hash_check
    check (length(input_hash) = 32),
  constraint matchday_progression_standings_hash_check
    check (length(standings_hash) = 32),
  constraint matchday_progression_snapshot_check
    check (jsonb_typeof(standings_snapshot) = 'array'),
  constraint matchday_progression_previous_number_check
    check (
      previous_matchday_number is null
      or previous_matchday_number > 0
    ),
  constraint matchday_progression_next_number_check
    check (
      next_matchday_number is null
      or next_matchday_number > 0
    ),
  constraint matchday_progression_advance_target_check
    check (
      not advanced
      or (
        next_matchday_id is not null
        and next_matchday_number is not null
      )
    ),
  unique (matchday_id, progression_revision)
);

create unique index if not exists matchday_progression_current_idx
  on public.matchday_progression_runs (matchday_id)
  where superseded_at is null;

create index if not exists matchday_progression_league_idx
  on public.matchday_progression_runs (
    league_id,
    matchday_id,
    progressed_at desc
  );

create index if not exists matchday_progression_officialization_idx
  on public.matchday_progression_runs (officialization_run_id);

alter table public.matchday_progression_runs enable row level security;

drop policy if exists matchday_progression_read_members
on public.matchday_progression_runs;
create policy matchday_progression_read_members
on public.matchday_progression_runs
for select to authenticated
using (public.is_league_member(league_id));

revoke all on table public.matchday_progression_runs
from public, anon, authenticated;
grant select on table public.matchday_progression_runs
to authenticated;

create or replace function public.prevent_matchday_progression_mutation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if coalesce(
    current_setting('leghevo.matchday_progression_context', true),
    ''
  ) = 'on' then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  raise exception
    'Progressione certificata: modifica diretta non consentita.';
end;
$$;

drop trigger if exists matchday_progression_immutable
on public.matchday_progression_runs;
create trigger matchday_progression_immutable
before update or delete on public.matchday_progression_runs
for each row
execute function public.prevent_matchday_progression_mutation();

create or replace function public.build_league_standings_snapshot_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_snapshot jsonb;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if not public.is_league_member(p_league_id)
    and not public.is_league_admin(p_league_id) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'position', standing."position",
        'teamId', standing.fantasy_team_id,
        'teamName', standing.team_name,
        'played', standing.played,
        'won', standing.won,
        'drawn', standing.drawn,
        'lost', standing.lost,
        'goalsFor', standing.goals_for,
        'goalsAgainst', standing.goals_against,
        'goalDifference', standing.goal_difference,
        'pointsFor', standing.points_for,
        'leaguePoints', standing.league_points,
        'tiebreaker', standing.standings_tiebreaker,
        'headToHeadPlayed', standing.head_to_head_played,
        'headToHeadPoints', standing.head_to_head_points,
        'headToHeadGoalDifference',
          standing.head_to_head_goal_difference,
        'headToHeadEligible', standing.head_to_head_eligible
      )
      order by standing."position"
    ),
    '[]'::jsonb
  )
  into v_snapshot
  from public.get_league_standings_v2(p_league_id) standing;

  return v_snapshot;
end;
$$;

create or replace function public.settle_matchday_progression_guarded_v1(
  p_league_id uuid,
  p_matchday_id uuid,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_league public.leagues%rowtype;
  v_matchday public.matchdays%rowtype;
  v_next_matchday public.matchdays%rowtype;
  v_officialization public.matchday_officialization_runs%rowtype;
  v_existing public.matchday_progression_runs%rowtype;
  v_run public.matchday_progression_runs%rowtype;
  v_fixture_count integer := 0;
  v_official_count integer := 0;
  v_officialization_count integer := 0;
  v_previous_unofficial_count integer := 0;
  v_revision integer := 0;
  v_standings jsonb := '[]'::jsonb;
  v_standings_hash text;
  v_input_hash text;
  v_advanced boolean := false;
  v_season_ready boolean := false;
  v_payload jsonb;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if p_request_id is null then
    raise exception 'Identificativo di progressione mancante.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'matchday-progression:' || p_league_id::text,
      0
    )
  );

  select league.*
  into v_league
  from public.leagues league
  where league.id = p_league_id
  for update;

  if not found then
    raise exception 'Lega non trovata.';
  end if;

  if v_league.owner_id <> auth.uid() then
    raise exception
      'Solo il Presidente può certificare l''avanzamento della giornata.';
  end if;

  if v_league.competition_started_at is null then
    raise exception 'La competizione non è ancora iniziata.';
  end if;

  if v_league.status in ('completed', 'archived') then
    raise exception 'La stagione è già conclusa.';
  end if;

  select matchday.*
  into v_matchday
  from public.matchdays matchday
  where matchday.id = p_matchday_id
    and exists (
      select 1
      from public.fantasy_fixtures fixture
      where fixture.league_id = p_league_id
        and fixture.matchday_id = matchday.id
    )
  for update;

  if not found then
    raise exception 'Giornata non trovata nel calendario della lega.';
  end if;

  select
    count(*)::integer,
    count(*) filter (
      where fixture.finalized_at is not null
    )::integer,
    count(distinct fixture.officialization_run_id) filter (
      where fixture.officialization_run_id is not null
    )::integer
  into
    v_fixture_count,
    v_official_count,
    v_officialization_count
  from public.fantasy_fixtures fixture
  where fixture.league_id = p_league_id
    and fixture.matchday_id = p_matchday_id;

  if v_fixture_count = 0
    or v_official_count <> v_fixture_count
    or v_officialization_count <> 1 then
    raise exception
      'La giornata deve essere interamente ufficializzata prima dell''avanzamento.';
  end if;

  select officialization.*
  into v_officialization
  from public.matchday_officialization_runs officialization
  where officialization.id = (
    select min(fixture.officialization_run_id)
    from public.fantasy_fixtures fixture
    where fixture.league_id = p_league_id
      and fixture.matchday_id = p_matchday_id
  )
    and officialization.league_id = p_league_id
    and officialization.matchday_id = p_matchday_id
    and officialization.superseded_at is null;

  if not found then
    raise exception
      'La fotografia ufficiale corrente della giornata non è disponibile.';
  end if;

  select run.*
  into v_existing
  from public.matchday_progression_runs run
  where run.request_id = p_request_id;

  if found then
    if v_existing.league_id <> p_league_id
      or v_existing.matchday_id <> p_matchday_id
      or v_existing.officialization_run_id <> v_officialization.id then
      raise exception 'La chiave di progressione è già stata utilizzata.';
    end if;

    return v_existing.result_payload || jsonb_build_object(
      'progressionId', v_existing.id,
      'progressionRevision', v_existing.progression_revision,
      'standingsHash', v_existing.standings_hash,
      'progressedAt', v_existing.progressed_at,
      'idempotentReplay', true
    );
  end if;

  select run.*
  into v_existing
  from public.matchday_progression_runs run
  where run.matchday_id = p_matchday_id
    and run.officialization_run_id = v_officialization.id
    and run.superseded_at is null;

  if found then
    return v_existing.result_payload || jsonb_build_object(
      'progressionId', v_existing.id,
      'progressionRevision', v_existing.progression_revision,
      'standingsHash', v_existing.standings_hash,
      'progressedAt', v_existing.progressed_at,
      'idempotentReplay', true
    );
  end if;

  if v_league.current_matchday_id is null
    or v_league.current_matchday_number is null then
    raise exception
      'La giornata corrente della competizione non è certificata.';
  end if;

  if v_matchday.number > v_league.current_matchday_number then
    raise exception
      'Non puoi saltare la giornata corrente della competizione.';
  end if;

  select count(*)::integer
  into v_previous_unofficial_count
  from public.fantasy_fixtures fixture
  join public.matchdays previous_matchday
    on previous_matchday.id = fixture.matchday_id
  where fixture.league_id = p_league_id
    and previous_matchday.number < v_matchday.number
    and fixture.finalized_at is null;

  if v_previous_unofficial_count > 0 then
    raise exception
      'Esistono giornate precedenti non ancora ufficializzate.';
  end if;

  select next_matchday.*
  into v_next_matchday
  from public.fantasy_fixtures fixture
  join public.matchdays next_matchday
    on next_matchday.id = fixture.matchday_id
  where fixture.league_id = p_league_id
    and next_matchday.number > v_matchday.number
  group by next_matchday.id
  order by next_matchday.number, next_matchday.starts_at, next_matchday.id
  limit 1;

  v_standings := public.build_league_standings_snapshot_v1(p_league_id);
  v_standings_hash := md5(v_standings::text);

  v_input_hash := md5(
    jsonb_build_object(
      'leagueId', p_league_id,
      'matchdayId', p_matchday_id,
      'matchdayNumber', v_matchday.number,
      'officializationId', v_officialization.id,
      'officializationHash', v_officialization.result_hash,
      'standingsHash', v_standings_hash,
      'currentMatchdayId', v_league.current_matchday_id,
      'currentMatchdayNumber', v_league.current_matchday_number,
      'nextMatchdayId', v_next_matchday.id,
      'nextMatchdayNumber', v_next_matchday.number
    )::text
  );

  select coalesce(max(run.progression_revision), 0) + 1
  into v_revision
  from public.matchday_progression_runs run
  where run.matchday_id = p_matchday_id;

  -- La prima ufficializzazione della giornata corrente fa avanzare il
  -- puntatore. Una riufficializzazione di una giornata passata aggiorna
  -- soltanto fotografia e revisione, senza far arretrare il calendario.
  v_advanced :=
    v_matchday.number = v_league.current_matchday_number
    and v_next_matchday.id is not null;
  v_season_ready := v_next_matchday.id is null;

  if v_advanced then
    perform set_config('leghevo.competition_activation', 'allowed', true);

    update public.leagues league
    set
      competition_revision = greatest(league.competition_revision, 0) + 1,
      current_matchday_id = v_next_matchday.id,
      current_matchday_number = v_next_matchday.number,
      updated_at = now()
    where league.id = p_league_id;
  end if;

  v_payload := jsonb_build_object(
    'leagueId', p_league_id,
    'matchdayId', p_matchday_id,
    'matchdayNumber', v_matchday.number,
    'officializationId', v_officialization.id,
    'officializationRevision',
      v_officialization.finalization_revision,
    'standings', v_standings,
    'standingsHash', v_standings_hash,
    'advanced', v_advanced,
    'nextMatchdayId', v_next_matchday.id,
    'nextMatchdayNumber', v_next_matchday.number,
    'seasonReadyToComplete', v_season_ready
  );

  perform set_config(
    'leghevo.matchday_progression_context',
    'on',
    true
  );

  update public.matchday_progression_runs run
  set superseded_at = now()
  where run.matchday_id = p_matchday_id
    and run.superseded_at is null;

  insert into public.matchday_progression_runs (
    league_id,
    matchday_id,
    officialization_run_id,
    request_id,
    progression_revision,
    input_hash,
    standings_hash,
    standings_snapshot,
    previous_matchday_id,
    previous_matchday_number,
    next_matchday_id,
    next_matchday_number,
    advanced,
    season_ready_to_complete,
    result_payload,
    progressed_by
  ) values (
    p_league_id,
    p_matchday_id,
    v_officialization.id,
    p_request_id,
    v_revision,
    v_input_hash,
    v_standings_hash,
    v_standings,
    v_league.current_matchday_id,
    v_league.current_matchday_number,
    v_next_matchday.id,
    v_next_matchday.number,
    v_advanced,
    v_season_ready,
    v_payload,
    auth.uid()
  )
  returning * into v_run;

  return v_payload || jsonb_build_object(
    'progressionId', v_run.id,
    'progressionRevision', v_run.progression_revision,
    'progressionInputHash', v_run.input_hash,
    'progressedAt', v_run.progressed_at,
    'idempotentReplay', false
  );
end;
$$;

