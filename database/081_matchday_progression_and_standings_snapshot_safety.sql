create or replace function public.finalize_league_matchday_guarded_v2(
  p_league_id uuid,
  p_matchday_id uuid,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_league public.leagues%rowtype;
  v_matchday public.matchdays%rowtype;
  v_existing public.matchday_officialization_runs%rowtype;
  v_run public.matchday_officialization_runs%rowtype;
  v_fixture record;
  v_payload jsonb;
  v_input_hash text;
  v_result_hash text;
  v_source_projection_ids jsonb;
  v_source_correction_run_ids jsonb;
  v_fixture_count integer := 0;
  v_official_count integer := 0;
  v_pending_count integer := 0;
  v_linked_run_count integer := 0;
  v_revision integer := 1;
  v_updated integer := 0;
  v_active_run_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if p_request_id is null then
    raise exception 'Identificativo di ufficializzazione mancante.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'matchday-officialization:'
        || p_league_id::text
        || ':'
        || p_matchday_id::text,
      0
    )
  );

  select league.*
  into v_league
  from public.leagues league
  where league.id = p_league_id
  for update;

  if not found then
    raise exception 'Lega non trovata.';
  end if;

  if v_league.owner_id <> auth.uid() then
    raise exception 'Solo il Presidente può ufficializzare la giornata.';
  end if;

  if v_league.competition_started_at is null then
    raise exception 'Avvia la competizione prima di chiudere una giornata.';
  end if;

  if v_league.status in ('completed', 'archived') then
    raise exception 'La stagione è già conclusa e non può essere modificata.';
  end if;

  select matchday.*
  into v_matchday
  from public.matchdays matchday
  where matchday.id = p_matchday_id
    and exists (
      select 1
      from public.fantasy_fixtures fixture
      where fixture.league_id = p_league_id
        and fixture.matchday_id = p_matchday_id
    )
  for update;

  if not found then
    raise exception 'Giornata non trovata nel calendario della lega.';
  end if;

  if now() < coalesce(
    v_matchday.ends_at,
    v_matchday.starts_at + interval '4 days'
  ) then
    raise exception 'La giornata reale non è ancora terminata.';
  end if;

  select
    count(*)::integer,
    count(*) filter (where fixture.finalized_at is not null)::integer,
    count(distinct fixture.officialization_run_id) filter (
      where fixture.officialization_run_id is not null
    )::integer
  into v_fixture_count, v_official_count, v_linked_run_count
  from public.fantasy_fixtures fixture
  where fixture.league_id = p_league_id
    and fixture.matchday_id = p_matchday_id;

  if v_fixture_count = 0 then
    raise exception 'La giornata non contiene partite fantasy.';
  end if;

  v_pending_count := v_fixture_count - v_official_count;

  if v_official_count = v_fixture_count
    and v_linked_run_count = 1 then
    select run.*
    into v_existing
    from public.matchday_officialization_runs run
    where run.id = (
      select min(fixture.officialization_run_id)
      from public.fantasy_fixtures fixture
      where fixture.league_id = p_league_id
        and fixture.matchday_id = p_matchday_id
    )
      and run.superseded_at is null;

    if found then
      return v_existing.result_payload || jsonb_build_object(
        'officializationId', v_existing.id,
        'officializationRevision', v_existing.finalization_revision,
        'officializationInputHash', v_existing.input_hash,
        'officializationHash', v_existing.result_hash,
        'finalizedAt', v_existing.finalized_at,
        'finalizedFixtureCount', v_existing.finalized_fixture_count,
        'newlyFinalizedFixtureCount', 0,
        'idempotentReplay', true
      );
    end if;
  end if;

  select run.*
  into v_existing
  from public.matchday_officialization_runs run
  where run.request_id = p_request_id;

  if found then
    if v_existing.league_id <> p_league_id
      or v_existing.matchday_id <> p_matchday_id then
      raise exception
        'La chiave di ufficializzazione è già stata utilizzata.';
    end if;

    return v_existing.result_payload || jsonb_build_object(
      'officializationId', v_existing.id,
      'officializationRevision', v_existing.finalization_revision,
      'officializationInputHash', v_existing.input_hash,
      'officializationHash', v_existing.result_hash,
      'finalizedAt', v_existing.finalized_at,
      'finalizedFixtureCount', v_existing.finalized_fixture_count,
      'newlyFinalizedFixtureCount', 0,
      'idempotentReplay', true
    );
  end if;

  perform public.ensure_matchday_lineups(p_matchday_id);

  for v_fixture in
    select fixture.id
    from public.fantasy_fixtures fixture
    where fixture.league_id = p_league_id
      and fixture.matchday_id = p_matchday_id
      and fixture.finalized_at is null
    order by fixture.id
    for update
  loop
    perform public.refresh_live_fixture_projection_guarded_v1(
      v_fixture.id,
      public.leghevo_stable_request_uuid(
        'matchday-finalization-v2-source:'
          || p_matchday_id::text
          || ':'
          || v_fixture.id::text
          || ':'
          || coalesce(
            public.live_fixture_projection_input_hash_v1(v_fixture.id),
            'missing'
          )
      )
    );
  end loop;

  v_payload := public.compute_matchday_officialization_v2(
    p_league_id,
    p_matchday_id
  );

  if not coalesce((v_payload ->> 'available')::boolean, false) then
    raise exception 'Ufficializzazione non disponibile per questa giornata.';
  end if;

  if not coalesce((v_payload ->> 'providerComplete')::boolean, false) then
    raise exception 'Il provider non ha ancora chiuso tutte le partite reali della giornata.';
  end if;

  if not coalesce((v_payload ->> 'allReady')::boolean, false) then
    raise exception
      'Mancano voti o sostituzioni certificate: % partite pronte su %.',
      coalesce((v_payload ->> 'readyCount')::integer, 0),
      coalesce((v_payload ->> 'fixtureCount')::integer, 0);
  end if;

  v_input_hash := public.matchday_officialization_input_hash_v2(
    p_league_id,
    p_matchday_id
  );

  if v_input_hash is null then
    raise exception 'Impossibile calcolare l''impronta della giornata.';
  end if;

  select coalesce(max(run.finalization_revision), 0) + 1
  into v_revision
  from public.matchday_officialization_runs run
  where run.matchday_id = p_matchday_id;

  select coalesce(
    jsonb_agg(source.projection_id order by source.fixture_id),
    '[]'::jsonb
  )
  into v_source_projection_ids
  from (
    select
      fixture.id as fixture_id,
      coalesce(
        fixture.official_projection_id,
        current_projection.id
      ) as projection_id
    from public.fantasy_fixtures fixture
    left join public.live_fixture_projection_runs current_projection
      on fixture.finalized_at is null
     and current_projection.fixture_id = fixture.id
     and current_projection.superseded_at is null
    where fixture.league_id = p_league_id
      and fixture.matchday_id = p_matchday_id
  ) source;

  select coalesce(
    jsonb_agg(source.correction_run_id order by source.correction_run_id),
    '[]'::jsonb
  )
  into v_source_correction_run_ids
  from (
    select distinct fixture.correction_run_id
    from public.fantasy_fixtures fixture
    where fixture.league_id = p_league_id
      and fixture.matchday_id = p_matchday_id
      and fixture.correction_run_id is not null
  ) source;

  v_result_hash := md5(v_payload::text);

  perform set_config(
    'leghevo.matchday_officialization_context',
    'on',
    true
  );

  update public.matchday_officialization_runs run
  set superseded_at = now()
  where run.matchday_id = p_matchday_id
    and run.superseded_at is null;

  insert into public.matchday_officialization_runs (
    league_id,
    matchday_id,
    request_id,
    finalization_revision,
    input_hash,
    result_hash,
    fixture_count,
    finalized_fixture_count,
    source_projection_ids,
    source_correction_run_ids,
    result_payload,
    finalized_by
  )
  values (
    p_league_id,
    p_matchday_id,
    p_request_id,
    v_revision,
    v_input_hash,
    v_result_hash,
    v_fixture_count,
    v_fixture_count,
    v_source_projection_ids,
    v_source_correction_run_ids,
    v_payload,
    auth.uid()
  )
  returning * into v_run;

  update public.fantasy_fixtures fixture
  set
    home_base_points = nullif(
      projection.projection_payload #>> '{home,basePoints}',
      ''
    )::numeric,
    away_base_points = nullif(
      projection.projection_payload #>> '{away,basePoints}',
      ''
    )::numeric,
    home_defense_modifier = coalesce(
      nullif(
        projection.projection_payload #>> '{home,defenseModifier,bonus}',
        ''
      )::numeric,
      0
    ),
    away_defense_modifier = coalesce(
      nullif(
        projection.projection_payload #>> '{away,defenseModifier,bonus}',
        ''
      )::numeric,
      0
    ),
    home_bonus_applied = coalesce(
      nullif(
        projection.projection_payload #>> '{home,homeBonus}',
        ''
      )::numeric,
      0
    ),
    home_goal_margin_bonus = coalesce(
      nullif(
        projection.projection_payload #>> '{goalMargin,homeBonus}',
        ''
      )::smallint,
      0
    ),
    away_goal_margin_bonus = coalesce(
      nullif(
        projection.projection_payload #>> '{goalMargin,awayBonus}',
        ''
      )::smallint,
      0
    ),
    home_points = projection.home_points,
    away_points = projection.away_points,
    home_goals = projection.home_goals,
    away_goals = projection.away_goals,
    home_counted_players = projection.home_counted_players,
    away_counted_players = projection.away_counted_players,
    home_ready = projection.home_ready,
    away_ready = projection.away_ready,
    official_projection_id = projection.id,
    finalized_at = now(),
    finalized_by = auth.uid()
  from public.live_fixture_projection_runs projection
  where fixture.league_id = p_league_id
    and fixture.matchday_id = p_matchday_id
    and fixture.finalized_at is null
    and projection.fixture_id = fixture.id
    and projection.superseded_at is null;

  get diagnostics v_updated = row_count;

  if v_updated <> v_pending_count then
    raise exception
      'Ufficializzazione incompleta: % partite aggiornate su %.',
      v_updated,
      v_pending_count;
  end if;

  update public.fantasy_fixtures fixture
  set officialization_run_id = v_run.id
  where fixture.league_id = p_league_id
    and fixture.matchday_id = p_matchday_id
    and fixture.finalized_at is not null;

  select run.id
  into v_active_run_id
  from public.matchday_officialization_runs run
  where run.matchday_id = p_matchday_id
    and run.superseded_at is null;

  if v_active_run_id is distinct from v_run.id then
    raise exception 'La revisione ufficiale corrente non è coerente.';
  end if;

  return v_payload || jsonb_build_object(
    'officializationId', v_run.id,
    'officializationRevision', v_run.finalization_revision,
    'officializationInputHash', v_run.input_hash,
    'officializationHash', v_run.result_hash,
    'sourceCorrectionRunIds', v_run.source_correction_run_ids,
    'finalizedAt', v_run.finalized_at,
    'finalizedFixtureCount', v_fixture_count,
    'newlyFinalizedFixtureCount', v_updated,
    'idempotentReplay', false
  );
end;
$$;

