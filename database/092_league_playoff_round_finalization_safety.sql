create or replace function public.get_league_playoff_state_v4(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_state jsonb;
  v_playoff public.league_playoffs%rowtype;
  v_latest_run public.league_playoff_round_finalization_runs%rowtype;
  v_official_round_count integer := 0;
  v_certified_round_count integer := 0;
  v_current_officialization_ready boolean := false;
  v_rounds_certified boolean := false;
begin
  v_state := public.get_league_playoff_state_v3(p_league_id);

  select playoff.*
  into v_playoff
  from public.league_playoffs playoff
  where playoff.league_id = p_league_id;

  if v_playoff.id is not null then
    select count(*)::integer
    into v_official_round_count
    from public.league_playoff_rounds playoff_round
    where playoff_round.playoff_id = v_playoff.id
      and playoff_round.status = 'official';

    select count(*)::integer
    into v_certified_round_count
    from public.league_playoff_round_finalization_runs run
    where run.playoff_id = v_playoff.id;

    select run.*
    into v_latest_run
    from public.league_playoff_round_finalization_runs run
    where run.playoff_id = v_playoff.id
    order by run.requested_round_number desc, run.id desc
    limit 1;

    v_rounds_certified :=
      v_official_round_count = v_certified_round_count;

    if v_playoff.status = 'active' then
      select exists (
        select 1
        from public.league_playoff_rounds playoff_round
        join public.matchday_officialization_runs officialization
          on officialization.matchday_id = playoff_round.matchday_id
          and officialization.league_id = p_league_id
          and officialization.superseded_at is null
        where playoff_round.playoff_id = v_playoff.id
          and playoff_round.round_number = v_playoff.current_round
      ) into v_current_officialization_ready;
    end if;
  end if;

  return coalesce(v_state, '{}'::jsonb) || jsonb_build_object(
    'roundFinalizationPolicy', 'guarded_v1',
    'officialRoundCount', v_official_round_count,
    'certifiedRoundCount', v_certified_round_count,
    'roundsCertified', v_rounds_certified,
    'currentRoundOfficializationReady', v_current_officialization_ready,
    'canFinalizeCurrent',
      coalesce((v_state ->> 'canFinalizeCurrent')::boolean, false)
      and v_current_officialization_ready,
    'lastRoundRunId', v_latest_run.id,
    'lastCertifiedRound', v_latest_run.requested_round_number,
    'lastRoundFinalizedAt', v_latest_run.finalized_at
  );
end;
$$;

revoke all on function public.get_league_playoff_state_v4(uuid)
from public, anon, authenticated;
grant execute on function public.get_league_playoff_state_v4(uuid)
to authenticated;

create or replace function public.finalize_league_playoff_round_guarded_v1(
  p_league_id uuid,
  p_round_number smallint,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_league public.leagues%rowtype;
  v_playoff public.league_playoffs%rowtype;
  v_round public.league_playoff_rounds%rowtype;
  v_start_run public.league_playoff_start_runs%rowtype;
  v_officialization public.matchday_officialization_runs%rowtype;
  v_existing_run public.league_playoff_round_finalization_runs%rowtype;
  v_tie_count integer := 0;
  v_unready_count integer := 0;
  v_finalized_tie_count integer := 0;
  v_winner_count integer := 0;
  v_next_round_number smallint;
  v_input_hash text;
  v_result_hash text;
  v_state jsonb;
  v_completed boolean := false;
  v_payload jsonb;
  v_run_id bigint;
  v_playoff_id uuid;
  v_round_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if p_request_id is null then
    raise exception 'Identificativo richiesta ufficializzazione mancante.';
  end if;

  if p_round_number is null or p_round_number < 1 then
    raise exception 'Turno Playoff non valido.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'leghevo:league-playoff-round-finalization:' || p_league_id::text,
      0
    )
  );

  select run.*
  into v_existing_run
  from public.league_playoff_round_finalization_runs run
  where run.league_id = p_league_id
    and run.request_id = p_request_id;

  if found then
    if v_existing_run.requested_round_number <> p_round_number then
      raise exception
        'La richiesta idempotente è già associata a un turno differente.';
    end if;

    return public.get_league_playoff_state_v4(p_league_id)
      || jsonb_build_object(
        'idempotentReplay', true,
        'roundFinalizationRunId', v_existing_run.id
      );
  end if;

  select league.*
  into v_league
  from public.leagues league
  where league.id = p_league_id
  for update;

  if not found then
    raise exception 'Lega non trovata.';
  end if;

  if v_league.owner_id <> auth.uid() then
    raise exception 'Solo il Presidente può ufficializzare i playoff.';
  end if;

  select playoff.*
  into v_playoff
  from public.league_playoffs playoff
  where playoff.league_id = p_league_id
  for update;

  if not found or v_playoff.status = 'configured' then
    raise exception 'I playoff non sono ancora iniziati.';
  end if;

  v_playoff_id := v_playoff.id;

  if p_round_number > v_playoff.round_count then
    raise exception 'Il turno richiesto supera il numero di turni configurati.';
  end if;

  select playoff_round.*
  into v_round
  from public.league_playoff_rounds playoff_round
  where playoff_round.playoff_id = v_playoff.id
    and playoff_round.round_number = p_round_number
  for update;

  if not found then
    raise exception 'Turno Playoff non trovato.';
  end if;

  v_round_id := v_round.id;

  select run.*
  into v_existing_run
  from public.league_playoff_round_finalization_runs run
  where run.round_id = v_round.id;

  if found then
    return public.get_league_playoff_state_v4(p_league_id)
      || jsonb_build_object(
        'idempotentReplay', true,
        'roundFinalizationRunId', v_existing_run.id
      );
  end if;

  if v_playoff.status = 'completed' then
    raise exception
      'I Playoff risultano conclusi ma manca il certificato del turno finale.';
  end if;

  if p_round_number <> v_playoff.current_round then
    raise exception 'Il turno richiesto non è quello corrente dei Playoff.';
  end if;

  select run.*
  into v_start_run
  from public.league_playoff_start_runs run
  where run.playoff_id = v_playoff.id;

  if not found then
    raise exception 'L''avvio dei Playoff non è certificato.';
  end if;

  select officialization.*
  into v_officialization
  from public.matchday_officialization_runs officialization
  where officialization.league_id = p_league_id
    and officialization.matchday_id = v_round.matchday_id
    and officialization.superseded_at is null;

  if not found then
    raise exception
      'Prima di ufficializzare i Playoff devi ufficializzare la giornata di campionato.';
  end if;

  perform public.refresh_league_playoff_round_internal(
    v_playoff.id,
    p_round_number
  );

  select
    count(*)::integer,
    count(*) filter (
      where tie.home_team_id is null
        or tie.away_team_id is null
        or not tie.home_ready
        or not tie.away_ready
        or tie.home_points is null
        or tie.away_points is null
        or tie.home_goals is null
        or tie.away_goals is null
    )::integer
  into v_tie_count, v_unready_count
  from public.league_playoff_ties tie
  where tie.round_id = v_round.id;

  if v_tie_count < 1 then
    raise exception 'Il turno Playoff non contiene sfide.';
  end if;

  if v_unready_count > 0 then
    raise exception
      'Mancano ancora voti definitivi per % sfide.',
      v_unready_count;
  end if;

  v_input_hash := public.compute_league_playoff_round_input_hash_v1(
    v_playoff.id,
    p_round_number,
    v_officialization.id
  );

  if v_input_hash is null or char_length(v_input_hash) <> 64 then
    raise exception 'Impossibile certificare la sorgente del turno Playoff.';
  end if;

  perform public.finalize_league_playoff_round_legacy_internal_v1(
    p_league_id
  );

  select playoff.*
  into v_playoff
  from public.league_playoffs playoff
  where playoff.id = v_playoff_id;

  select playoff_round.*
  into v_round
  from public.league_playoff_rounds playoff_round
  where playoff_round.id = v_round_id;

  select
    count(*) filter (where tie.finalized_at is not null)::integer,
    count(*) filter (where tie.winner_team_id is not null)::integer
  into v_finalized_tie_count, v_winner_count
  from public.league_playoff_ties tie
  where tie.round_id = v_round.id;

  if v_round.status <> 'official'
    or v_round.finalized_at is null
    or v_finalized_tie_count <> v_tie_count
    or v_winner_count <> v_tie_count then
    raise exception
      'L''ufficializzazione Playoff non ha prodotto un esito completo.';
  end if;

  if p_round_number = v_playoff.round_count then
    v_completed := true;
    v_next_round_number := null;

    if v_playoff.status <> 'completed'
      or v_playoff.champion_team_id is null
      or v_playoff.runner_up_team_id is null then
      raise exception 'La finale Playoff non ha prodotto un podio valido.';
    end if;
  else
    v_next_round_number := p_round_number + 1;

    if v_playoff.status <> 'active'
      or v_playoff.current_round <> v_next_round_number then
      raise exception 'Il tabellone non è avanzato al turno successivo.';
    end if;

    if exists (
      select 1
      from public.league_playoff_ties tie
      join public.league_playoff_rounds playoff_round
        on playoff_round.id = tie.round_id
      where playoff_round.playoff_id = v_playoff.id
        and playoff_round.round_number = v_next_round_number
        and (tie.home_team_id is null or tie.away_team_id is null)
    ) then
      raise exception 'Il turno successivo non contiene tutti i qualificati.';
    end if;
  end if;

  v_result_hash := public.compute_league_playoff_round_result_hash_v1(
    v_playoff.id,
    p_round_number
  );

  if v_result_hash is null or char_length(v_result_hash) <> 64 then
    raise exception 'Impossibile certificare l''esito del turno Playoff.';
  end if;

  v_payload := jsonb_build_object(
    'playoffId', v_playoff.id,
    'roundId', v_round.id,
    'roundNumber', p_round_number,
    'matchdayId', v_round.matchday_id,
