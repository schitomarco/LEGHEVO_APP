create table if not exists public.league_playoff_round_finalization_runs (
  id bigint generated by default as identity primary key,
  league_id uuid not null
    references public.leagues(id) on delete cascade,
  playoff_id uuid not null
    references public.league_playoffs(id) on delete cascade,
  round_id uuid not null unique
    references public.league_playoff_rounds(id) on delete cascade,
  start_run_id bigint not null
    references public.league_playoff_start_runs(id) on delete restrict,
  matchday_officialization_run_id bigint
    references public.matchday_officialization_runs(id) on delete restrict,
  request_id uuid not null,
  requested_by uuid not null
    references public.profiles(id) on delete restrict,
  requested_round_number smallint not null
    check (requested_round_number between 1 and 3),
  source_mode text not null
    check (source_mode in ('guarded_v1', 'legacy_backfill')),
  input_hash text not null check (char_length(input_hash) = 64),
  result_hash text not null check (char_length(result_hash) = 64),
  tie_count integer not null check (tie_count >= 1),
  finalized_tie_count integer not null check (finalized_tie_count >= 1),
  winner_count integer not null check (winner_count >= 1),
  next_round_number smallint check (next_round_number between 1 and 3),
  completed_playoffs boolean not null default false,
  champion_team_id uuid references public.fantasy_teams(id) on delete restrict,
  runner_up_team_id uuid references public.fantasy_teams(id) on delete restrict,
  result_payload jsonb not null default '{}'::jsonb,
  finalized_at timestamptz not null default now(),
  check (finalized_tie_count <= tie_count),
  check (winner_count <= finalized_tie_count),
  check (
    not completed_playoffs
    or (
      champion_team_id is not null
      and runner_up_team_id is not null
      and champion_team_id <> runner_up_team_id
    )
  )
);

