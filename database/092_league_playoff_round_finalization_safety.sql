-- Backfill non distruttivo dei turni già ufficiali.
insert into public.league_playoff_round_finalization_runs (
  league_id,
  playoff_id,
  round_id,
  start_run_id,
  matchday_officialization_run_id,
  request_id,
  requested_by,
  requested_round_number,
  source_mode,
  input_hash,
  result_hash,
  tie_count,
  finalized_tie_count,
  winner_count,
  next_round_number,
  completed_playoffs,
  champion_team_id,
  runner_up_team_id,
  result_payload,
  finalized_at
)
select
  playoff.league_id,
  playoff.id,
  playoff_round.id,
  start_run.id,
  officialization.id,
  public.leghevo_stable_request_uuid(
    'league-playoff-round-legacy:' || playoff_round.id::text
  ),
  coalesce(playoff_round.finalized_by, playoff.configured_by),
  playoff_round.round_number,
  'legacy_backfill',
  public.compute_league_playoff_round_input_hash_v1(
    playoff.id,
    playoff_round.round_number,
    officialization.id
  ),
  public.compute_league_playoff_round_result_hash_v1(
    playoff.id,
    playoff_round.round_number
  ),
  tie_counts.tie_count,
  tie_counts.finalized_tie_count,
  tie_counts.winner_count,
  case
    when playoff_round.round_number < playoff.round_count
      then playoff_round.round_number + 1
    else null
  end,
  playoff_round.round_number = playoff.round_count
    and playoff.status = 'completed',
  case
    when playoff_round.round_number = playoff.round_count
      then playoff.champion_team_id
    else null
  end,
  case
    when playoff_round.round_number = playoff.round_count
      then playoff.runner_up_team_id
    else null
  end,
  jsonb_build_object(
    'playoffId', playoff.id,
    'roundId', playoff_round.id,
    'roundNumber', playoff_round.round_number,
    'legacyBackfill', true,
    'matchdayOfficializationRunId', officialization.id
  ),
  coalesce(playoff_round.finalized_at, playoff.completed_at, now())
from public.league_playoffs playoff
join public.league_playoff_rounds playoff_round
  on playoff_round.playoff_id = playoff.id
join public.league_playoff_start_runs start_run
  on start_run.playoff_id = playoff.id
cross join lateral (
  select
    count(*)::integer as tie_count,
    count(*) filter (where tie.finalized_at is not null)::integer
      as finalized_tie_count,
    count(*) filter (where tie.winner_team_id is not null)::integer
      as winner_count
  from public.league_playoff_ties tie
  where tie.round_id = playoff_round.id
) tie_counts
left join lateral (
  select officialization_run.*
  from public.matchday_officialization_runs officialization_run
  where officialization_run.league_id = playoff.league_id
    and officialization_run.matchday_id = playoff_round.matchday_id
    and officialization_run.superseded_at is null
  order by officialization_run.finalization_revision desc
  limit 1
) officialization on true
where playoff_round.status = 'official'
  and tie_counts.tie_count >= 1
  and tie_counts.finalized_tie_count = tie_counts.tie_count
  and tie_counts.winner_count = tie_counts.tie_count
  and not exists (
    select 1
    from public.league_playoff_round_finalization_runs existing_run
    where existing_run.round_id = playoff_round.id
  );

create or replace function public.get_league_playoff_round_integrity_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_playoff public.league_playoffs%rowtype;
  v_official_round_count integer := 0;
  v_certified_round_count integer := 0;
  v_hash_mismatch_count integer := 0;
  v_source_mismatch_count integer := 0;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if not public.is_league_member(p_league_id)
    and not public.is_league_admin(p_league_id) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  select playoff.*
  into v_playoff
  from public.league_playoffs playoff
  where playoff.league_id = p_league_id;

  if v_playoff.id is not null then
    select count(*)::integer
    into v_official_round_count
    from public.league_playoff_rounds playoff_round
    where playoff_round.playoff_id = v_playoff.id
      and playoff_round.status = 'official';

    select count(*)::integer
    into v_certified_round_count
    from public.league_playoff_round_finalization_runs run
    where run.playoff_id = v_playoff.id;

    select count(*)::integer
    into v_hash_mismatch_count
    from public.league_playoff_round_finalization_runs run
    where run.playoff_id = v_playoff.id
      and (
        run.input_hash <> public.compute_league_playoff_round_input_hash_v1(
          run.playoff_id,
          run.requested_round_number,
          run.matchday_officialization_run_id
        )
        or run.result_hash <> public.compute_league_playoff_round_result_hash_v1(
          run.playoff_id,
          run.requested_round_number
        )
      );

    select count(*)::integer
    into v_source_mismatch_count
    from public.league_playoff_round_finalization_runs run
    join public.league_playoff_rounds playoff_round
      on playoff_round.id = run.round_id
    where run.playoff_id = v_playoff.id
      and (
        playoff_round.playoff_id <> run.playoff_id
        or playoff_round.round_number <> run.requested_round_number
        or not exists (
          select 1
          from public.league_playoff_start_runs start_run
          where start_run.id = run.start_run_id
            and start_run.playoff_id = run.playoff_id
        )
        or (
          run.source_mode = 'guarded_v1'
          and not exists (
            select 1
            from public.matchday_officialization_runs officialization
            where officialization.id = run.matchday_officialization_run_id
              and officialization.league_id = run.league_id
              and officialization.matchday_id = playoff_round.matchday_id
          )
        )
      );
  end if;

  return jsonb_build_object(
    'leagueId', p_league_id,
    'ready',
      v_playoff.id is null
      or v_playoff.status = 'configured'
      or (
        v_official_round_count = v_certified_round_count
        and v_hash_mismatch_count = 0
        and v_source_mismatch_count = 0
      ),
    'playoffExists', v_playoff.id is not null,
    'playoffStatus', v_playoff.status,
    'officialRoundCount', v_official_round_count,
    'certifiedRoundCount', v_certified_round_count,
    'hashMismatchCount', v_hash_mismatch_count,
    'sourceMismatchCount', v_source_mismatch_count
  );
end;
$$;

