create or replace function public.compute_league_playoff_round_input_hash_v1(
  p_playoff_id uuid,
  p_round_number smallint,
  p_matchday_officialization_run_id bigint
)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select public.leghevo_sha256_hex_v1(
    coalesce(
      (
        select string_agg(
          tie.id::text || ':'
          || tie.bracket_position::text || ':'
          || coalesce(tie.home_team_id::text, '-') || ':'
          || coalesce(tie.away_team_id::text, '-') || ':'
          || coalesce(tie.home_seed::text, '-') || ':'
          || coalesce(tie.away_seed::text, '-') || ':'
          || coalesce(tie.home_points::text, '-') || ':'
          || coalesce(tie.away_points::text, '-') || ':'
          || coalesce(tie.home_goals::text, '-') || ':'
          || coalesce(tie.away_goals::text, '-') || ':'
          || tie.home_ready::text || ':'
          || tie.away_ready::text || ':'
          || tie.home_counted_players::text || ':'
          || tie.away_counted_players::text,
          '|' order by tie.bracket_position
        )
        from public.league_playoff_ties tie
        join public.league_playoff_rounds playoff_round
          on playoff_round.id = tie.round_id
        where playoff_round.playoff_id = p_playoff_id
          and playoff_round.round_number = p_round_number
      ),
      'empty'
    ) || '#'
    || coalesce(
      (
        select officialization.id::text || ':'
          || officialization.finalization_revision::text || ':'
          || officialization.input_hash || ':'
          || officialization.result_hash || ':'
          || officialization.fixture_count::text || ':'
          || officialization.finalized_fixture_count::text
        from public.matchday_officialization_runs officialization
        where officialization.id = p_matchday_officialization_run_id
      ),
      'legacy-no-officialization'
    )
  );
$$;

