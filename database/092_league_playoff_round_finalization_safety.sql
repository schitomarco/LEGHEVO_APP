create or replace function public.compute_league_playoff_round_result_hash_v1(
  p_playoff_id uuid,
  p_round_number smallint
)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select public.leghevo_sha256_hex_v1(
    coalesce(
      (
        select playoff_round.id::text || ':'
          || playoff_round.status || ':'
          || coalesce(
            extract(epoch from playoff_round.finalized_at)::text,
            '-'
          ) || ':'
          || coalesce(playoff_round.finalized_by::text, '-')
        from public.league_playoff_rounds playoff_round
        where playoff_round.playoff_id = p_playoff_id
          and playoff_round.round_number = p_round_number
      ),
      'missing-round'
    ) || '#'
    || coalesce(
      (
        select string_agg(
          tie.id::text || ':'
          || tie.bracket_position::text || ':'
          || coalesce(tie.winner_team_id::text, '-') || ':'
          || coalesce(tie.decided_by, '-') || ':'
          || coalesce(
            extract(epoch from tie.finalized_at)::text,
            '-'
          ),
          '|' order by tie.bracket_position
        )
        from public.league_playoff_ties tie
        join public.league_playoff_rounds playoff_round
          on playoff_round.id = tie.round_id
        where playoff_round.playoff_id = p_playoff_id
          and playoff_round.round_number = p_round_number
      ),
      'empty'
    ) || '#'
    || coalesce(
      (
        select string_agg(
          tie.bracket_position::text || ':'
          || coalesce(tie.home_team_id::text, '-') || ':'
          || coalesce(tie.home_seed::text, '-') || ':'
          || coalesce(tie.away_team_id::text, '-') || ':'
          || coalesce(tie.away_seed::text, '-'),
          '|' order by tie.bracket_position
        )
        from public.league_playoff_ties tie
        join public.league_playoff_rounds playoff_round
          on playoff_round.id = tie.round_id
        where playoff_round.playoff_id = p_playoff_id
          and playoff_round.round_number = p_round_number + 1
      ),
      'no-next-round'
    ) || '#'
    || coalesce(
      (
        select case
          when p_round_number = playoff.round_count then
            playoff.status || ':'
            || coalesce(playoff.champion_team_id::text, '-') || ':'
            || coalesce(playoff.runner_up_team_id::text, '-') || ':'
            || coalesce(
              extract(epoch from playoff.completed_at)::text,
              '-'
            )
          else 'round-advanced'
        end
        from public.league_playoffs playoff
        where playoff.id = p_playoff_id
      ),
      'missing-playoff'
    )
  );
$$;

