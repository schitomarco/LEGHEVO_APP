create or replace function public.get_my_lineup_workspace_v3(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_workspace jsonb;
  v_team_id uuid;
  v_matchday_id uuid;
  v_event public.lineup_deadline_events%rowtype;
  v_matchday public.matchdays%rowtype;
  v_deadline_outcome text;
  v_deadline_certified boolean := false;
  v_immutable boolean := false;
begin
  v_workspace := public.get_my_lineup_workspace_v2(p_league_id);

  if not coalesce((v_workspace ->> 'available')::boolean, false) then
    return v_workspace || jsonb_build_object(
      'deadlinePolicy', 'guarded_v1',
      'deadlineCertified', false,
      'deadlineEventReady',
        to_regclass('public.lineup_deadline_events') is not null,
      'immutableAfterLock', false
    );
  end if;

  v_team_id := (v_workspace ->> 'teamId')::uuid;
  v_matchday_id := (v_workspace -> 'matchday' ->> 'id')::uuid;

  select matchday.*
  into v_matchday
  from public.matchdays matchday
  where matchday.id = v_matchday_id;

  select event.*
  into v_event
  from public.lineup_deadline_events event
  where event.fantasy_team_id = v_team_id
    and event.matchday_id = v_matchday_id;

  if found then
    v_deadline_outcome := v_event.outcome;
    v_deadline_certified := true;
  elsif now() < v_matchday.locks_at then
    v_deadline_outcome := 'open';
  else
    v_deadline_outcome := 'processing';
  end if;

  v_immutable := now() >= v_matchday.locks_at
    or v_deadline_certified;

  return v_workspace || jsonb_build_object(
    'deadlinePolicy', 'guarded_v1',
    'deadlineOutcome', v_deadline_outcome,
    'deadlineCertified', v_deadline_certified,
    'deadlineProcessedAt', v_event.processed_at,
    'deadlineEventReady', true,
    'immutableAfterLock', v_immutable,
    'matchdayLineupsFinalizedAt', v_matchday.lineups_finalized_at,
    'matchdayLineupLockRevision', v_matchday.lineup_lock_revision,
    'matchdayLineupLockHash', v_matchday.lineup_lock_hash,
    'canSubmit',
      coalesce((v_workspace ->> 'canSubmit')::boolean, false)
      and not v_immutable
  );
end;
$$;

create or replace function public.get_league_lineup_integrity_v2(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_base jsonb;
  v_past_team_slots integer := 0;
  v_deadline_event_count integer := 0;
  v_missing_event_count integer := 0;
  v_locked_without_event_count integer := 0;
  v_event_without_lineup_count integer := 0;
  v_hash_issue_count integer := 0;
  v_finalization_issue_count integer := 0;
  v_triggers_ready boolean := false;
  v_healthy boolean := false;
begin
  v_base := public.get_league_lineup_integrity_v1(p_league_id);

  select count(*)::integer
  into v_past_team_slots
  from (
    select fixture.matchday_id, fixture.home_team_id as fantasy_team_id
    from public.fantasy_fixtures fixture
    join public.matchdays matchday
      on matchday.id = fixture.matchday_id
    where fixture.league_id = p_league_id
      and matchday.locks_at <= now()

    union

    select fixture.matchday_id, fixture.away_team_id as fantasy_team_id
    from public.fantasy_fixtures fixture
    join public.matchdays matchday
      on matchday.id = fixture.matchday_id
    where fixture.league_id = p_league_id
      and matchday.locks_at <= now()
  ) scheduled;

  select count(*)::integer
  into v_deadline_event_count
  from public.lineup_deadline_events event
  where event.league_id = p_league_id;

  v_missing_event_count := greatest(
    v_past_team_slots - v_deadline_event_count,
    0
  );

  select count(*)::integer
  into v_locked_without_event_count
  from public.lineups lineup
  join public.fantasy_teams team
    on team.id = lineup.fantasy_team_id
  where team.league_id = p_league_id
    and lineup.status = 'locked'
    and not exists (
      select 1
      from public.lineup_deadline_events event
      where event.fantasy_team_id = lineup.fantasy_team_id
        and event.matchday_id = lineup.matchday_id
    );

  select count(*)::integer
  into v_event_without_lineup_count
  from public.lineup_deadline_events event
  where event.league_id = p_league_id
    and event.outcome in ('manager', 'carried')
    and event.lineup_id is null;

  select count(*)::integer
  into v_hash_issue_count
  from public.lineup_deadline_events event
  where event.league_id = p_league_id
    and event.outcome in ('manager', 'carried')
    and event.content_hash is distinct from
      public.compute_lineup_content_hash(event.lineup_id);

  select count(*)::integer
  into v_finalization_issue_count
  from public.matchdays matchday
  where matchday.lineups_finalized_at is not null
    and exists (
      select 1
      from public.fantasy_fixtures fixture
      where fixture.matchday_id = matchday.id
        and fixture.league_id = p_league_id
    )
    and (
      matchday.lineup_lock_hash is null
      or matchday.lineup_lock_revision < 1
      or coalesce(
        (matchday.lineup_lock_summary ->> 'finalized')::boolean,
        false
      ) is false
    );

  select count(*) = 2
  into v_triggers_ready
  from pg_catalog.pg_trigger trigger_row
  where not trigger_row.tgisinternal
    and trigger_row.tgname in (
      'lineups_prevent_mutation_after_deadline',
      'lineup_entries_prevent_mutation_after_deadline'
    );

  v_healthy :=
    coalesce((v_base ->> 'healthy')::boolean, true)
    and v_missing_event_count = 0
    and v_locked_without_event_count = 0
    and v_event_without_lineup_count = 0
    and v_hash_issue_count = 0
    and v_finalization_issue_count = 0
    and v_triggers_ready;

  return v_base || jsonb_build_object(
    'version', 2,
    'deadlinePolicy', 'guarded_v1',
    'pastTeamSlots', v_past_team_slots,
    'deadlineEventCount', v_deadline_event_count,
    'missingDeadlineEventCount', v_missing_event_count,
    'lockedWithoutDeadlineEventCount', v_locked_without_event_count,
    'eventWithoutLineupCount', v_event_without_lineup_count,
    'deadlineHashIssueCount', v_hash_issue_count,
    'matchdayFinalizationIssueCount', v_finalization_issue_count,
    'deadlineMutationTriggersReady', v_triggers_ready,
    'healthy', v_healthy
  );
end;
$$;

