begin;

alter table public.lineups
  add column if not exists deadline_lock_revision integer not null default 0,
  add column if not exists deadline_outcome text,
  add column if not exists deadline_request_id uuid;

alter table public.lineups
  drop constraint if exists lineups_deadline_lock_revision_check;
alter table public.lineups
  add constraint lineups_deadline_lock_revision_check
  check (deadline_lock_revision >= 0);

alter table public.lineups
  drop constraint if exists lineups_deadline_outcome_check;
alter table public.lineups
  add constraint lineups_deadline_outcome_check
  check (
    deadline_outcome is null
    or deadline_outcome in ('manager', 'carried')
  );

alter table public.matchdays
  add column if not exists lineups_finalized_at timestamptz,
  add column if not exists lineup_lock_revision integer not null default 0,
  add column if not exists lineup_lock_request_id uuid,
  add column if not exists lineup_lock_hash text,
  add column if not exists lineup_lock_summary jsonb not null default '{}'::jsonb;

alter table public.matchdays
  drop constraint if exists matchdays_lineup_lock_revision_check;
alter table public.matchdays
  add constraint matchdays_lineup_lock_revision_check
  check (lineup_lock_revision >= 0);

alter table public.matchdays
  drop constraint if exists matchdays_lineup_lock_hash_check;
alter table public.matchdays
  add constraint matchdays_lineup_lock_hash_check
  check (lineup_lock_hash is null or length(lineup_lock_hash) = 32);

comment on column public.lineups.deadline_lock_revision is
  'Revisione del congelamento effettuato alla scadenza della giornata.';
comment on column public.lineups.deadline_outcome is
  'manager se consegnata dal Mister, carried se recuperata dalla giornata precedente.';
comment on column public.matchdays.lineups_finalized_at is
  'Istante in cui tutte le distinte della giornata sono state congelate o classificate come mancanti.';
comment on column public.matchdays.lineup_lock_hash is
  'Impronta deterministica degli esiti di blocco di tutte le squadre della giornata.';

create table if not exists public.lineup_deadline_events (
  id bigint generated by default as identity primary key,
  league_id uuid not null
    references public.leagues(id) on delete cascade,
  fantasy_team_id uuid not null
    references public.fantasy_teams(id) on delete cascade,
  matchday_id uuid not null
    references public.matchdays(id) on delete cascade,
  lineup_id uuid
    references public.lineups(id) on delete set null,
  source_lineup_id uuid
    references public.lineups(id) on delete set null,
  request_id uuid not null unique,
  outcome text not null,
  content_hash text,
  locks_at timestamptz not null,
  processed_at timestamptz not null default now(),
  response_payload jsonb not null default '{}'::jsonb,
  constraint lineup_deadline_events_outcome_check
    check (outcome in ('manager', 'carried', 'missing')),
  constraint lineup_deadline_events_hash_check
    check (content_hash is null or length(content_hash) = 32),
  unique (fantasy_team_id, matchday_id)
);

create index if not exists lineup_deadline_events_league_matchday_idx
  on public.lineup_deadline_events (league_id, matchday_id, outcome);

alter table public.lineup_deadline_events enable row level security;

drop policy if exists lineup_deadline_events_read_members
on public.lineup_deadline_events;
create policy lineup_deadline_events_read_members
on public.lineup_deadline_events
for select to authenticated
using (public.is_league_member(league_id));

revoke all on table public.lineup_deadline_events
from public, anon, authenticated;
grant select on table public.lineup_deadline_events
to authenticated;

create or replace function public.leghevo_stable_request_uuid(
  p_value text
)
returns uuid
language sql
immutable
security definer
set search_path = ''
as $$
  select (
    substr(md5(coalesce(p_value, '')), 1, 8)
    || '-'
    || substr(md5(coalesce(p_value, '')), 9, 4)
    || '-4'
    || substr(md5(coalesce(p_value, '')), 14, 3)
    || '-a'
    || substr(md5(coalesce(p_value, '')), 18, 3)
    || '-'
    || substr(md5(coalesce(p_value, '')), 21, 12)
  )::uuid;
$$;

revoke all on function public.leghevo_stable_request_uuid(text)
from public, anon, authenticated;

create or replace function public.prevent_lineup_mutation_after_deadline()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_matchday_id uuid;
  v_locks_at timestamptz;
  v_internal_context text;
begin
  v_internal_context := current_setting(
    'leghevo.lineup_deadline_context',
    true
  );

  if coalesce(v_internal_context, '') = 'on' then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  v_matchday_id := case
    when tg_op = 'DELETE' then old.matchday_id
    else new.matchday_id
  end;

  select matchday.locks_at
  into v_locks_at
  from public.matchdays matchday
  where matchday.id = v_matchday_id;

  if v_locks_at is not null and now() >= v_locks_at then
    raise exception
      'Formazione congelata: la scadenza della giornata è già trascorsa.';
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

create or replace function public.prevent_lineup_entry_mutation_after_deadline()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_lineup_id uuid;
  v_locks_at timestamptz;
  v_internal_context text;
begin
  v_internal_context := current_setting(
    'leghevo.lineup_deadline_context',
    true
  );

  if coalesce(v_internal_context, '') = 'on' then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  v_lineup_id := case
    when tg_op = 'DELETE' then old.lineup_id
    else new.lineup_id
  end;

  select matchday.locks_at
  into v_locks_at
  from public.lineups lineup
  join public.matchdays matchday
    on matchday.id = lineup.matchday_id
  where lineup.id = v_lineup_id;

  if v_locks_at is not null and now() >= v_locks_at then
    raise exception
      'Distinta congelata: titolari e panchina non sono più modificabili.';
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

