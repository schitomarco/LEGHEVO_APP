create or replace function public.ensure_matchday_lineups(
  p_matchday_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
begin
  return public.ensure_matchday_lineups_guarded_v1(
    p_matchday_id,
    public.leghevo_stable_request_uuid(
      'matchday-lineups:' || p_matchday_id::text
