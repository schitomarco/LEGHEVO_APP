create or replace function public.lock_or_carry_team_lineup_guarded_v1(
  p_fantasy_team_id uuid,
  p_matchday_id uuid,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_team public.fantasy_teams%rowtype;
  v_matchday public.matchdays%rowtype;
  v_existing_lineup public.lineups%rowtype;
  v_event public.lineup_deadline_events%rowtype;
  v_preview jsonb;
  v_lineup_id uuid;
  v_source_lineup_id uuid;
  v_outcome text;
  v_hash text;
  v_response jsonb;
begin
  if p_request_id is null then
    raise exception 'Identificativo di blocco mancante.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'lineup-deadline:'
        || p_fantasy_team_id::text
        || ':'
        || p_matchday_id::text,
      0
    )
  );

  select event.*
  into v_event
  from public.lineup_deadline_events event
  where event.request_id = p_request_id;

  if found then
    if v_event.fantasy_team_id <> p_fantasy_team_id
      or v_event.matchday_id <> p_matchday_id then
      raise exception 'La chiave di blocco è già stata utilizzata.';
    end if;

    return v_event.response_payload
      || jsonb_build_object('idempotentReplay', true);
  end if;

  select event.*
  into v_event
  from public.lineup_deadline_events event
  where event.fantasy_team_id = p_fantasy_team_id
    and event.matchday_id = p_matchday_id;

  if found then
    return v_event.response_payload
      || jsonb_build_object('idempotentReplay', true);
  end if;

  select team.*
  into v_team
  from public.fantasy_teams team
  where team.id = p_fantasy_team_id
  for update;

  if not found then
    raise exception 'Squadra non trovata.';
  end if;

  select matchday.*
  into v_matchday
  from public.matchdays matchday
  where matchday.id = p_matchday_id
  for update;

  if not found then
    raise exception 'Giornata non trovata.';
  end if;

  if not public.team_competes_on_matchday(
    p_fantasy_team_id,
    p_matchday_id
  ) then
    raise exception 'La squadra non disputa questa giornata.';
  end if;

  if now() < v_matchday.locks_at then
    return jsonb_build_object(
      'teamId', p_fantasy_team_id,
      'matchdayId', p_matchday_id,
      'outcome', 'pending',
      'locksAt', v_matchday.locks_at,
      'secondsUntilLock', greatest(
        floor(extract(epoch from (v_matchday.locks_at - now())))::integer,
        0
      ),
      'idempotentReplay', false
    );
  end if;

  select lineup.*
  into v_existing_lineup
  from public.lineups lineup
  where lineup.fantasy_team_id = p_fantasy_team_id
    and lineup.matchday_id = p_matchday_id
  for update;

  if found and v_existing_lineup.status in ('submitted', 'locked') then
    perform set_config('leghevo.lineup_deadline_context', 'on', true);

    update public.lineups lineup
    set
      status = 'locked',
      locked_at = coalesce(lineup.locked_at, v_matchday.locks_at),
      deadline_lock_revision = greatest(
        coalesce(lineup.deadline_lock_revision, 0),
        1
      ),
      deadline_outcome = coalesce(
        lineup.deadline_outcome,
        lineup.submission_source
      ),
      deadline_request_id = coalesce(
        lineup.deadline_request_id,
        p_request_id
      ),
      updated_at = greatest(
        coalesce(lineup.updated_at, v_matchday.locks_at),
        v_matchday.locks_at
      )
    where lineup.id = v_existing_lineup.id
    returning * into v_existing_lineup;

    perform set_config('leghevo.lineup_deadline_context', 'off', true);

    v_lineup_id := v_existing_lineup.id;
    v_source_lineup_id := v_existing_lineup.source_lineup_id;
    v_outcome := case
      when v_existing_lineup.submission_source = 'carried' then 'carried'
      else 'manager'
    end;
    v_hash := public.compute_lineup_content_hash(v_lineup_id);

    perform set_config('leghevo.lineup_deadline_context', 'on', true);
    update public.lineups lineup
    set
      content_hash = v_hash,
      deadline_outcome = v_outcome
    where lineup.id = v_lineup_id;
    perform set_config('leghevo.lineup_deadline_context', 'off', true);
  else
    if found then
      perform set_config('leghevo.lineup_deadline_context', 'on', true);
      delete from public.lineups lineup
      where lineup.id = v_existing_lineup.id;
      perform set_config('leghevo.lineup_deadline_context', 'off', true);
    end if;

    v_preview := public.get_reusable_lineup_preview(
      p_fantasy_team_id,
      p_matchday_id
    );

    if v_preview is null then
      v_outcome := 'missing';
      v_lineup_id := null;
      v_source_lineup_id := null;
      v_hash := null;
    else
      v_outcome := 'carried';
      v_source_lineup_id := (v_preview ->> 'sourceLineupId')::uuid;

      perform set_config('leghevo.lineup_deadline_context', 'on', true);

      insert into public.lineups (
        fantasy_team_id,
        matchday_id,
        formation,
        status,
        submitted_at,
        submission_source,
        source_lineup_id,
        locked_at,
        submission_revision,
        first_submitted_at,
        updated_at,
        deadline_lock_revision,
        deadline_outcome,
        deadline_request_id
      ) values (
        p_fantasy_team_id,
        p_matchday_id,
        v_preview ->> 'formation',
        'locked',
        v_matchday.locks_at,
        'carried',
        v_source_lineup_id,
        v_matchday.locks_at,
        1,
        v_matchday.locks_at,
        v_matchday.locks_at,
        1,
        'carried',
        p_request_id
      )
      on conflict (fantasy_team_id, matchday_id) do nothing
      returning id into v_lineup_id;

      if v_lineup_id is null then
        select lineup.id
        into v_lineup_id
        from public.lineups lineup
        where lineup.fantasy_team_id = p_fantasy_team_id
          and lineup.matchday_id = p_matchday_id;
      else
        insert into public.lineup_entries (
          lineup_id,
          athlete_id,
          slot,
          is_starter,
          captain
        )
        select
          v_lineup_id,
          item.value::uuid,
          item.ordinality::smallint,
          true,
          false
        from jsonb_array_elements_text(
          v_preview -> 'starterIds'
        ) with ordinality as item(value, ordinality);

        insert into public.lineup_entries (
          lineup_id,
          athlete_id,
          slot,
          is_starter,
          captain
        )
        select
          v_lineup_id,
          item.value::uuid,
          (11 + item.ordinality)::smallint,
          false,
          false
        from jsonb_array_elements_text(
          v_preview -> 'benchIds'
        ) with ordinality as item(value, ordinality);
      end if;

      v_hash := public.compute_lineup_content_hash(v_lineup_id);

      update public.lineups lineup
      set content_hash = v_hash
      where lineup.id = v_lineup_id;

      perform set_config('leghevo.lineup_deadline_context', 'off', true);
    end if;
  end if;

  v_response := jsonb_build_object(
    'leagueId', v_team.league_id,
    'teamId', p_fantasy_team_id,
    'matchdayId', p_matchday_id,
    'lineupId', v_lineup_id,
    'sourceLineupId', v_source_lineup_id,
    'outcome', v_outcome,
    'contentHash', v_hash,
    'locksAt', v_matchday.locks_at,
    'processedAt', now(),
    'idempotentReplay', false
  );

  insert into public.lineup_deadline_events (
    league_id,
    fantasy_team_id,
    matchday_id,
    lineup_id,
    source_lineup_id,
    request_id,
    outcome,
    content_hash,
    locks_at,
    response_payload
  ) values (
    v_team.league_id,
    p_fantasy_team_id,
    p_matchday_id,
    v_lineup_id,
    v_source_lineup_id,
    p_request_id,
    v_outcome,
    v_hash,
    v_matchday.locks_at,
    v_response
  );

  if v_outcome = 'missing' then
    perform public.create_user_notification(
      v_team.manager_id,
      v_team.league_id,
      'lineup',
      'Formazione non consegnata',
      'Non esisteva una distinta precedente valida: la giornata '
        || v_matchday.number
        || ' sarà calcolata con 0 fantapunti.',
      'lineup',
      jsonb_build_object(
        'event', 'lineup_missing',
        'matchday_id', p_matchday_id,
        'matchday_number', v_matchday.number,
        'fantasy_team_id', p_fantasy_team_id
      ),
      'lineup:missing:'
        || p_fantasy_team_id::text
        || ':'
        || p_matchday_id::text
    );
  elsif v_outcome = 'carried' then
    perform public.create_user_notification(
      v_team.manager_id,
      v_team.league_id,
      'lineup',
      'Formazione recuperata',
      'Per la giornata '
        || v_matchday.number
        || ' è stata confermata automaticamente la distinta precedente.',
      'live',
      jsonb_build_object(
        'event', 'lineup_carried',
        'matchday_id', p_matchday_id,
        'matchday_number', v_matchday.number,
        'source_lineup_id', v_source_lineup_id,
        'fantasy_team_id', p_fantasy_team_id
      ),
      'lineup:carried:'
        || p_fantasy_team_id::text
        || ':'
        || p_matchday_id::text
    );
  end if;

  return v_response;
exception
  when others then
    perform set_config('leghevo.lineup_deadline_context', 'off', true);
    raise;
end;
$$;

revoke all on function public.lock_or_carry_team_lineup_guarded_v1(
  uuid,
  uuid,
  uuid
) from public, anon, authenticated;

create or replace function public.ensure_matchday_lineups_guarded_v1(
  p_matchday_id uuid,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_matchday public.matchdays%rowtype;
  v_team_id uuid;
  v_team_request_id uuid;
  v_result jsonb;
  v_outcome text;
  v_manager_count integer := 0;
  v_carried_count integer := 0;
  v_missing_count integer := 0;
  v_pending_count integer := 0;
  v_team_count integer := 0;
  v_event_count integer := 0;
  v_hash text;
  v_summary jsonb;
begin
  if p_request_id is null then
    raise exception 'Identificativo di chiusura giornata mancante.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'matchday-lineups:' || p_matchday_id::text,
      0
    )
  );

  select matchday.*
  into v_matchday
  from public.matchdays matchday
  where matchday.id = p_matchday_id
  for update;

  if not found then
    raise exception 'Giornata non trovata.';
  end if;

  if v_matchday.lineups_finalized_at is not null then
    return v_matchday.lineup_lock_summary
      || jsonb_build_object(
        'matchdayId', p_matchday_id,
        'lineupsFinalizedAt', v_matchday.lineups_finalized_at,
        'lineupLockRevision', v_matchday.lineup_lock_revision,
        'lineupLockHash', v_matchday.lineup_lock_hash,
        'idempotentReplay', true
      );
  end if;

  if now() < v_matchday.locks_at then
    return jsonb_build_object(
      'matchdayId', p_matchday_id,
      'manager', 0,
      'carried', 0,
      'missing', 0,
      'pending', 1,
      'finalized', false,
      'locksAt', v_matchday.locks_at,
      'secondsUntilLock', greatest(
        floor(extract(epoch from (v_matchday.locks_at - now())))::integer,
        0
      ),
      'idempotentReplay', false
    );
  end if;

  for v_team_id in
    select fixture.home_team_id
    from public.fantasy_fixtures fixture
    where fixture.matchday_id = p_matchday_id

    union

    select fixture.away_team_id
    from public.fantasy_fixtures fixture
    where fixture.matchday_id = p_matchday_id
  loop
    v_team_count := v_team_count + 1;
    v_team_request_id := public.leghevo_stable_request_uuid(
      p_request_id::text || ':' || v_team_id::text
    );

    v_result := public.lock_or_carry_team_lineup_guarded_v1(
      v_team_id,
      p_matchday_id,
      v_team_request_id
    );
    v_outcome := v_result ->> 'outcome';

    if v_outcome = 'manager' then
      v_manager_count := v_manager_count + 1;
    elsif v_outcome = 'carried' then
      v_carried_count := v_carried_count + 1;
    elsif v_outcome = 'missing' then
      v_missing_count := v_missing_count + 1;
    else
      v_pending_count := v_pending_count + 1;
    end if;
  end loop;

  select
    count(*)::integer,
    md5(
      coalesce(
        string_agg(
          event.fantasy_team_id::text
            || ':'
            || event.outcome
            || ':'
            || coalesce(event.content_hash, 'missing'),
          '|'
          order by event.fantasy_team_id
        ),
        ''
      )
    )
  into v_event_count, v_hash
  from public.lineup_deadline_events event
  where event.matchday_id = p_matchday_id;

  if v_team_count = 0 then
    raise exception 'La giornata non contiene partite fantasy.';
  end if;

  if v_pending_count > 0 or v_event_count <> v_team_count then
    raise exception
      'Chiusura distinte incompleta: % squadre attese, % eventi registrati.',
      v_team_count,
      v_event_count;
  end if;

  v_summary := jsonb_build_object(
    'matchdayId', p_matchday_id,
    'manager', v_manager_count,
    'carried', v_carried_count,
    'missing', v_missing_count,
    'pending', 0,
    'teamCount', v_team_count,
    'eventCount', v_event_count,
    'finalized', true,
    'locksAt', v_matchday.locks_at,
    'lineupLockHash', v_hash,
    'idempotentReplay', false
  );

  update public.matchdays matchday
  set
    lineups_finalized_at = now(),
    lineup_lock_revision = matchday.lineup_lock_revision + 1,
    lineup_lock_request_id = p_request_id,
    lineup_lock_hash = v_hash,
    lineup_lock_summary = v_summary
  where matchday.id = p_matchday_id
  returning * into v_matchday;

  return v_summary || jsonb_build_object(
    'lineupsFinalizedAt', v_matchday.lineups_finalized_at,
    'lineupLockRevision', v_matchday.lineup_lock_revision
  );
end;
$$;

