create table if not exists public.live_fixture_projection_runs (
  id bigint generated by default as identity primary key,
  league_id uuid not null
    references public.leagues(id) on delete cascade,
  fixture_id uuid not null
    references public.fantasy_fixtures(id) on delete cascade,
  matchday_id uuid not null
    references public.matchdays(id) on delete cascade,
  home_team_id uuid not null
    references public.fantasy_teams(id) on delete cascade,
  away_team_id uuid not null
    references public.fantasy_teams(id) on delete cascade,
  request_id uuid not null unique,
  projection_revision integer not null,
  input_hash text not null,
  result_hash text not null,
  status text not null,
  home_resolution_id bigint
    references public.lineup_resolution_runs(id) on delete set null,
  away_resolution_id bigint
    references public.lineup_resolution_runs(id) on delete set null,
  home_resolution_hash text,
  away_resolution_hash text,
  home_points numeric(8,2),
  away_points numeric(8,2),
  home_goals smallint,
  away_goals smallint,
  home_counted_players smallint not null default 0,
  away_counted_players smallint not null default 0,
  home_ready boolean not null default false,
  away_ready boolean not null default false,
  certified boolean not null default false,
  projection_payload jsonb not null default '{}'::jsonb,
  projected_at timestamptz not null default now(),
  superseded_at timestamptz,
  constraint live_fixture_projection_revision_check
    check (projection_revision >= 1),
  constraint live_fixture_projection_input_hash_check
    check (length(input_hash) = 32),
  constraint live_fixture_projection_result_hash_check
    check (length(result_hash) = 32),
  constraint live_fixture_projection_home_hash_check
    check (
      home_resolution_hash is null
      or length(home_resolution_hash) = 32
    ),
  constraint live_fixture_projection_away_hash_check
    check (
      away_resolution_hash is null
      or length(away_resolution_hash) = 32
    ),
  constraint live_fixture_projection_status_check
    check (status in ('upcoming', 'live', 'pending', 'final')),
  constraint live_fixture_projection_teams_check
    check (home_team_id <> away_team_id),
  constraint live_fixture_projection_home_count_check
    check (home_counted_players between 0 and 11),
  constraint live_fixture_projection_away_count_check
    check (away_counted_players between 0 and 11),
  constraint live_fixture_projection_home_goals_check
    check (home_goals is null or home_goals >= 0),
  constraint live_fixture_projection_away_goals_check
    check (away_goals is null or away_goals >= 0),
  unique (fixture_id, projection_revision),
  unique (fixture_id, input_hash)
);

create unique index if not exists live_fixture_projection_current_idx
