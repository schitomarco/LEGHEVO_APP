create or replace function public.prevent_live_fixture_projection_mutation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if coalesce(
    current_setting('leghevo.live_projection_context', true),
    ''
  ) = 'on' then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  raise exception
    'Proiezione Live certificata: modifica diretta non consentita.';
end;
$$;

drop trigger if exists live_fixture_projection_immutable
on public.live_fixture_projection_runs;
