before update or delete on public.live_fixture_projection_runs
for each row
execute function public.prevent_live_fixture_projection_mutation();

create or replace function public.live_fixture_projection_input_hash_v1(
  p_fixture_id uuid
)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_fixture record;
  v_home_input_hash text;
  v_away_input_hash text;
begin
  select
    fixture.id,
    fixture.league_id,
    fixture.matchday_id,
    fixture.home_team_id,
    fixture.away_team_id,
    fixture.finalized_at,
    league.mode,
    coalesce(league.scoring_rules, '{}'::jsonb) as scoring_rules,
    matchday.number,
    matchday.starts_at,
    matchday.locks_at,
    matchday.ends_at,
    matchday.provider_fixture_count,
    matchday.provider_final_fixture_count,
    matchday.lineups_finalized_at,
    matchday.lineup_lock_revision,
    matchday.lineup_lock_hash
  into v_fixture
  from public.fantasy_fixtures fixture
  join public.leagues league
    on league.id = fixture.league_id
  join public.matchdays matchday
    on matchday.id = fixture.matchday_id
  where fixture.id = p_fixture_id;

  if not found then
    return null;
  end if;

  v_home_input_hash := public.lineup_resolution_input_hash_v1(
    v_fixture.home_team_id,
    v_fixture.matchday_id
  );
  v_away_input_hash := public.lineup_resolution_input_hash_v1(
    v_fixture.away_team_id,
    v_fixture.matchday_id
  );

  if v_home_input_hash is null then
    v_home_input_hash := md5(
      public.compute_team_matchday_lineup_resolution_v1(
        v_fixture.home_team_id,
        v_fixture.matchday_id
      )::text
    );
  end if;

  if v_away_input_hash is null then
    v_away_input_hash := md5(
      public.compute_team_matchday_lineup_resolution_v1(
        v_fixture.away_team_id,
        v_fixture.matchday_id
      )::text
    );
  end if;

  return md5(
    jsonb_build_object(
      'fixtureId', v_fixture.id,
      'leagueId', v_fixture.league_id,
      'matchdayId', v_fixture.matchday_id,
      'homeTeamId', v_fixture.home_team_id,
      'awayTeamId', v_fixture.away_team_id,
      'finalizedAt', v_fixture.finalized_at,
      'mode', v_fixture.mode,
      'scoringRules', v_fixture.scoring_rules,
      'matchdayNumber', v_fixture.number,
      'startsAt', v_fixture.starts_at,
      'locksAt', v_fixture.locks_at,
      'endsAt', v_fixture.ends_at,
      'providerFixtureCount', v_fixture.provider_fixture_count,
      'providerFinalFixtureCount',
        v_fixture.provider_final_fixture_count,
      'lineupsFinalizedAt', v_fixture.lineups_finalized_at,
      'lineupLockRevision', v_fixture.lineup_lock_revision,
      'lineupLockHash', v_fixture.lineup_lock_hash,
      'homeResolutionInputHash', v_home_input_hash,
      'awayResolutionInputHash', v_away_input_hash
    )::text
  );
end;
$$;

create or replace function public.compute_live_fixture_projection_v1(
  p_fixture_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_fixture record;
  v_home_resolution jsonb;
  v_away_resolution jsonb;
  v_home_modifier jsonb;
  v_away_modifier jsonb;
  v_goal_resolution jsonb;
  v_home_base_points numeric;
  v_away_base_points numeric;
  v_home_modifier_bonus numeric := 0;
  v_away_modifier_bonus numeric := 0;
  v_home_bonus numeric := 0;
  v_home_points numeric;
  v_away_points numeric;
  v_home_goals smallint;
  v_away_goals smallint;
  v_status text;
  v_home_resolution_hash text;
  v_away_resolution_hash text;
  v_home_certified boolean := false;
  v_away_certified boolean := false;
begin
  select
    fixture.id,
    fixture.league_id,
    fixture.matchday_id,
    fixture.home_team_id,
    fixture.away_team_id,
    fixture.finalized_at,
    league.name as league_name,
    league.mode,
    coalesce(league.scoring_rules, '{}'::jsonb) as scoring_rules,
    matchday.number as matchday_number,
    matchday.starts_at,
    matchday.locks_at,
    matchday.ends_at,
    home_team.name as home_team_name,
    away_team.name as away_team_name
  into v_fixture
  from public.fantasy_fixtures fixture
  join public.leagues league
    on league.id = fixture.league_id
  join public.matchdays matchday
    on matchday.id = fixture.matchday_id
  join public.fantasy_teams home_team
    on home_team.id = fixture.home_team_id
  join public.fantasy_teams away_team
    on away_team.id = fixture.away_team_id
  where fixture.id = p_fixture_id;

  if not found then
    return jsonb_build_object(
      'available', false,
      'integrityError', 'fixture_not_found'
    );
  end if;

  v_home_resolution := public.resolve_team_matchday_lineup(
    v_fixture.home_team_id,
    v_fixture.matchday_id
  );
  v_away_resolution := public.resolve_team_matchday_lineup(
    v_fixture.away_team_id,
    v_fixture.matchday_id
  );

  if nullif(v_home_resolution ->> 'integrityError', '') is not null then
    raise exception
      'Proiezione Live bloccata per la squadra di casa: %.',
      v_home_resolution ->> 'integrityError';
  end if;

  if nullif(v_away_resolution ->> 'integrityError', '') is not null then
    raise exception
      'Proiezione Live bloccata per la squadra ospite: %.',
      v_away_resolution ->> 'integrityError';
  end if;

  v_home_modifier := public.calculate_defense_modifier(
    v_home_resolution,
    v_fixture.mode,
    v_fixture.scoring_rules
  );
  v_away_modifier := public.calculate_defense_modifier(
    v_away_resolution,
    v_fixture.mode,
    v_fixture.scoring_rules
  );

  v_home_base_points := nullif(
    v_home_resolution ->> 'totalPoints',
    ''
  )::numeric;
  v_away_base_points := nullif(
    v_away_resolution ->> 'totalPoints',
    ''
  )::numeric;
  v_home_modifier_bonus := coalesce(
    nullif(v_home_modifier ->> 'bonus', '')::numeric,
    0
  );
  v_away_modifier_bonus := coalesce(
    nullif(v_away_modifier ->> 'bonus', '')::numeric,
    0
  );
  v_home_bonus := coalesce(
    nullif(v_fixture.scoring_rules ->> 'home_bonus', '')::numeric,
    0
  );

  v_home_points := case
    when v_home_base_points is null then null
    else round(
      v_home_base_points + v_home_modifier_bonus + v_home_bonus,
      2
    )
  end;
  v_away_points := case
    when v_away_base_points is null then null
    else round(v_away_base_points + v_away_modifier_bonus, 2)
  end;

  v_goal_resolution := public.resolve_fantasy_fixture_goals(
    v_home_points,
    v_away_points,
    v_fixture.scoring_rules
  );
  v_home_goals := nullif(
    v_goal_resolution ->> 'homeGoals',
    ''
  )::smallint;
  v_away_goals := nullif(
    v_goal_resolution ->> 'awayGoals',
    ''
  )::smallint;

  v_status := case
    when v_fixture.finalized_at is not null then 'final'
    when now() < v_fixture.starts_at then 'upcoming'
    when now() <= coalesce(
      v_fixture.ends_at,
      v_fixture.starts_at + interval '4 days'
    ) then 'live'
    else 'pending'
  end;

  v_home_resolution_hash := coalesce(
    nullif(v_home_resolution ->> 'resolutionHash', ''),
    md5(v_home_resolution::text)
  );
  v_away_resolution_hash := coalesce(
    nullif(v_away_resolution ->> 'resolutionHash', ''),
    md5(v_away_resolution::text)
  );
  v_home_certified := coalesce(
    nullif(v_home_resolution ->> 'certified', '')::boolean,
    false
  );
  v_away_certified := coalesce(
    nullif(v_away_resolution ->> 'certified', '')::boolean,
    false
  );

  return jsonb_build_object(
    'available', true,
    'leagueId', v_fixture.league_id,
    'leagueName', v_fixture.league_name,
    'mode', v_fixture.mode,
    'fixtureId', v_fixture.id,
    'matchdayId', v_fixture.matchday_id,
    'status', v_status,
    'certified', v_home_certified and v_away_certified,
    'matchday', jsonb_build_object(
      'id', v_fixture.matchday_id,
      'number', v_fixture.matchday_number,
      'startsAt', v_fixture.starts_at,
      'locksAt', v_fixture.locks_at,
      'endsAt', v_fixture.ends_at
    ),
    'home', jsonb_build_object(
      'teamId', v_fixture.home_team_id,
      'name', v_fixture.home_team_name,
      'points', v_home_points,
      'basePoints', v_home_base_points,
      'defenseModifier', v_home_modifier,
      'homeBonus',
        case when v_home_points is null then 0 else v_home_bonus end,
      'goals', v_home_goals,
      'countedPlayers', coalesce(
        (v_home_resolution ->> 'countedPlayers')::integer,
        0
      ),
      'ready', coalesce(
        (v_home_resolution ->> 'isReady')::boolean,
        false
      ),
      'lineupOrigin', coalesce(
        nullif(v_home_resolution ->> 'deadlineOutcome', ''),
        'missing'
      ),
      'resolutionId', nullif(
        v_home_resolution ->> 'resolutionId',
        ''
      )::bigint,
      'resolutionRevision', nullif(
        v_home_resolution ->> 'resolutionRevision',
        ''
      )::integer,
      'resolutionHash', v_home_resolution_hash,
      'resolutionStatus', coalesce(
        nullif(v_home_resolution ->> 'resolutionStatus', ''),
        case when v_home_certified then 'certified' else 'preview' end
      ),
      'substitutions', jsonb_build_object(
        'used', coalesce(
          (v_home_resolution ->> 'substitutionsUsed')::integer,
          0
        ),
        'limit', coalesce(
          (v_home_resolution ->> 'maxSubstitutions')::integer,
          5
        ),
        'unavailableStarters', coalesce(
          (v_home_resolution ->> 'unavailableStarters')::integer,
          0
        ),
        'applied', coalesce(
          (v_home_resolution ->> 'matchdayComplete')::boolean,
          false
        )
      )
    ),
    'away', jsonb_build_object(
      'teamId', v_fixture.away_team_id,
      'name', v_fixture.away_team_name,
      'points', v_away_points,
      'basePoints', v_away_base_points,
      'defenseModifier', v_away_modifier,
      'homeBonus', 0,
      'goals', v_away_goals,
      'countedPlayers', coalesce(
        (v_away_resolution ->> 'countedPlayers')::integer,
        0
      ),
      'ready', coalesce(
        (v_away_resolution ->> 'isReady')::boolean,
        false
      ),
      'lineupOrigin', coalesce(
        nullif(v_away_resolution ->> 'deadlineOutcome', ''),
        'missing'
      ),
      'resolutionId', nullif(
        v_away_resolution ->> 'resolutionId',
        ''
      )::bigint,
      'resolutionRevision', nullif(
        v_away_resolution ->> 'resolutionRevision',
        ''
      )::integer,
      'resolutionHash', v_away_resolution_hash,
      'resolutionStatus', coalesce(
        nullif(v_away_resolution ->> 'resolutionStatus', ''),
        case when v_away_certified then 'certified' else 'preview' end
      ),
      'substitutions', jsonb_build_object(
        'used', coalesce(
          (v_away_resolution ->> 'substitutionsUsed')::integer,
          0
        ),
        'limit', coalesce(
          (v_away_resolution ->> 'maxSubstitutions')::integer,
          5
        ),
        'unavailableStarters', coalesce(
          (v_away_resolution ->> 'unavailableStarters')::integer,
          0
        ),
        'applied', coalesce(
          (v_away_resolution ->> 'matchdayComplete')::boolean,
          false
        )
      )
    ),
    'goalMargin', jsonb_build_object(
      'enabled', coalesce(
        (v_goal_resolution ->> 'enabled')::boolean,
        false
      ),
      'minimum', coalesce(
        nullif(v_goal_resolution ->> 'minimum', '')::numeric,
        4
      ),
      'applied', coalesce(
        (v_goal_resolution ->> 'applied')::boolean,
        false
      ),
      'homeBonus', coalesce(
        nullif(v_goal_resolution ->> 'homeBonus', '')::integer,
        0
      ),
      'awayBonus', coalesce(
        nullif(v_goal_resolution ->> 'awayBonus', '')::integer,
        0
      )
    )
  );
end;
$$;

create or replace function public.refresh_live_fixture_projection_guarded_v1(
  p_fixture_id uuid,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_fixture public.fantasy_fixtures%rowtype;
  v_existing public.live_fixture_projection_runs%rowtype;
  v_run public.live_fixture_projection_runs%rowtype;
  v_input_hash text;
  v_result_hash text;
  v_projection jsonb;
  v_revision integer;
  v_home_resolution_id bigint;
  v_away_resolution_id bigint;
  v_home_resolution_hash text;
  v_away_resolution_hash text;
  v_status text;
  v_home_points numeric;
  v_away_points numeric;
  v_home_goals smallint;
  v_away_goals smallint;
  v_home_counted smallint;
  v_away_counted smallint;
  v_home_ready boolean;
  v_away_ready boolean;
  v_certified boolean;
begin
  if p_request_id is null then
    raise exception 'Identificativo proiezione Live mancante.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'live-fixture-projection:' || p_fixture_id::text,
      0
    )
  );

  select fixture.*
  into v_fixture
  from public.fantasy_fixtures fixture
  where fixture.id = p_fixture_id;

  if not found then
    raise exception 'Partita fantasy non trovata.';
  end if;

  if exists (
    select 1
    from public.matchdays matchday
    where matchday.id = v_fixture.matchday_id
      and now() >= matchday.locks_at
  ) then
    perform public.ensure_matchday_lineups(v_fixture.matchday_id);
  end if;

  v_input_hash := public.live_fixture_projection_input_hash_v1(
    p_fixture_id
  );

  if v_input_hash is null then
    raise exception 'Impossibile calcolare l''impronta del Live.';
  end if;

  select run.*
  into v_existing
  from public.live_fixture_projection_runs run
  where run.request_id = p_request_id;

  if found then
    if v_existing.fixture_id <> p_fixture_id
      or v_existing.input_hash <> v_input_hash then
      raise exception
        'La chiave della proiezione Live è già stata utilizzata.';
    end if;

    if v_existing.superseded_at is not null then
      perform set_config(
        'leghevo.live_projection_context',
        'on',
        true
      );

      update public.live_fixture_projection_runs run
      set superseded_at = now()
      where run.fixture_id = p_fixture_id
        and run.superseded_at is null
        and run.id <> v_existing.id;

      update public.live_fixture_projection_runs run
      set superseded_at = null
      where run.id = v_existing.id;
    end if;

    return v_existing.projection_payload || jsonb_build_object(
      'projectionId', v_existing.id,
      'projectionRevision', v_existing.projection_revision,
      'projectionInputHash', v_existing.input_hash,
      'projectionHash', v_existing.result_hash,
      'projectedAt', v_existing.projected_at,
      'idempotentReplay', true,
      'reactivated', v_existing.superseded_at is not null
    );
  end if;

  select run.*
  into v_existing
  from public.live_fixture_projection_runs run
  where run.fixture_id = p_fixture_id
    and run.input_hash = v_input_hash;

  if found then
    if v_existing.superseded_at is not null then
      perform set_config(
        'leghevo.live_projection_context',
        'on',
        true
      );

      update public.live_fixture_projection_runs run
      set superseded_at = now()
      where run.fixture_id = p_fixture_id
        and run.superseded_at is null
        and run.id <> v_existing.id;

      update public.live_fixture_projection_runs run
      set superseded_at = null
      where run.id = v_existing.id;
    end if;

    return v_existing.projection_payload || jsonb_build_object(
      'projectionId', v_existing.id,
      'projectionRevision', v_existing.projection_revision,
      'projectionInputHash', v_existing.input_hash,
      'projectionHash', v_existing.result_hash,
      'projectedAt', v_existing.projected_at,
      'idempotentReplay', true,
      'reactivated', v_existing.superseded_at is not null
    );
  end if;

  v_projection := public.compute_live_fixture_projection_v1(
    p_fixture_id
  );

  if not coalesce(
    (v_projection ->> 'available')::boolean,
    false
  ) then
    raise exception
      'Proiezione Live non disponibile: %.',
      coalesce(v_projection ->> 'integrityError', 'errore sconosciuto');
  end if;

  v_result_hash := md5(v_projection::text);
  v_home_resolution_id := nullif(
    v_projection #>> '{home,resolutionId}',
    ''
  )::bigint;
  v_away_resolution_id := nullif(
    v_projection #>> '{away,resolutionId}',
    ''
  )::bigint;
  v_home_resolution_hash := nullif(
    v_projection #>> '{home,resolutionHash}',
    ''
  );
  v_away_resolution_hash := nullif(
    v_projection #>> '{away,resolutionHash}',
    ''
  );
  v_status := v_projection ->> 'status';
  v_home_points := nullif(
    v_projection #>> '{home,points}',
    ''
  )::numeric;
  v_away_points := nullif(
    v_projection #>> '{away,points}',
    ''
  )::numeric;
  v_home_goals := nullif(
    v_projection #>> '{home,goals}',
    ''
  )::smallint;
  v_away_goals := nullif(
    v_projection #>> '{away,goals}',
    ''
  )::smallint;
  v_home_counted := coalesce(
    (v_projection #>> '{home,countedPlayers}')::smallint,
    0
  );
  v_away_counted := coalesce(
    (v_projection #>> '{away,countedPlayers}')::smallint,
    0
  );
  v_home_ready := coalesce(
    (v_projection #>> '{home,ready}')::boolean,
    false
  );
  v_away_ready := coalesce(
    (v_projection #>> '{away,ready}')::boolean,
    false
  );
  v_certified := coalesce(
    (v_projection ->> 'certified')::boolean,
    false
  );

  if v_status not in ('upcoming', 'live', 'pending', 'final')
    or v_home_counted not between 0 and 11
    or v_away_counted not between 0 and 11 then
    raise exception
      'La proiezione Live non supera i controlli finali.';
  end if;

  perform set_config(
    'leghevo.live_projection_context',
    'on',
    true
  );

  update public.live_fixture_projection_runs run
  set superseded_at = now()
  where run.fixture_id = p_fixture_id
    and run.superseded_at is null;

  select coalesce(max(run.projection_revision), 0) + 1
  into v_revision
  from public.live_fixture_projection_runs run
  where run.fixture_id = p_fixture_id;

  insert into public.live_fixture_projection_runs (
    league_id,
    fixture_id,
    matchday_id,
    home_team_id,
    away_team_id,
    request_id,
    projection_revision,
    input_hash,
    result_hash,
    status,
    home_resolution_id,
    away_resolution_id,
    home_resolution_hash,
    away_resolution_hash,
    home_points,
    away_points,
    home_goals,
    away_goals,
    home_counted_players,
    away_counted_players,
    home_ready,
    away_ready,
    certified,
    projection_payload
  ) values (
    v_fixture.league_id,
    v_fixture.id,
    v_fixture.matchday_id,
    v_fixture.home_team_id,
    v_fixture.away_team_id,
    p_request_id,
    v_revision,
    v_input_hash,
    v_result_hash,
    v_status,
    v_home_resolution_id,
    v_away_resolution_id,
    v_home_resolution_hash,
    v_away_resolution_hash,
    v_home_points,
    v_away_points,
    v_home_goals,
    v_away_goals,
    v_home_counted,
    v_away_counted,
    v_home_ready,
    v_away_ready,
    v_certified,
    v_projection
  )
  returning * into v_run;

  return v_projection || jsonb_build_object(
    'projectionId', v_run.id,
    'projectionRevision', v_run.projection_revision,
    'projectionInputHash', v_run.input_hash,
    'projectionHash', v_run.result_hash,
    'projectedAt', v_run.projected_at,
    'idempotentReplay', false,
    'reactivated', false
  );
end;
$$;

create or replace function public.refresh_live_projection_after_fixture_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_input_hash text;
begin
  if coalesce(
    current_setting('leghevo.live_projection_context', true),
    ''
  ) = 'on' then
    return new;
  end if;

  v_input_hash := public.live_fixture_projection_input_hash_v1(new.id);

  if v_input_hash is not null then
    perform public.refresh_live_fixture_projection_guarded_v1(
      new.id,
      public.leghevo_stable_request_uuid(
        'live-fixture-projection:'
          || new.id::text
          || ':'
          || v_input_hash
      )
    );
  end if;

  return new;
end;
$$;

