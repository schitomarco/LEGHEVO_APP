create or replace function public.get_my_live_match_v6(
  p_league_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_match jsonb;
  v_projection jsonb;
  v_fixture_id uuid;
  v_my_team_id uuid;
  v_home_team_id uuid;
  v_input_hash text;
  v_my_substitutions jsonb;
begin
  v_match := public.get_my_live_match_v5(p_league_id);

  if v_match is null then
    return null;
  end if;

  v_fixture_id := (v_match ->> 'fixtureId')::uuid;
  v_my_team_id := (v_match ->> 'myTeamId')::uuid;
  v_home_team_id := (v_match #>> '{home,teamId}')::uuid;
  v_input_hash := public.live_fixture_projection_input_hash_v1(
    v_fixture_id
  );

  if v_input_hash is null then
    raise exception 'Proiezione Live non disponibile.';
  end if;

  v_projection := public.refresh_live_fixture_projection_guarded_v1(
    v_fixture_id,
    public.leghevo_stable_request_uuid(
      'live-fixture-projection:'
        || v_fixture_id::text
        || ':'
        || v_input_hash
    )
  );

  v_my_substitutions := case
    when v_my_team_id = v_home_team_id then
      v_projection #> '{home,substitutions}'
    else v_projection #> '{away,substitutions}'
  end;

  return v_match || jsonb_build_object(
    'status', v_projection -> 'status',
    'home',
      coalesce(v_match -> 'home', '{}'::jsonb)
      || coalesce(v_projection -> 'home', '{}'::jsonb),
    'away',
      coalesce(v_match -> 'away', '{}'::jsonb)
      || coalesce(v_projection -> 'away', '{}'::jsonb),
    'substitutions', coalesce(
      v_my_substitutions,
      jsonb_build_object(
        'used', 0,
        'limit', 5,
        'unavailableStarters', 0,
        'applied', false
      )
    ),
    'goalMargin',
      coalesce(v_match -> 'goalMargin', '{}'::jsonb)
      || coalesce(v_projection -> 'goalMargin', '{}'::jsonb),
    'liveProjection', jsonb_build_object(
      'policy', 'protected_v1',
      'projectionId', v_projection -> 'projectionId',
      'revision', v_projection -> 'projectionRevision',
      'inputHash', v_projection -> 'projectionInputHash',
      'hash', v_projection -> 'projectionHash',
      'projectedAt', v_projection -> 'projectedAt',
      'certified', v_projection -> 'certified',
      'idempotentReplay', v_projection -> 'idempotentReplay'
    )
  );
end;
$$;

create or replace function public.get_league_live_projection_integrity_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_current_count integer := 0;
  v_duplicate_current_count integer := 0;
  v_stale_input_count integer := 0;
  v_result_hash_issue_count integer := 0;
  v_fixture_link_issue_count integer := 0;
  v_payload_issue_count integer := 0;
  v_resolution_link_issue_count integer := 0;
  v_revision_issue_count integer := 0;
  v_triggers_ready boolean := false;
  v_realtime_ready boolean := false;
  v_healthy boolean := false;
begin
  if auth.uid() is not null
    and not public.is_league_member(p_league_id)
    and not public.is_league_admin(p_league_id) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  select count(*)::integer
  into v_current_count
  from public.live_fixture_projection_runs run
  where run.league_id = p_league_id
    and run.superseded_at is null;

  select count(*)::integer
  into v_duplicate_current_count
  from (
    select run.fixture_id
    from public.live_fixture_projection_runs run
    where run.league_id = p_league_id
      and run.superseded_at is null
    group by run.fixture_id
    having count(*) > 1
  ) duplicate_rows;

  select count(*)::integer
  into v_stale_input_count
  from public.live_fixture_projection_runs run
  where run.league_id = p_league_id
    and run.superseded_at is null
    and run.input_hash is distinct from
      public.live_fixture_projection_input_hash_v1(run.fixture_id);

  select count(*)::integer
  into v_result_hash_issue_count
  from public.live_fixture_projection_runs run
  where run.league_id = p_league_id
    and run.result_hash is distinct from md5(run.projection_payload::text);

  select count(*)::integer
  into v_fixture_link_issue_count
  from public.live_fixture_projection_runs run
  join public.fantasy_fixtures fixture
    on fixture.id = run.fixture_id
  where run.league_id = p_league_id
    and (
      run.league_id <> fixture.league_id
      or run.matchday_id <> fixture.matchday_id
      or run.home_team_id <> fixture.home_team_id
      or run.away_team_id <> fixture.away_team_id
    );

  select count(*)::integer
  into v_payload_issue_count
  from public.live_fixture_projection_runs run
  where run.league_id = p_league_id
    and (
      run.status is distinct from run.projection_payload ->> 'status'
      or run.home_points is distinct from nullif(
        run.projection_payload #>> '{home,points}',
        ''
      )::numeric
      or run.away_points is distinct from nullif(
        run.projection_payload #>> '{away,points}',
        ''
      )::numeric
      or run.home_goals is distinct from nullif(
        run.projection_payload #>> '{home,goals}',
        ''
      )::smallint
      or run.away_goals is distinct from nullif(
        run.projection_payload #>> '{away,goals}',
        ''
      )::smallint
      or run.home_counted_players is distinct from coalesce(
        (run.projection_payload #>> '{home,countedPlayers}')::smallint,
        0
      )
      or run.away_counted_players is distinct from coalesce(
        (run.projection_payload #>> '{away,countedPlayers}')::smallint,
        0
      )
      or run.home_ready is distinct from coalesce(
        (run.projection_payload #>> '{home,ready}')::boolean,
        false
      )
      or run.away_ready is distinct from coalesce(
        (run.projection_payload #>> '{away,ready}')::boolean,
        false
      )
      or run.certified is distinct from coalesce(
        (run.projection_payload ->> 'certified')::boolean,
        false
      )
    );

  select count(*)::integer
  into v_resolution_link_issue_count
  from public.live_fixture_projection_runs run
  where run.league_id = p_league_id
    and (
      (
        run.home_resolution_id is not null
        and not exists (
          select 1
          from public.lineup_resolution_runs resolution
          where resolution.id = run.home_resolution_id
            and resolution.fantasy_team_id = run.home_team_id
            and resolution.matchday_id = run.matchday_id
            and resolution.result_hash = run.home_resolution_hash
        )
      )
      or (
        run.away_resolution_id is not null
        and not exists (
          select 1
          from public.lineup_resolution_runs resolution
          where resolution.id = run.away_resolution_id
            and resolution.fantasy_team_id = run.away_team_id
            and resolution.matchday_id = run.matchday_id
            and resolution.result_hash = run.away_resolution_hash
        )
      )
    );

  select count(*)::integer
  into v_revision_issue_count
  from (
    select
      run.fixture_id,
      count(*)::integer as revision_count,
      min(run.projection_revision) as minimum_revision,
      max(run.projection_revision) as maximum_revision,
      count(distinct run.projection_revision)::integer
        as distinct_revision_count
    from public.live_fixture_projection_runs run
    where run.league_id = p_league_id
    group by run.fixture_id
    having min(run.projection_revision) <> 1
      or max(run.projection_revision) <> count(*)
      or count(distinct run.projection_revision) <> count(*)
  ) revision_issues;

  select count(*) = 2
  into v_triggers_ready
  from pg_catalog.pg_trigger trigger_row
  where not trigger_row.tgisinternal
    and trigger_row.tgname in (
      'live_fixture_projection_immutable',
      'fantasy_fixture_refresh_live_projection'
    );

  select exists (
    select 1
    from pg_catalog.pg_publication_tables publication_table
    where publication_table.pubname = 'supabase_realtime'
      and publication_table.schemaname = 'public'
      and publication_table.tablename = 'live_fixture_projection_runs'
  )
  into v_realtime_ready;

  v_healthy :=
    v_duplicate_current_count = 0
    and v_stale_input_count = 0
    and v_result_hash_issue_count = 0
    and v_fixture_link_issue_count = 0
    and v_payload_issue_count = 0
    and v_resolution_link_issue_count = 0
    and v_revision_issue_count = 0
    and v_triggers_ready
    and v_realtime_ready;

  return jsonb_build_object(
    'version', 1,
    'liveProjectionPolicy', 'protected_v1',
    'currentProjectionCount', v_current_count,
    'duplicateCurrentProjectionCount', v_duplicate_current_count,
    'staleInputCount', v_stale_input_count,
    'resultHashIssueCount', v_result_hash_issue_count,
    'fixtureLinkIssueCount', v_fixture_link_issue_count,
    'payloadIssueCount', v_payload_issue_count,
    'resolutionLinkIssueCount', v_resolution_link_issue_count,
    'revisionIssueCount', v_revision_issue_count,
    'triggersReady', v_triggers_ready,
    'realtimeReady', v_realtime_ready,
    'healthy', v_healthy
  );
end;
$$;

