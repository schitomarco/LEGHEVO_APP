create or replace function public.get_league_playoff_configuration_integrity_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_playoff public.league_playoffs%rowtype;
  v_run public.league_playoff_configuration_runs%rowtype;
  v_hash_matches boolean := false;
  v_result_hash_matches boolean := false;
  v_configuration_matches boolean := false;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if not public.is_league_member(p_league_id)
    and not public.is_league_admin(p_league_id) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  select playoff.*
  into v_playoff
  from public.league_playoffs playoff
  where playoff.league_id = p_league_id;

  select run.*
  into v_run
  from public.league_playoff_configuration_runs run
  where run.league_id = p_league_id
  order by run.configured_at desc, run.id desc
  limit 1;

  if v_run.id is not null then
    v_hash_matches := v_run.configuration_hash =
      public.compute_league_playoff_configuration_hash_v1(
        v_run.league_id,
        v_run.participant_count,
        v_run.round_count,
        v_run.league_team_limit,
        v_run.league_status,
        v_run.competition_started_at,
        v_run.source_mode
      );

    v_result_hash_matches := v_run.result_hash =
      public.compute_league_playoff_configuration_result_hash_v1(
        v_run.configuration_hash,
        v_run.playoff_id,
        v_run.requested_by
      );

    v_configuration_matches := v_playoff.id = v_run.playoff_id
      and v_playoff.participant_count = v_run.participant_count
      and v_playoff.round_count = v_run.round_count;
  end if;

  return jsonb_build_object(
    'leagueId', p_league_id,
    'ready', v_playoff.id is null
      or (
        v_run.id is not null
        and v_hash_matches
        and v_result_hash_matches
        and v_configuration_matches
      ),
    'playoffExists', v_playoff.id is not null,
    'configurationCertified', v_run.id is not null,
    'configurationRunId', v_run.id,
    'sourceMode', v_run.source_mode,
    'hashMatches', v_hash_matches,
    'resultHashMatches', v_result_hash_matches,
    'configurationMatches', v_configuration_matches,
    'configurationHash', v_run.configuration_hash,
    'resultHash', v_run.result_hash
  );
end;
$$;

