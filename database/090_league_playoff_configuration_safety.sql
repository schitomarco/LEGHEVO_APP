select
  playoff.league_id,
  playoff.id,
  public.leghevo_stable_request_uuid(
    'league-playoff-configuration-backfill:' || playoff.id::text
  ),
  playoff.configured_by,
  'legacy_backfill',
  playoff.participant_count,
  playoff.round_count,
  league.team_limit,
  league.status::text,
  league.competition_started_at,
  public.compute_league_playoff_configuration_hash_v1(
    playoff.league_id,
    playoff.participant_count,
    playoff.round_count,
    league.team_limit,
    league.status::text,
    league.competition_started_at,
    'legacy_backfill'
  ),
  public.compute_league_playoff_configuration_result_hash_v1(
    public.compute_league_playoff_configuration_hash_v1(
      playoff.league_id,
      playoff.participant_count,
      playoff.round_count,
      league.team_limit,
      league.status::text,
      league.competition_started_at,
      'legacy_backfill'
    ),
    playoff.id,
    playoff.configured_by
  ),
  playoff.configured_at
from public.league_playoffs playoff
join public.leagues league on league.id = playoff.league_id
where not exists (
  select 1
  from public.league_playoff_configuration_runs run
  where run.playoff_id = playoff.id
)
on conflict do nothing;

