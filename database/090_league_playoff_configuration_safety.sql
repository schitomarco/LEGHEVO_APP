create or replace function public.configure_league_playoffs_guarded_v1(
  p_league_id uuid,
  p_participant_count smallint,
  p_request_id uuid
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_league public.leagues%rowtype;
  v_playoff public.league_playoffs%rowtype;
  v_existing_run public.league_playoff_configuration_runs%rowtype;
  v_round_count smallint;
  v_configuration_hash text;
  v_result_hash text;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if p_request_id is null then
    raise exception 'Identificativo richiesta configurazione mancante.';
  end if;

  if p_participant_count not in (4, 8) then
    raise exception 'I playoff possono includere quattro o otto squadre.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'leghevo:playoff-configuration:' || p_league_id::text,
      0
    )
  );

  select run.*
  into v_existing_run
  from public.league_playoff_configuration_runs run
  where run.league_id = p_league_id
    and run.request_id = p_request_id;

  if found then
    if v_existing_run.participant_count <> p_participant_count then
      raise exception
        'La richiesta idempotente è già associata a un formato Playoff differente.';
    end if;
    return v_existing_run.playoff_id;
  end if;

  select league.*
  into v_league
  from public.leagues league
  where league.id = p_league_id
  for update;

  if not found then
    raise exception 'Lega non trovata.';
  end if;

  if v_league.owner_id <> auth.uid() then
    raise exception 'Solo il Presidente può configurare i playoff.';
  end if;

  if v_league.status <> 'draft'
    or v_league.competition_started_at is not null then
    raise exception
      'Il formato playoff si decide prima dell''avvio del campionato.';
  end if;

  if v_league.team_limit < p_participant_count then
    raise exception
      'Il formato scelto supera il numero di squadre della lega.';
  end if;

  v_round_count := case when p_participant_count = 8 then 3 else 2 end;

  select playoff.*
  into v_playoff
  from public.league_playoffs playoff
  where playoff.league_id = p_league_id
  for update;

  if found then
    if v_playoff.participant_count <> p_participant_count
      or v_playoff.round_count <> v_round_count then
      raise exception
        'I Playoff risultano già configurati con un formato differente.';
    end if;

    select run.*
    into v_existing_run
    from public.league_playoff_configuration_runs run
    where run.playoff_id = v_playoff.id;

    if found then
      return v_playoff.id;
    end if;

    v_configuration_hash :=
      public.compute_league_playoff_configuration_hash_v1(
        p_league_id,
        v_playoff.participant_count,
        v_playoff.round_count,
        v_league.team_limit,
        v_league.status::text,
        v_league.competition_started_at,
        'legacy_backfill'
      );
    v_result_hash :=
      public.compute_league_playoff_configuration_result_hash_v1(
        v_configuration_hash,
        v_playoff.id,
        v_playoff.configured_by
      );

    insert into public.league_playoff_configuration_runs (
      league_id,
      playoff_id,
      request_id,
      requested_by,
      source_mode,
      participant_count,
      round_count,
      league_team_limit,
      league_status,
      competition_started_at,
      configuration_hash,
      result_hash,
      configured_at
    )
    values (
      p_league_id,
      v_playoff.id,
      p_request_id,
      v_playoff.configured_by,
      'legacy_backfill',
      v_playoff.participant_count,
      v_playoff.round_count,
      v_league.team_limit,
      v_league.status::text,
      v_league.competition_started_at,
      v_configuration_hash,
      v_result_hash,
      v_playoff.configured_at
    );

    return v_playoff.id;
  end if;

  insert into public.league_playoffs (
    league_id,
    status,
    participant_count,
    round_count,
    current_round,
    configured_by
  )
  values (
    p_league_id,
    'configured',
    p_participant_count,
    v_round_count,
    0,
    auth.uid()
  )
  returning * into v_playoff;

  v_configuration_hash :=
    public.compute_league_playoff_configuration_hash_v1(
      p_league_id,
      p_participant_count,
      v_round_count,
      v_league.team_limit,
      v_league.status::text,
      v_league.competition_started_at,
      'guarded_v1'
    );
  v_result_hash :=
    public.compute_league_playoff_configuration_result_hash_v1(
      v_configuration_hash,
      v_playoff.id,
      auth.uid()
    );

  insert into public.league_playoff_configuration_runs (
    league_id,
    playoff_id,
    request_id,
    requested_by,
    source_mode,
    participant_count,
    round_count,
    league_team_limit,
    league_status,
    competition_started_at,
    configuration_hash,
    result_hash,
    configured_at
  )
  values (
    p_league_id,
    v_playoff.id,
    p_request_id,
    auth.uid(),
    'guarded_v1',
    p_participant_count,
    v_round_count,
    v_league.team_limit,
    v_league.status::text,
    v_league.competition_started_at,
    v_configuration_hash,
    v_result_hash,
    v_playoff.configured_at
  );

  return v_playoff.id;
end;
$$;

