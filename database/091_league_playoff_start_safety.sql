create or replace function public.compute_league_playoff_qualification_source_hash_v1(
  p_league_id uuid,
  p_participant_count smallint
)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select public.leghevo_sha256_hex_v1(
    coalesce(
      string_agg(
        standing.fantasy_team_id::text || ':'
        || standing.position::text || ':'
        || standing.position::text,
        '|' order by standing.position
      ),
      'empty'
    )
  )
  from public.get_league_standings_v2(p_league_id) standing
  where standing.position <= p_participant_count;
$$;

