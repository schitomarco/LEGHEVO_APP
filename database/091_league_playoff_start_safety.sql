create or replace function public.start_league_playoffs_guarded_v1(
  p_league_id uuid,
  p_start_matchday_number smallint,
  p_request_id uuid
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_league public.leagues%rowtype;
  v_playoff public.league_playoffs%rowtype;
  v_configuration public.league_playoff_configuration_runs%rowtype;
  v_existing_run public.league_playoff_start_runs%rowtype;
  v_fixture_count integer := 0;
  v_official_fixture_count integer := 0;
  v_fixture_matchday_count integer := 0;
  v_progressed_matchday_count integer := 0;
  v_team_count integer := 0;
  v_available_matchday_count integer := 0;
  v_first_matchday_number smallint;
  v_last_matchday_number smallint;
  v_entry_count integer := 0;
  v_round_record_count integer := 0;
  v_tie_count integer := 0;
  v_qualification_source_hash text;
  v_qualification_hash text;
  v_schedule_hash text;
  v_opening_bracket_hash text;
  v_result_hash text;
  v_playoff_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if p_request_id is null then
    raise exception 'Identificativo richiesta avvio mancante.';
  end if;

  if p_start_matchday_number is null or p_start_matchday_number < 1 then
    raise exception 'Giornata di partenza dei Playoff non valida.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'leghevo:league-playoff-start:' || p_league_id::text,
      0
    )
  );

  select run.*
  into v_existing_run
  from public.league_playoff_start_runs run
  where run.league_id = p_league_id
    and run.request_id = p_request_id;

  if found then
    if v_existing_run.start_matchday_number <> p_start_matchday_number then
      raise exception
        'La richiesta idempotente è già associata a una giornata differente.';
    end if;
    return v_existing_run.playoff_id;
  end if;

  select league.*
  into v_league
  from public.leagues league
  where league.id = p_league_id
  for update;

  if not found then
    raise exception 'Lega non trovata.';
  end if;

  if v_league.owner_id <> auth.uid() then
    raise exception 'Solo il Presidente può avviare i playoff.';
  end if;

  if v_league.status <> 'active'
    or v_league.competition_started_at is null then
    raise exception 'La stagione regolare non è attiva.';
  end if;

  select playoff.*
  into v_playoff
  from public.league_playoffs playoff
  where playoff.league_id = p_league_id
  for update;

  if not found then
    raise exception 'I playoff non sono stati configurati.';
  end if;

  select configuration.*
  into v_configuration
  from public.league_playoff_configuration_runs configuration
  where configuration.playoff_id = v_playoff.id
  order by configuration.configured_at desc, configuration.id desc
  limit 1;

  if not found then
    raise exception 'La configurazione Playoff non è certificata.';
  end if;

  if v_configuration.participant_count <> v_playoff.participant_count
    or v_configuration.round_count <> v_playoff.round_count then
    raise exception
      'La configurazione certificata non coincide con il formato Playoff corrente.';
  end if;

  select run.*
  into v_existing_run
  from public.league_playoff_start_runs run
  where run.playoff_id = v_playoff.id;

  if found then
    if v_existing_run.start_matchday_number <> p_start_matchday_number then
      raise exception
        'I Playoff sono già certificati su una giornata di partenza differente.';
    end if;
    return v_existing_run.playoff_id;
  end if;

  if v_playoff.status in ('active', 'completed') then
    raise exception
      'I Playoff risultano già avviati ma manca il certificato di avvio. Esegui la migrazione di continuità.';
  end if;

  select
    count(*)::integer,
    count(*) filter (
      where fixture.finalized_at is not null
        and fixture.officialization_run_id is not null
    )::integer,
    count(distinct fixture.matchday_id)::integer
  into
    v_fixture_count,
    v_official_fixture_count,
    v_fixture_matchday_count
  from public.fantasy_fixtures fixture
  where fixture.league_id = p_league_id;

  if v_fixture_count = 0
    or v_fixture_count <> v_official_fixture_count then
    raise exception
      'La stagione regolare deve avere tutti i risultati certificati.';
  end if;

  select count(distinct progression.matchday_id)::integer
  into v_progressed_matchday_count
  from public.matchday_progression_runs progression
  where progression.league_id = p_league_id
    and progression.superseded_at is null
    and exists (
      select 1
      from public.fantasy_fixtures fixture
      where fixture.league_id = p_league_id
        and fixture.matchday_id = progression.matchday_id
    );

  if v_progressed_matchday_count <> v_fixture_matchday_count then
    raise exception
      'Manca la progressione certificata di almeno una giornata della stagione regolare.';
  end if;

  select count(*)::integer
  into v_team_count
  from public.fantasy_teams team
  where team.league_id = p_league_id;

  if v_team_count < v_playoff.participant_count then
    raise exception
      'Servono almeno % squadre per avviare i playoff.',
      v_playoff.participant_count;
  end if;

  select
    count(*)::integer,
    min(available.number)::smallint,
    max(available.number)::smallint
  into
    v_available_matchday_count,
    v_first_matchday_number,
    v_last_matchday_number
  from (
    select matchday.number
    from public.matchdays matchday
    where matchday.number >= p_start_matchday_number
      and matchday.locks_at > now()
      and (
        v_league.calendar_season is null
        or matchday.season = v_league.calendar_season
      )
    order by matchday.number
    limit v_playoff.round_count
  ) available;

  if v_available_matchday_count <> v_playoff.round_count
    or v_first_matchday_number <> p_start_matchday_number
    or v_last_matchday_number <>
      p_start_matchday_number + v_playoff.round_count - 1 then
    raise exception
      'Servono % giornate future consecutive a partire dalla giornata %.',
      v_playoff.round_count,
      p_start_matchday_number;
  end if;

  v_qualification_source_hash :=
    public.compute_league_playoff_qualification_source_hash_v1(
      p_league_id,
      v_playoff.participant_count
    );

  v_playoff_id := public.start_league_playoffs_legacy_internal_v1(
    p_league_id,
    p_start_matchday_number
  );

  select playoff.*
  into v_playoff
  from public.league_playoffs playoff
  where playoff.id = v_playoff_id
  for update;

  if not found or v_playoff.status <> 'active' or v_playoff.current_round <> 1 then
    raise exception 'L''avvio dei Playoff non ha prodotto uno stato valido.';
  end if;

  select count(*)::integer
  into v_entry_count
  from public.league_playoff_entries entry
  where entry.playoff_id = v_playoff.id;

  select count(*)::integer
  into v_round_record_count
  from public.league_playoff_rounds playoff_round
  where playoff_round.playoff_id = v_playoff.id;

  select count(*)::integer
  into v_tie_count
  from public.league_playoff_ties tie
  join public.league_playoff_rounds playoff_round
    on playoff_round.id = tie.round_id
  where playoff_round.playoff_id = v_playoff.id;

  if v_entry_count <> v_playoff.participant_count
    or v_round_record_count <> v_playoff.round_count
    or v_tie_count <> v_playoff.participant_count - 1 then
    raise exception
      'Il tabellone Playoff non contiene il numero atteso di qualificate, turni o sfide.';
  end if;

  v_qualification_hash :=
    public.compute_league_playoff_qualification_hash_v1(v_playoff.id);
  v_schedule_hash :=
    public.compute_league_playoff_schedule_hash_v1(v_playoff.id);
  v_opening_bracket_hash :=
    public.compute_league_playoff_opening_bracket_hash_v1(v_playoff.id);

  if v_qualification_source_hash <> v_qualification_hash then
    raise exception
      'Le teste di serie create non coincidono con la classifica certificata.';
  end if;

  v_result_hash := public.compute_league_playoff_start_result_hash_v1(
    v_playoff.id,
    v_configuration.id,
    p_start_matchday_number,
    v_playoff.participant_count,
    v_playoff.round_count,
    v_qualification_source_hash,
    v_qualification_hash,
    v_schedule_hash,
    v_opening_bracket_hash,
    v_playoff.started_at
  );

  insert into public.league_playoff_start_runs (
    league_id,
    playoff_id,
    configuration_run_id,
    request_id,
    requested_by,
    source_mode,
    start_matchday_number,
    participant_count,
    round_count,
    regular_fixture_count,
    official_fixture_count,
    qualified_team_count,
    entry_count,
    round_record_count,
    tie_count,
    qualification_source_hash,
    qualification_hash,
    schedule_hash,
    opening_bracket_hash,
    result_hash,
    started_at
  ) values (
    p_league_id,
    v_playoff.id,
    v_configuration.id,
    p_request_id,
    auth.uid(),
    'guarded_v1',
    p_start_matchday_number,
    v_playoff.participant_count,
    v_playoff.round_count,
    v_fixture_count,
    v_official_fixture_count,
    v_entry_count,
    v_entry_count,
    v_round_record_count,
    v_tie_count,
    v_qualification_source_hash,
    v_qualification_hash,
    v_schedule_hash,
    v_opening_bracket_hash,
    v_result_hash,
    v_playoff.started_at
  );

  return v_playoff.id;
end;
$$;

