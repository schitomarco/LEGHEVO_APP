-- Certifica senza alterazioni i Playoff storici già avviati o completati.
insert into public.league_playoff_start_runs (
  league_id,
  playoff_id,
  configuration_run_id,
  request_id,
  requested_by,
  source_mode,
  start_matchday_number,
  participant_count,
  round_count,
  regular_fixture_count,
  official_fixture_count,
  qualified_team_count,
  entry_count,
  round_record_count,
  tie_count,
  qualification_source_hash,
  qualification_hash,
  schedule_hash,
  opening_bracket_hash,
  result_hash,
  started_at
)
select
  playoff.league_id,
  playoff.id,
  configuration.id,
  public.leghevo_stable_request_uuid(
    'league-playoff-start-backfill:' || playoff.id::text
  ),
  playoff.configured_by,
  'legacy_backfill',
  schedule.start_matchday_number,
  playoff.participant_count,
  playoff.round_count,
  fixture_totals.regular_fixture_count,
  fixture_totals.official_fixture_count,
  entry_totals.entry_count,
  entry_totals.entry_count,
  round_totals.round_record_count,
  tie_totals.tie_count,
  public.compute_league_playoff_qualification_hash_v1(playoff.id),
  public.compute_league_playoff_qualification_hash_v1(playoff.id),
  public.compute_league_playoff_schedule_hash_v1(playoff.id),
  public.compute_league_playoff_opening_bracket_hash_v1(playoff.id),
  public.compute_league_playoff_start_result_hash_v1(
    playoff.id,
    configuration.id,
    schedule.start_matchday_number,
    playoff.participant_count,
    playoff.round_count,
    public.compute_league_playoff_qualification_hash_v1(playoff.id),
    public.compute_league_playoff_qualification_hash_v1(playoff.id),
    public.compute_league_playoff_schedule_hash_v1(playoff.id),
    public.compute_league_playoff_opening_bracket_hash_v1(playoff.id),
    coalesce(playoff.started_at, playoff.configured_at)
  ),
  coalesce(playoff.started_at, playoff.configured_at)
from public.league_playoffs playoff
join public.league_playoff_configuration_runs configuration
  on configuration.playoff_id = playoff.id
cross join lateral (
  select min(matchday.number)::smallint as start_matchday_number
  from public.league_playoff_rounds playoff_round
  join public.matchdays matchday on matchday.id = playoff_round.matchday_id
  where playoff_round.playoff_id = playoff.id
) schedule
cross join lateral (
  select
    count(*)::integer as regular_fixture_count,
    count(*) filter (
      where fixture.finalized_at is not null
        and fixture.officialization_run_id is not null
    )::integer as official_fixture_count
  from public.fantasy_fixtures fixture
  where fixture.league_id = playoff.league_id
) fixture_totals
cross join lateral (
  select count(*)::integer as entry_count
  from public.league_playoff_entries entry
  where entry.playoff_id = playoff.id
) entry_totals
cross join lateral (
  select count(*)::integer as round_record_count
  from public.league_playoff_rounds playoff_round
  where playoff_round.playoff_id = playoff.id
) round_totals
cross join lateral (
  select count(*)::integer as tie_count
  from public.league_playoff_ties tie
  join public.league_playoff_rounds playoff_round
    on playoff_round.id = tie.round_id
  where playoff_round.playoff_id = playoff.id
) tie_totals
where playoff.status in ('active', 'completed')
  and schedule.start_matchday_number is not null
  and not exists (
    select 1
    from public.league_playoff_start_runs run
    where run.playoff_id = playoff.id
  )
on conflict do nothing;

