create table if not exists public.league_playoff_start_runs (
  id bigint generated by default as identity primary key,
  league_id uuid not null
    references public.leagues(id) on delete cascade,
  playoff_id uuid not null unique
    references public.league_playoffs(id) on delete cascade,
  configuration_run_id bigint not null
    references public.league_playoff_configuration_runs(id) on delete restrict,
  request_id uuid not null,
  requested_by uuid not null
    references public.profiles(id) on delete restrict,
  source_mode text not null
    check (source_mode in ('guarded_v1', 'legacy_backfill')),
  start_matchday_number smallint not null
    check (start_matchday_number >= 1),
  participant_count smallint not null
    check (participant_count in (4, 8)),
  round_count smallint not null
    check (round_count in (2, 3)),
  regular_fixture_count integer not null check (regular_fixture_count >= 0),
  official_fixture_count integer not null check (official_fixture_count >= 0),
  qualified_team_count integer not null check (qualified_team_count >= 0),
  entry_count integer not null check (entry_count >= 0),
  round_record_count integer not null check (round_record_count >= 0),
  tie_count integer not null check (tie_count >= 0),
  qualification_source_hash text not null
    check (char_length(qualification_source_hash) = 64),
  qualification_hash text not null
    check (char_length(qualification_hash) = 64),
  schedule_hash text not null
    check (char_length(schedule_hash) = 64),
  opening_bracket_hash text not null
    check (char_length(opening_bracket_hash) = 64),
  result_hash text not null
    check (char_length(result_hash) = 64),
  started_at timestamptz not null default now(),
  check (official_fixture_count <= regular_fixture_count),
  check (qualified_team_count <= participant_count),
  check (
    (participant_count = 4 and round_count = 2)
    or (participant_count = 8 and round_count = 3)
  )
);

