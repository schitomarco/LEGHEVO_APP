create or replace function public.compute_league_playoff_opening_bracket_hash_v1(
  p_playoff_id uuid
)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select public.leghevo_sha256_hex_v1(
    coalesce(
      string_agg(
        playoff_round.round_number::text || ':'
        || tie.bracket_position::text || ':'
        || tie.id::text || ':'
        || case
          when playoff_round.round_number = 1
            then coalesce(tie.home_team_id::text, '-')
          else '-'
        end || ':'
        || case
          when playoff_round.round_number = 1
            then coalesce(tie.home_seed::text, '-')
          else '-'
        end || ':'
        || case
          when playoff_round.round_number = 1
            then coalesce(tie.away_team_id::text, '-')
          else '-'
        end || ':'
        || case
          when playoff_round.round_number = 1
            then coalesce(tie.away_seed::text, '-')
          else '-'
        end,
        '|' order by playoff_round.round_number, tie.bracket_position
      ),
      'empty'
    )
  )
  from public.league_playoff_ties tie
  join public.league_playoff_rounds playoff_round
    on playoff_round.id = tie.round_id
  where playoff_round.playoff_id = p_playoff_id;
$$;

revoke all on function public.compute_league_playoff_opening_bracket_hash_v1(uuid)
from public, anon, authenticated;

