create or replace function public.compute_league_playoff_schedule_hash_v1(
  p_playoff_id uuid
)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select public.leghevo_sha256_hex_v1(
    coalesce(
      string_agg(
        playoff_round.id::text || ':'
        || playoff_round.round_number::text || ':'
        || playoff_round.name || ':'
        || playoff_round.matchday_id::text || ':'
        || matchday.number::text,
        '|' order by playoff_round.round_number
      ),
      'empty'
    )
