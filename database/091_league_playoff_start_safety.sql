create or replace function public.get_league_playoff_start_integrity_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_playoff public.league_playoffs%rowtype;
  v_run public.league_playoff_start_runs%rowtype;
  v_qualification_hash text;
  v_schedule_hash text;
  v_opening_bracket_hash text;
  v_result_hash text;
  v_counts_match boolean := false;
  v_hashes_match boolean := false;
  v_configuration_matches boolean := false;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if not public.is_league_member(p_league_id)
    and not public.is_league_admin(p_league_id) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  select playoff.*
  into v_playoff
  from public.league_playoffs playoff
  where playoff.league_id = p_league_id;

  select run.*
  into v_run
  from public.league_playoff_start_runs run
  where run.league_id = p_league_id
  order by run.started_at desc, run.id desc
  limit 1;

  if v_run.id is not null then
    v_qualification_hash :=
      public.compute_league_playoff_qualification_hash_v1(v_run.playoff_id);
    v_schedule_hash :=
      public.compute_league_playoff_schedule_hash_v1(v_run.playoff_id);
    v_opening_bracket_hash :=
      public.compute_league_playoff_opening_bracket_hash_v1(v_run.playoff_id);
    v_result_hash := public.compute_league_playoff_start_result_hash_v1(
      v_run.playoff_id,
      v_run.configuration_run_id,
      v_run.start_matchday_number,
      v_run.participant_count,
      v_run.round_count,
      v_run.qualification_source_hash,
      v_run.qualification_hash,
      v_run.schedule_hash,
      v_run.opening_bracket_hash,
      v_run.started_at
    );

    v_counts_match :=
      v_run.entry_count = (
        select count(*)::integer
        from public.league_playoff_entries entry
        where entry.playoff_id = v_run.playoff_id
      )
      and v_run.round_record_count = (
        select count(*)::integer
        from public.league_playoff_rounds playoff_round
        where playoff_round.playoff_id = v_run.playoff_id
      )
      and v_run.tie_count = (
        select count(*)::integer
        from public.league_playoff_ties tie
        join public.league_playoff_rounds playoff_round
          on playoff_round.id = tie.round_id
        where playoff_round.playoff_id = v_run.playoff_id
      );

    v_hashes_match :=
      v_run.qualification_hash = v_qualification_hash
      and v_run.schedule_hash = v_schedule_hash
      and v_run.opening_bracket_hash = v_opening_bracket_hash
      and v_run.result_hash = v_result_hash
      and (
        v_run.source_mode = 'legacy_backfill'
        or v_run.qualification_source_hash = v_run.qualification_hash
      );

    v_configuration_matches := exists (
      select 1
      from public.league_playoff_configuration_runs configuration
      where configuration.id = v_run.configuration_run_id
        and configuration.playoff_id = v_run.playoff_id
        and configuration.participant_count = v_run.participant_count
        and configuration.round_count = v_run.round_count
    );
  end if;

  return jsonb_build_object(
    'leagueId', p_league_id,
    'ready',
      v_playoff.id is null
      or v_playoff.status = 'configured'
      or (
        v_run.id is not null
        and v_counts_match
        and v_hashes_match
        and v_configuration_matches
      ),
    'playoffExists', v_playoff.id is not null,
    'playoffStatus', v_playoff.status,
    'startCertified', v_run.id is not null,
    'startRunId', v_run.id,
    'sourceMode', v_run.source_mode,
    'configurationMatches', v_configuration_matches,
    'countsMatch', v_counts_match,
    'hashesMatch', v_hashes_match,
    'qualificationHash', v_run.qualification_hash,
    'scheduleHash', v_run.schedule_hash,
    'openingBracketHash', v_run.opening_bracket_hash,
    'resultHash', v_run.result_hash
  );
end;
$$;

