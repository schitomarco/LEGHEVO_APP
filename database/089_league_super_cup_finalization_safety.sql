create or replace function public.finalize_league_super_cup_guarded_v1(
  p_league_id uuid,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_league public.leagues%rowtype;
  v_super_cup public.league_super_cups%rowtype;
  v_matchday public.matchdays%rowtype;
  v_schedule_run public.league_super_cup_schedule_runs%rowtype;
  v_existing_run public.league_super_cup_finalization_runs%rowtype;
  v_officialization public.matchday_officialization_runs%rowtype;
  v_home_resolution public.lineup_resolution_runs%rowtype;
  v_away_resolution public.lineup_resolution_runs%rowtype;
  v_scoring_rules jsonb := '{}'::jsonb;
  v_home_breakdown jsonb;
  v_away_breakdown jsonb;
  v_goal_resolution jsonb;
  v_home_points numeric(8,2);
  v_away_points numeric(8,2);
  v_home_goals smallint;
  v_away_goals smallint;
  v_winner_id uuid;
  v_runner_up_id uuid;
  v_decided_by text;
  v_input_hash text;
  v_result_hash text;
  v_finalized_at timestamptz := now();
  v_winner_name text;
  v_member_user_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if p_request_id is null then
    raise exception 'Identificativo richiesta mancante.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'leghevo:league-super-cup-finalization:' || p_league_id::text,
      0
    )
  );

  select run.*
  into v_existing_run
  from public.league_super_cup_finalization_runs run
  where run.league_id = p_league_id
    and run.request_id = p_request_id;

  if found then
    return public.get_league_super_cup_state_v3(p_league_id)
      || jsonb_build_object(
        'idempotentReplay', true,
        'finalizationRunId', v_existing_run.id
      );
  end if;

  select league.*
  into v_league
  from public.leagues league
  where league.id = p_league_id
  for update;

  if not found then
    raise exception 'Lega non trovata.';
  end if;

  if v_league.owner_id <> auth.uid() then
    raise exception 'Solo il Presidente può ufficializzare la Supercoppa.';
  end if;

  select super_cup.*
  into v_super_cup
  from public.league_super_cups super_cup
  where super_cup.league_id = p_league_id
  for update;

  if not found then
    raise exception 'La Supercoppa non è stata programmata.';
  end if;

  select run.*
  into v_schedule_run
  from public.league_super_cup_schedule_runs run
  where run.super_cup_id = v_super_cup.id;

  if not found then
    raise exception 'Programmazione della Supercoppa non certificata.';
  end if;

  select run.*
  into v_existing_run
  from public.league_super_cup_finalization_runs run
  where run.super_cup_id = v_super_cup.id;

  if found then
    return public.get_league_super_cup_state_v3(p_league_id)
      || jsonb_build_object(
        'idempotentReplay', true,
        'alreadyFinalized', true,
        'finalizationRunId', v_existing_run.id
      );
  end if;

  if v_super_cup.status = 'completed' then
    raise exception 'Supercoppa conclusa ma priva di certificato: eseguire nuovamente la migrazione v0.60.5.';
  end if;

  select matchday.*
  into v_matchday
  from public.matchdays matchday
  where matchday.id = v_super_cup.matchday_id;

  if not found then
    raise exception 'Giornata della Supercoppa non trovata.';
  end if;

  if now() < coalesce(
    v_matchday.ends_at,
    v_matchday.starts_at + interval '4 days'
  ) then
    raise exception 'La giornata reale della Supercoppa non è ancora terminata.';
  end if;

  select officialization.*
  into v_officialization
  from public.matchday_officialization_runs officialization
  where officialization.league_id = p_league_id
    and officialization.matchday_id = v_super_cup.matchday_id
    and officialization.superseded_at is null
  order by officialization.finalization_revision desc
  limit 1;

  if not found
    or v_officialization.fixture_count <> v_officialization.finalized_fixture_count then
    raise exception 'La giornata della Supercoppa non è ancora ufficializzata integralmente.';
  end if;

  v_home_breakdown := public.get_team_matchday_breakdown(
    v_super_cup.league_champion_team_id,
    v_super_cup.matchday_id
  );
  v_away_breakdown := public.get_team_matchday_breakdown(
    v_super_cup.challenger_team_id,
    v_super_cup.matchday_id
  );

  if not coalesce((v_home_breakdown ->> 'isReady')::boolean, false)
    or not coalesce((v_away_breakdown ->> 'isReady')::boolean, false)
    or nullif(v_home_breakdown ->> 'totalPoints', '') is null
    or nullif(v_away_breakdown ->> 'totalPoints', '') is null then
    raise exception 'Mancano ancora voti o sostituzioni certificate per la Supercoppa.';
  end if;

  select resolution.*
  into v_home_resolution
  from public.lineup_resolution_runs resolution
  where resolution.fantasy_team_id = v_super_cup.league_champion_team_id
    and resolution.matchday_id = v_super_cup.matchday_id
    and resolution.superseded_at is null
    and resolution.is_ready
  order by resolution.resolution_revision desc
  limit 1;

  select resolution.*
  into v_away_resolution
  from public.lineup_resolution_runs resolution
  where resolution.fantasy_team_id = v_super_cup.challenger_team_id
    and resolution.matchday_id = v_super_cup.matchday_id
    and resolution.superseded_at is null
    and resolution.is_ready
  order by resolution.resolution_revision desc
  limit 1;

  if v_home_resolution.id is null or v_away_resolution.id is null then
    raise exception 'Risoluzioni protette delle due formazioni non disponibili.';
  end if;

  v_home_points := round((v_home_breakdown ->> 'totalPoints')::numeric, 2);
  v_away_points := round((v_away_breakdown ->> 'totalPoints')::numeric, 2);

  select league.scoring_rules
  into v_scoring_rules
  from public.leagues league
  where league.id = p_league_id;

  v_goal_resolution := public.resolve_fantasy_fixture_goals(
    v_home_points,
    v_away_points,
    coalesce(v_scoring_rules, '{}'::jsonb)
  );

  v_home_goals := nullif(v_goal_resolution ->> 'homeGoals', '')::smallint;
  v_away_goals := nullif(v_goal_resolution ->> 'awayGoals', '')::smallint;

  if v_home_goals is null or v_away_goals is null then
    raise exception 'Conversione dei fantapunti in gol non disponibile.';
  end if;

  if v_home_goals > v_away_goals then
    v_winner_id := v_super_cup.league_champion_team_id;
    v_runner_up_id := v_super_cup.challenger_team_id;
    v_decided_by := 'goals';
  elsif v_away_goals > v_home_goals then
    v_winner_id := v_super_cup.challenger_team_id;
    v_runner_up_id := v_super_cup.league_champion_team_id;
    v_decided_by := 'goals';
  elsif v_home_points > v_away_points then
    v_winner_id := v_super_cup.league_champion_team_id;
    v_runner_up_id := v_super_cup.challenger_team_id;
    v_decided_by := 'fantasy_points';
  elsif v_away_points > v_home_points then
    v_winner_id := v_super_cup.challenger_team_id;
    v_runner_up_id := v_super_cup.league_champion_team_id;
    v_decided_by := 'fantasy_points';
  else
    v_winner_id := v_super_cup.league_champion_team_id;
    v_runner_up_id := v_super_cup.challenger_team_id;
    v_decided_by := 'league_champion';
  end if;

  v_input_hash := public.compute_league_super_cup_finalization_input_hash_v1(
    v_super_cup.id,
    v_schedule_run.result_hash,
    v_officialization.result_hash,
    v_home_resolution.result_hash,
    v_away_resolution.result_hash,
    v_home_points,
    v_away_points,
    v_home_goals,
    v_away_goals,
    'guarded_v1'
  );

  v_result_hash := public.compute_league_super_cup_finalization_result_hash_v1(
    v_input_hash,
    v_winner_id,
    v_runner_up_id,
    v_decided_by
  );

  update public.league_super_cups
  set
    status = 'completed',
    home_points = v_home_points,
    away_points = v_away_points,
    home_goals = v_home_goals,
    away_goals = v_away_goals,
    home_ready = true,
    away_ready = true,
    home_counted_players = least(v_home_resolution.counted_players, 11),
    away_counted_players = least(v_away_resolution.counted_players, 11),
    winner_team_id = v_winner_id,
    runner_up_team_id = v_runner_up_id,
    decided_by = v_decided_by,
    finalized_by = auth.uid(),
    completed_at = v_finalized_at
  where id = v_super_cup.id;

  insert into public.league_super_cup_finalization_runs (
    league_id,
    super_cup_id,
    schedule_run_id,
    request_id,
    requested_by,
    source_mode,
    matchday_id,
    matchday_officialization_run_id,
    home_resolution_id,
    away_resolution_id,
    schedule_result_hash,
    officialization_result_hash,
    home_resolution_hash,
    away_resolution_hash,
    input_hash,
    result_hash,
    home_points,
    away_points,
    home_goals,
    away_goals,
    winner_team_id,
    runner_up_team_id,
    decided_by,
    finalized_at
  ) values (
    p_league_id,
    v_super_cup.id,
    v_schedule_run.id,
    p_request_id,
    auth.uid(),
    'guarded_v1',
    v_super_cup.matchday_id,
    v_officialization.id,
    v_home_resolution.id,
    v_away_resolution.id,
    v_schedule_run.result_hash,
    v_officialization.result_hash,
    v_home_resolution.result_hash,
    v_away_resolution.result_hash,
    v_input_hash,
    v_result_hash,
    v_home_points,
    v_away_points,
    v_home_goals,
    v_away_goals,
    v_winner_id,
    v_runner_up_id,
    v_decided_by,
    v_finalized_at
  );

  select team.name
  into v_winner_name
  from public.fantasy_teams team
  where team.id = v_winner_id;

  if to_regprocedure(
    'public.create_user_notification(uuid,uuid,text,text,text,text,jsonb,text)'
  ) is not null then
    for v_member_user_id in
      select member.user_id
      from public.league_members member
      where member.league_id = p_league_id
    loop
      perform public.create_user_notification(
        v_member_user_id,
        p_league_id,
        'result',
        'Supercoppa assegnata',
        coalesce(v_winner_name, 'La squadra vincitrice')
          || ' ha vinto la Supercoppa di '
          || v_league.name
          || '.',
        'leagueSuperCup',
        jsonb_build_object(
          'superCupId', v_super_cup.id,
          'winnerTeamId', v_winner_id,
          'decidedBy', v_decided_by,
          'finalizationPolicy', 'guarded_v1'
        ),
        pg_catalog.format('league-super-cup-completed:%s', v_super_cup.id)
      );
    end loop;
  end if;

  return public.get_league_super_cup_state_v3(p_league_id)
    || jsonb_build_object(
      'idempotentReplay', false,
      'alreadyFinalized', false
    );
end;
$$;

