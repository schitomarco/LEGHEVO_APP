with candidates as (
  select
    super_cup.*,
    schedule_run.id as schedule_run_id,
    schedule_run.result_hash as schedule_result_hash,
    coalesce(super_cup.finalized_by, super_cup.created_by) as requested_by
  from public.league_super_cups super_cup
  join public.league_super_cup_schedule_runs schedule_run
    on schedule_run.super_cup_id = super_cup.id
  where super_cup.status = 'completed'
    and super_cup.winner_team_id is not null
    and super_cup.runner_up_team_id is not null
    and super_cup.home_points is not null
    and super_cup.away_points is not null
    and super_cup.home_goals is not null
    and super_cup.away_goals is not null
    and super_cup.decided_by is not null
    and not exists (
      select 1
      from public.league_super_cup_finalization_runs run
      where run.super_cup_id = super_cup.id
    )
), prepared as (
  select
    candidate.*,
    public.compute_league_super_cup_finalization_input_hash_v1(
      candidate.id,
      candidate.schedule_result_hash,
      null,
      null,
      null,
      candidate.home_points,
      candidate.away_points,
      candidate.home_goals,
      candidate.away_goals,
      'legacy_backfill'
    ) as computed_input_hash
  from candidates candidate
)
insert into public.league_super_cup_finalization_runs (
  league_id,
  super_cup_id,
  schedule_run_id,
  request_id,
  requested_by,
  source_mode,
  matchday_id,
  schedule_result_hash,
  input_hash,
  result_hash,
  home_points,
  away_points,
  home_goals,
  away_goals,
  winner_team_id,
  runner_up_team_id,
  decided_by,
  finalized_at
)
select
  prepared.league_id,
  prepared.id,
  prepared.schedule_run_id,
  public.leghevo_stable_request_uuid(
    'league-super-cup-finalization-backfill:' || prepared.id::text
  ),
  prepared.requested_by,
  'legacy_backfill',
  prepared.matchday_id,
  prepared.schedule_result_hash,
  prepared.computed_input_hash,
  public.compute_league_super_cup_finalization_result_hash_v1(
    prepared.computed_input_hash,
    prepared.winner_team_id,
    prepared.runner_up_team_id,
    prepared.decided_by
  ),
  prepared.home_points,
  prepared.away_points,
  prepared.home_goals,
  prepared.away_goals,
  prepared.winner_team_id,
  prepared.runner_up_team_id,
  prepared.decided_by,
  coalesce(prepared.completed_at, prepared.updated_at, prepared.created_at)
from prepared
on conflict do nothing;

