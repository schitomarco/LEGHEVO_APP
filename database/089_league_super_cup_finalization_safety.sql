create or replace function public.get_league_super_cup_finalization_integrity_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_run public.league_super_cup_finalization_runs%rowtype;
  v_input_hash_matches boolean := false;
  v_result_hash_matches boolean := false;
  v_verdict_matches boolean := false;
  v_sources_ready boolean := false;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if not public.is_league_member(p_league_id)
    and not public.is_league_admin(p_league_id) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  select run.*
  into v_run
  from public.league_super_cup_finalization_runs run
  where run.league_id = p_league_id
  order by run.finalized_at desc, run.id desc
  limit 1;

  if v_run.id is not null then
    v_input_hash_matches := v_run.input_hash =
      public.compute_league_super_cup_finalization_input_hash_v1(
        v_run.super_cup_id,
        v_run.schedule_result_hash,
        v_run.officialization_result_hash,
        v_run.home_resolution_hash,
        v_run.away_resolution_hash,
        v_run.home_points,
        v_run.away_points,
        v_run.home_goals,
        v_run.away_goals,
        v_run.source_mode
      );

    v_result_hash_matches := v_run.result_hash =
      public.compute_league_super_cup_finalization_result_hash_v1(
        v_run.input_hash,
        v_run.winner_team_id,
        v_run.runner_up_team_id,
        v_run.decided_by
      );

    select exists (
      select 1
      from public.league_super_cups super_cup
      where super_cup.id = v_run.super_cup_id
        and super_cup.status = 'completed'
        and super_cup.home_points = v_run.home_points
        and super_cup.away_points = v_run.away_points
        and super_cup.home_goals = v_run.home_goals
        and super_cup.away_goals = v_run.away_goals
        and super_cup.winner_team_id = v_run.winner_team_id
        and super_cup.runner_up_team_id = v_run.runner_up_team_id
        and super_cup.decided_by = v_run.decided_by
    ) into v_verdict_matches;

    v_sources_ready := case
      when v_run.source_mode = 'legacy_backfill' then true
      else v_run.matchday_officialization_run_id is not null
        and v_run.home_resolution_id is not null
        and v_run.away_resolution_id is not null
        and char_length(v_run.officialization_result_hash) = 32
        and char_length(v_run.home_resolution_hash) = 32
        and char_length(v_run.away_resolution_hash) = 32
    end;
  end if;

  return jsonb_build_object(
    'leagueId', p_league_id,
    'ready', v_run.id is not null
      and v_input_hash_matches
      and v_result_hash_matches
      and v_verdict_matches
      and v_sources_ready,
    'finalizationCertified', v_run.id is not null,
    'finalizationRunId', v_run.id,
    'requestId', v_run.request_id,
    'sourceMode', v_run.source_mode,
    'inputHashMatches', v_input_hash_matches,
    'resultHashMatches', v_result_hash_matches,
    'verdictMatches', v_verdict_matches,
    'sourcesReady', v_sources_ready,
    'inputHash', v_run.input_hash,
    'resultHash', v_run.result_hash
  );
end;
$$;

revoke all on function public.get_league_super_cup_finalization_integrity_v1(uuid)
from public, anon, authenticated;
grant execute on function public.get_league_super_cup_finalization_integrity_v1(uuid)
to authenticated;

commit;

