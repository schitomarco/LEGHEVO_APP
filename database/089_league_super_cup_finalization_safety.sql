create or replace function public.get_league_super_cup_state_v3(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_state jsonb;
  v_run public.league_super_cup_finalization_runs%rowtype;
begin
  v_state := public.get_league_super_cup_state_v2(p_league_id);

  select run.*
  into v_run
  from public.league_super_cup_finalization_runs run
  where run.league_id = p_league_id
  order by run.finalized_at desc, run.id desc
  limit 1;

  return coalesce(v_state, '{}'::jsonb) || jsonb_build_object(
    'finalizationPolicy', 'guarded_v1',
    'finalizationCertified', v_run.id is not null,
    'finalizationRunId', v_run.id,
    'finalizationRequestId', v_run.request_id,
    'finalizationSourceMode', v_run.source_mode,
    'finalizationInputHash', v_run.input_hash,
    'finalizationResultHash', v_run.result_hash,
    'finalizationOfficializationRunId', v_run.matchday_officialization_run_id,
    'finalizationHomeResolutionId', v_run.home_resolution_id,
    'finalizationAwayResolutionId', v_run.away_resolution_id
  );
end;
$$;

