create table if not exists public.result_correction_runs (
  id bigint generated by default as identity primary key,
  league_id uuid not null
    references public.leagues(id) on delete cascade,
  matchday_id uuid not null
    references public.matchdays(id) on delete cascade,
  fixture_id uuid
    references public.fantasy_fixtures(id) on delete cascade,
  request_id uuid not null unique,
  scope text not null,
  correction_revision integer not null,
  input_hash text not null,
  reason text not null,
  previous_officialization_id bigint
    references public.matchday_officialization_runs(id) on delete set null,
  affected_fixture_count integer not null,
  previous_official_fixture_count integer not null,
  result_payload jsonb not null default '{}'::jsonb,
  requested_by uuid references public.profiles(id) on delete set null,
  reopened_at timestamptz not null default now(),
  constraint result_correction_scope_check
    check (scope in ('fixture', 'matchday')),
  constraint result_correction_scope_fixture_check
    check (
      (scope = 'fixture' and fixture_id is not null)
      or (scope = 'matchday' and fixture_id is null)
    ),
  constraint result_correction_revision_check
    check (correction_revision >= 1),
  constraint result_correction_input_hash_check
    check (length(input_hash) = 32),
  constraint result_correction_reason_check
    check (char_length(trim(reason)) between 10 and 240),
  constraint result_correction_affected_check
    check (affected_fixture_count >= 1),
  constraint result_correction_previous_count_check
    check (previous_official_fixture_count >= affected_fixture_count),
  unique (matchday_id, correction_revision)
);

