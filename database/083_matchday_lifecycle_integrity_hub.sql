create or replace function public.get_league_matchday_lifecycle_state_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_league public.leagues%rowtype;
  v_matchday public.matchdays%rowtype;
  v_fixture_count integer := 0;
  v_finalized_fixture_count integer := 0;
  v_team_slot_count integer := 0;
  v_resolution_count integer := 0;
  v_projection_count integer := 0;
  v_officialization_count integer := 0;
  v_correction_count integer := 0;
  v_progression_count integer := 0;
  v_completion_count integer := 0;
  v_phase text := 'awaiting_competition';
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if not public.is_league_member(p_league_id)
    and not public.is_league_admin(p_league_id) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  select league.*
  into v_league
  from public.leagues league
  where league.id = p_league_id;

  if not found then
    raise exception 'Lega non trovata.';
  end if;

  if v_league.current_matchday_id is not null then
    select matchday.*
    into v_matchday
    from public.matchdays matchday
    where matchday.id = v_league.current_matchday_id;

    select
      count(*)::integer,
      count(*) filter (where fixture.finalized_at is not null)::integer
    into v_fixture_count, v_finalized_fixture_count
    from public.fantasy_fixtures fixture
    where fixture.league_id = p_league_id
      and fixture.matchday_id = v_league.current_matchday_id;

    v_team_slot_count := v_fixture_count * 2;

    select count(*)::integer
    into v_resolution_count
    from public.lineup_resolution_runs run
    where run.league_id = p_league_id
      and run.matchday_id = v_league.current_matchday_id
      and run.superseded_at is null;

    select count(*)::integer
    into v_projection_count
    from public.live_fixture_projection_runs run
    where run.league_id = p_league_id
      and run.matchday_id = v_league.current_matchday_id
      and run.superseded_at is null;

    select count(*)::integer
    into v_officialization_count
    from public.matchday_officialization_runs run
    where run.league_id = p_league_id
      and run.matchday_id = v_league.current_matchday_id
      and run.superseded_at is null;

    select count(*)::integer
    into v_correction_count
    from public.result_correction_runs run
    where run.league_id = p_league_id
      and run.matchday_id = v_league.current_matchday_id;

    select count(*)::integer
    into v_progression_count
    from public.matchday_progression_runs run
    where run.league_id = p_league_id
      and run.matchday_id = v_league.current_matchday_id
      and run.superseded_at is null;
  end if;

  select count(*)::integer
  into v_completion_count
  from public.season_completion_runs run
  where run.league_id = p_league_id;

  v_phase := case
    when v_league.status in ('completed', 'archived')
      or v_completion_count > 0
      then 'season_completed'
    when v_league.competition_started_at is null
      then 'awaiting_competition'
    when v_league.current_matchday_id is null
      then 'awaiting_matchday'
    when v_matchday.lineups_finalized_at is null
      then 'lineup_open'
    when v_finalized_fixture_count = 0
      then 'live'
    when v_finalized_fixture_count < v_fixture_count
      then 'officializing'
    when v_progression_count = 0
      then 'awaiting_progression'
    else 'progressed'
  end;

  return jsonb_build_object(
    'policy', 'coordinated_v1',
    'phase', v_phase,
    'leagueStatus', v_league.status,
    'competitionStartedAt', v_league.competition_started_at,
    'currentMatchdayId', v_league.current_matchday_id,
    'currentMatchdayNumber', v_league.current_matchday_number,
    'lineupsFinalizedAt', v_matchday.lineups_finalized_at,
    'lineupLockRevision', coalesce(v_matchday.lineup_lock_revision, 0),
    'fixtureCount', v_fixture_count,
    'finalizedFixtureCount', v_finalized_fixture_count,
    'teamSlotCount', v_team_slot_count,
    'currentResolutionCount', v_resolution_count,
    'currentProjectionCount', v_projection_count,
    'currentOfficializationCount', v_officialization_count,
    'correctionCount', v_correction_count,
    'currentProgressionCount', v_progression_count,
    'seasonCompletionCertified', v_completion_count > 0
  );
end;
$$;

-- Diagnostica unificata end-to-end. Ogni sezione conserva il dettaglio della
-- diagnostica specialistica già installata, mentre healthy certifica l'intera
-- catena senza ricostruire o duplicare le regole sportive.
create or replace function public.get_league_matchday_lifecycle_integrity_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_lineup jsonb;
  v_substitution jsonb;
  v_live jsonb;
  v_officialization jsonb;
  v_correction jsonb;
  v_progression jsonb;
  v_completion jsonb;
  v_state jsonb;
  v_direct_writes_blocked boolean := false;
  v_guarded_endpoints_ready boolean := false;
  v_healthy boolean := false;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if not public.is_league_member(p_league_id)
    and not public.is_league_admin(p_league_id) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  v_lineup := public.get_league_lineup_integrity_v2(p_league_id);
  v_substitution := public.get_league_substitution_integrity_v1(p_league_id);
  v_live := public.get_league_live_projection_integrity_v1(p_league_id);
  v_officialization :=
    public.get_league_matchday_officialization_integrity_v1(p_league_id);
  v_correction := public.get_league_result_correction_integrity_v1(p_league_id);
  v_progression :=
    public.get_league_matchday_progression_integrity_v1(p_league_id);
  v_completion :=
    public.get_league_season_completion_integrity_v1(p_league_id);
  v_state := public.get_league_matchday_lifecycle_state_v1(p_league_id);

  v_direct_writes_blocked :=
    not has_table_privilege('authenticated', 'public.matchdays', 'UPDATE')
    and not has_table_privilege(
      'authenticated', 'public.fantasy_fixtures', 'UPDATE'
    )
    and not has_table_privilege(
      'authenticated', 'public.player_match_scores', 'INSERT'
    )
    and not has_table_privilege(
      'authenticated', 'public.lineups', 'UPDATE'
    )
    and not has_table_privilege(
      'authenticated', 'public.lineup_entries', 'INSERT'
    )
    and not has_table_privilege(
      'authenticated', 'public.live_fixture_projection_runs', 'UPDATE'
    )
    and not has_table_privilege(
      'authenticated', 'public.matchday_officialization_runs', 'INSERT'
    )
    and not has_table_privilege(
      'authenticated', 'public.result_correction_runs', 'UPDATE'
    )
    and not has_table_privilege(
      'authenticated', 'public.matchday_progression_runs', 'INSERT'
    )
    and not has_table_privilege(
      'authenticated', 'public.season_completion_runs', 'UPDATE'
    );

  v_guarded_endpoints_ready :=
    has_function_privilege(
      'authenticated',
      'public.save_team_lineup_guarded_v1(uuid,uuid,text,uuid[],uuid[],integer,uuid)',
      'execute'
    )
    and to_regprocedure(
      'public.certify_team_matchday_substitutions_guarded_v1(uuid,uuid,uuid)'
    ) is not null
    and not has_function_privilege(
      'authenticated',
      'public.certify_team_matchday_substitutions_guarded_v1(uuid,uuid,uuid)',
      'execute'
    )
    and has_function_privilege(
      'authenticated',
      'public.get_my_live_match_v6(uuid)',
      'execute'
    )
    and has_function_privilege(
      'authenticated',
      'public.finalize_league_matchday_guarded_v3(uuid,uuid,uuid)',
      'execute'
    )
    and has_function_privilege(
      'authenticated',
      'public.reopen_league_fixture_guarded_v1(uuid,uuid,text,uuid)',
      'execute'
    )
    and has_function_privilege(
      'authenticated',
      'public.complete_league_season_guarded_v1(uuid,uuid)',
      'execute'
    );

  v_healthy :=
    coalesce((v_lineup ->> 'healthy')::boolean, false)
    and coalesce((v_substitution ->> 'healthy')::boolean, false)
    and coalesce((v_live ->> 'healthy')::boolean, false)
    and coalesce((v_officialization ->> 'healthy')::boolean, false)
    and coalesce((v_correction ->> 'healthy')::boolean, false)
    and coalesce((v_progression ->> 'healthy')::boolean, false)
    and coalesce((v_completion ->> 'healthy')::boolean, false)
    and v_direct_writes_blocked
    and v_guarded_endpoints_ready;

  return jsonb_build_object(
    'healthy', v_healthy,
    'policy', 'end_to_end_v1',
    'stageCount', 7,
    'directWritesBlocked', v_direct_writes_blocked,
    'guardedEndpointsReady', v_guarded_endpoints_ready,
    'state', v_state,
    'stages', jsonb_build_object(
      'lineup', v_lineup,
      'substitution', v_substitution,
      'live', v_live,
      'officialization', v_officialization,
      'correction', v_correction,
      'progression', v_progression,
      'completion', v_completion
    )
  );
end;
$$;

create or replace function public.get_league_management_state_v12(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_state jsonb;
  v_lifecycle jsonb;
  v_checks jsonb;
  v_stages jsonb;
begin
  v_state := public.get_league_management_state_v11(p_league_id);
  v_lifecycle :=
    public.get_league_matchday_lifecycle_integrity_v1(p_league_id);
  v_checks := coalesce(v_state -> 'checks', '{}'::jsonb);
  v_stages := coalesce(v_lifecycle -> 'stages', '{}'::jsonb);

  return v_state || jsonb_build_object(
    'matchdayLifecycle', v_lifecycle,
    'checks', v_checks || jsonb_build_object(
      'lineupLifecycleReady',
        coalesce((v_stages #>> '{lineup,healthy}')::boolean, false)
        and coalesce((v_stages #>> '{substitution,healthy}')::boolean, false),
      'liveLifecycleReady',
        coalesce((v_stages #>> '{live,healthy}')::boolean, false)
        and coalesce(
          (v_stages #>> '{officialization,healthy}')::boolean,
          false
        )
        and coalesce((v_stages #>> '{correction,healthy}')::boolean, false),
      'matchdayLifecycleReady',
        coalesce((v_lifecycle ->> 'healthy')::boolean, false)
    )
  );
end;
$$;

