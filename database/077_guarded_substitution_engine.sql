begin;

create table if not exists public.lineup_resolution_runs (
  id bigint generated by default as identity primary key,
  league_id uuid not null
    references public.leagues(id) on delete cascade,
  fantasy_team_id uuid not null
    references public.fantasy_teams(id) on delete cascade,
  matchday_id uuid not null
    references public.matchdays(id) on delete cascade,
  lineup_id uuid
    references public.lineups(id) on delete set null,
  request_id uuid not null unique,
  resolution_revision integer not null,
  input_hash text not null,
  result_hash text not null,
  lineup_content_hash text,
  matchday_lineup_lock_hash text,
  max_substitutions integer not null,
  substitutions_used integer not null,
  counted_players integer not null,
  unavailable_starters integer not null,
  total_points numeric(8,2),
  is_ready boolean not null,
  resolution_payload jsonb not null default '{}'::jsonb,
  response_payload jsonb not null default '{}'::jsonb,
  processed_at timestamptz not null default now(),
  superseded_at timestamptz,
  constraint lineup_resolution_runs_revision_check
    check (resolution_revision >= 1),
  constraint lineup_resolution_runs_input_hash_check
    check (length(input_hash) = 32),
  constraint lineup_resolution_runs_result_hash_check
    check (length(result_hash) = 32),
  constraint lineup_resolution_runs_lineup_hash_check
    check (
      lineup_content_hash is null
      or length(lineup_content_hash) = 32
    ),
  constraint lineup_resolution_runs_matchday_hash_check
    check (
      matchday_lineup_lock_hash is null
      or length(matchday_lineup_lock_hash) = 32
    ),
  constraint lineup_resolution_runs_max_substitutions_check
    check (max_substitutions between 0 and 11),
  constraint lineup_resolution_runs_substitutions_used_check
    check (
      substitutions_used between 0 and 11
      and substitutions_used <= max_substitutions
    ),
  constraint lineup_resolution_runs_counted_players_check
    check (counted_players between 0 and 11),
  constraint lineup_resolution_runs_unavailable_starters_check
    check (unavailable_starters between 0 and 11),
  unique (fantasy_team_id, matchday_id, resolution_revision),
  unique (fantasy_team_id, matchday_id, input_hash)
);

create unique index if not exists lineup_resolution_runs_current_idx
  on public.lineup_resolution_runs (fantasy_team_id, matchday_id)
  where superseded_at is null;

create index if not exists lineup_resolution_runs_league_matchday_idx
  on public.lineup_resolution_runs (
    league_id,
    matchday_id,
    superseded_at
  );

create table if not exists public.lineup_substitution_events (
  id bigint generated by default as identity primary key,
  resolution_id bigint not null
    references public.lineup_resolution_runs(id) on delete cascade,
  league_id uuid not null
    references public.leagues(id) on delete cascade,
  fantasy_team_id uuid not null
    references public.fantasy_teams(id) on delete cascade,
  matchday_id uuid not null
    references public.matchdays(id) on delete cascade,
  lineup_id uuid not null
    references public.lineups(id) on delete cascade,
  substitution_sequence smallint not null,
  outgoing_athlete_id uuid not null
    references public.athletes(id),
  incoming_athlete_id uuid not null
    references public.athletes(id),
  starter_slot smallint not null,
  bench_slot smallint not null,
  reason text not null default 'no_vote',
  compatibility_mode public.league_mode not null,
  event_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint lineup_substitution_events_sequence_check
    check (substitution_sequence between 1 and 11),
  constraint lineup_substitution_events_slots_check
    check (starter_slot between 1 and 11 and bench_slot > 11),
  constraint lineup_substitution_events_athletes_check
    check (outgoing_athlete_id <> incoming_athlete_id),
  constraint lineup_substitution_events_reason_check
    check (reason = 'no_vote'),
  unique (resolution_id, substitution_sequence),
  unique (resolution_id, outgoing_athlete_id),
  unique (resolution_id, incoming_athlete_id)
);

create index if not exists lineup_substitution_events_team_matchday_idx
  on public.lineup_substitution_events (
    fantasy_team_id,
    matchday_id,
    substitution_sequence
  );

alter table public.lineup_resolution_runs enable row level security;
alter table public.lineup_substitution_events enable row level security;

