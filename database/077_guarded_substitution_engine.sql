create or replace function public.prevent_substitution_resolution_mutation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if coalesce(
    current_setting('leghevo.substitution_resolution_context', true),
    ''
  ) = 'on' then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  raise exception
    'Elaborazione sostituzioni certificata: modifica diretta non consentita.';
end;
$$;

