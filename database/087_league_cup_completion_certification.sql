create or replace function public.compute_league_cup_completion_fingerprint_v1(
  p_cup_id uuid
)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_cup public.league_cups%rowtype;
  v_final_round public.league_cup_rounds%rowtype;
  v_run public.league_cup_round_finalization_runs%rowtype;
  v_ties text := '';
  v_entries text := '';
  v_payload text;
begin
  select cup.*
  into v_cup
  from public.league_cups cup
  where cup.id = p_cup_id;

  if not found or v_cup.status <> 'completed'
    or v_cup.champion_team_id is null
    or v_cup.runner_up_team_id is null then
    return null;
  end if;

  select cup_round.*
  into v_final_round
  from public.league_cup_rounds cup_round
  where cup_round.cup_id = v_cup.id
    and cup_round.round_number = v_cup.round_count;

  if not found or v_final_round.status <> 'official' then
    return null;
  end if;

  select run.*
  into v_run
  from public.league_cup_round_finalization_runs run
  where run.cup_id = v_cup.id
    and run.round_id = v_final_round.id
    and run.cup_completed
  order by run.id desc
  limit 1;

  if not found or v_run.champion_team_id is distinct from v_cup.champion_team_id then
    return null;
  end if;

  select coalesce(
    string_agg(
      tie.bracket_position::text || ':'
      || coalesce(tie.home_team_id::text, '-') || ':'
      || coalesce(tie.away_team_id::text, '-') || ':'
      || coalesce(tie.home_points::text, '-') || ':'
      || coalesce(tie.away_points::text, '-') || ':'
      || coalesce(tie.home_goals::text, '-') || ':'
      || coalesce(tie.away_goals::text, '-') || ':'
      || coalesce(tie.winner_team_id::text, '-') || ':'
      || coalesce(tie.decided_by, '-'),
      '|' order by tie.bracket_position
    ),
    ''
  )
  into v_ties
  from public.league_cup_ties tie
  where tie.round_id = v_final_round.id;

  select coalesce(
    string_agg(
      entry.seed::text || ':'
      || entry.fantasy_team_id::text || ':'
      || coalesce(entry.eliminated_round::text, '-') || ':'
      || coalesce(entry.final_position::text, '-'),
      '|' order by entry.seed
    ),
    ''
  )
  into v_entries
  from public.league_cup_entries entry
  where entry.cup_id = v_cup.id;

  v_payload :=
    v_cup.id::text || '#'
    || v_cup.league_id::text || '#'
    || v_cup.status || '#'
    || v_cup.team_count::text || '#'
    || v_cup.bracket_size::text || '#'
    || v_cup.round_count::text || '#'
    || v_cup.current_round::text || '#'
    || v_cup.champion_team_id::text || '#'
    || v_cup.runner_up_team_id::text || '#'
    || coalesce(v_cup.completed_at::text, '-') || '#'
    || v_final_round.id::text || '#'
    || v_final_round.round_number::text || '#'
    || coalesce(v_final_round.finalized_at::text, '-') || '#'
    || v_run.id::text || '#'
    || v_run.result_hash || '#'
    || v_ties || '#'
    || v_entries;

  return public.leghevo_sha256_hex_v1(v_payload);
end;
$$;

revoke all on function public.compute_league_cup_completion_fingerprint_v1(uuid)
from public, anon, authenticated;

create or replace function public.certify_league_cup_completion_internal_v1(
  p_cup_id uuid,
  p_finalization_run_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cup public.league_cups%rowtype;
  v_final_round public.league_cup_rounds%rowtype;
  v_run public.league_cup_round_finalization_runs%rowtype;
  v_certificate public.league_cup_completion_certificates%rowtype;
  v_current_result_hash text;
  v_fingerprint text;
begin
  select cup.*
  into v_cup
  from public.league_cups cup
  where cup.id = p_cup_id;

  if not found or v_cup.status <> 'completed' then
    raise exception 'La Coppa non è conclusa: certificazione non disponibile.';
  end if;

  if v_cup.champion_team_id is null or v_cup.runner_up_team_id is null then
    raise exception 'Podio finale della Coppa incompleto.';
  end if;

  select cup_round.*
  into v_final_round
  from public.league_cup_rounds cup_round
  where cup_round.cup_id = v_cup.id
    and cup_round.round_number = v_cup.round_count;

  if not found or v_final_round.status <> 'official' then
    raise exception 'Finale della Coppa non ufficiale.';
  end if;

  select run.*
  into v_run
  from public.league_cup_round_finalization_runs run
  where run.id = p_finalization_run_id
    and run.cup_id = v_cup.id
    and run.round_id = v_final_round.id
    and run.cup_completed;

  if not found then
    raise exception 'Ufficializzazione certificata della finale non trovata.';
  end if;

  if v_run.champion_team_id is distinct from v_cup.champion_team_id then
    raise exception 'Il campione non coincide con l''ufficializzazione della finale.';
  end if;

  v_current_result_hash := public.league_cup_round_result_hash_v1(
    v_cup.id,
    v_final_round.round_number
  );

  if v_current_result_hash is null or v_current_result_hash <> v_run.result_hash then
    raise exception 'L''esito della finale non coincide con la revisione certificata.';
  end if;

  v_fingerprint := public.compute_league_cup_completion_fingerprint_v1(v_cup.id);

  if v_fingerprint is null or char_length(v_fingerprint) <> 64 then
    raise exception 'Impossibile calcolare l''impronta conclusiva della Coppa.';
  end if;

  insert into public.league_cup_completion_certificates (
    league_id,
    cup_id,
    final_round_id,
    finalization_run_id,
    champion_team_id,
    runner_up_team_id,
    final_round_number,
    source_result_hash,
    completion_fingerprint,
    snapshot,
    certified_by,
    certified_at
  ) values (
    v_cup.league_id,
    v_cup.id,
    v_final_round.id,
    v_run.id,
    v_cup.champion_team_id,
    v_cup.runner_up_team_id,
    v_final_round.round_number,
    v_run.result_hash,
    v_fingerprint,
    jsonb_build_object(
      'policy', 'certified_v1',
      'leagueId', v_cup.league_id,
      'cupId', v_cup.id,
      'finalRoundId', v_final_round.id,
      'finalRoundNumber', v_final_round.round_number,
      'finalizationRunId', v_run.id,
      'championTeamId', v_cup.champion_team_id,
      'runnerUpTeamId', v_cup.runner_up_team_id,
      'sourceResultHash', v_run.result_hash,
      'completionFingerprint', v_fingerprint
    ),
    v_run.requested_by,
    coalesce(v_run.finalized_at, v_cup.completed_at, now())
  )
  on conflict (cup_id) do nothing;

  select certificate.*
  into v_certificate
  from public.league_cup_completion_certificates certificate
  where certificate.cup_id = v_cup.id;

  if not found then
    raise exception 'Certificato conclusivo della Coppa non creato.';
  end if;

  if v_certificate.finalization_run_id <> v_run.id
    or v_certificate.completion_fingerprint <> v_fingerprint
    or v_certificate.source_result_hash <> v_run.result_hash then
    raise exception 'Esiste un certificato conclusivo incompatibile.';
  end if;

  return v_certificate.id;
end;
$$;

revoke all on function public.certify_league_cup_completion_internal_v1(uuid, bigint)
from public, anon, authenticated;

