create or replace function public.get_league_cup_completion_integrity_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_completed_count integer := 0;
  v_certificate_count integer := 0;
  v_missing_count integer := 0;
  v_fingerprint_drift_count integer := 0;
  v_source_drift_count integer := 0;
  v_podium_issue_count integer := 0;
  v_link_issue_count integer := 0;
  v_healthy boolean := false;
begin
  if auth.uid() is null
    or (not public.is_league_member(p_league_id)
      and not public.is_league_admin(p_league_id)) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  select count(*)::integer
  into v_completed_count
  from public.league_cups cup
  where cup.league_id = p_league_id
    and cup.status = 'completed';

  select count(*)::integer
  into v_certificate_count
  from public.league_cup_completion_certificates certificate
  where certificate.league_id = p_league_id;

  select count(*)::integer
  into v_missing_count
  from public.league_cups cup
  left join public.league_cup_completion_certificates certificate
    on certificate.cup_id = cup.id
  where cup.league_id = p_league_id
    and cup.status = 'completed'
    and certificate.id is null;

  select count(*)::integer
  into v_fingerprint_drift_count
  from public.league_cup_completion_certificates certificate
  where certificate.league_id = p_league_id
    and certificate.completion_fingerprint is distinct from
      public.compute_league_cup_completion_fingerprint_v1(certificate.cup_id);

  select count(*)::integer
  into v_source_drift_count
  from public.league_cup_completion_certificates certificate
  join public.league_cup_round_finalization_runs run
    on run.id = certificate.finalization_run_id
  where certificate.league_id = p_league_id
    and certificate.source_result_hash is distinct from run.result_hash;

  select count(*)::integer
  into v_podium_issue_count
  from public.league_cup_completion_certificates certificate
  join public.league_cups cup on cup.id = certificate.cup_id
  where certificate.league_id = p_league_id
    and (
      certificate.champion_team_id is distinct from cup.champion_team_id
      or certificate.runner_up_team_id is distinct from cup.runner_up_team_id
      or certificate.champion_team_id = certificate.runner_up_team_id
    );

  select count(*)::integer
  into v_link_issue_count
  from public.league_cup_completion_certificates certificate
  join public.league_cup_rounds cup_round
    on cup_round.id = certificate.final_round_id
  join public.league_cup_round_finalization_runs run
    on run.id = certificate.finalization_run_id
  where certificate.league_id = p_league_id
    and (
      cup_round.cup_id <> certificate.cup_id
      or cup_round.round_number <> certificate.final_round_number
      or cup_round.status <> 'official'
      or run.cup_id <> certificate.cup_id
      or run.round_id <> certificate.final_round_id
      or not run.cup_completed
    );

  v_healthy :=
    v_missing_count = 0
    and v_fingerprint_drift_count = 0
    and v_source_drift_count = 0
    and v_podium_issue_count = 0
    and v_link_issue_count = 0;

  return jsonb_build_object(
    'policy', 'certified_v1',
    'healthy', v_healthy,
    'completedCupCount', v_completed_count,
    'certificateCount', v_certificate_count,
    'missingCertificateCount', v_missing_count,
    'fingerprintDriftCount', v_fingerprint_drift_count,
    'sourceDriftCount', v_source_drift_count,
    'podiumIssueCount', v_podium_issue_count,
    'linkIssueCount', v_link_issue_count
  );
end;
$$;

