create trigger league_cup_completion_after_finalization
after insert on public.league_cup_round_finalization_runs
for each row
when (new.cup_completed)
execute function public.certify_league_cup_completion_on_finalization_v1();

-- Certifica in modo non distruttivo le Coppe già concluse e validate dalla v0.60.2.
do $block$
declare
  v_item record;
begin
  for v_item in
    select cup.id as cup_id, run.id as run_id
    from public.league_cups cup
    join public.league_cup_rounds cup_round
      on cup_round.cup_id = cup.id
      and cup_round.round_number = cup.round_count
      and cup_round.status = 'official'
    join lateral (
      select finalization.id
      from public.league_cup_round_finalization_runs finalization
      where finalization.cup_id = cup.id
        and finalization.round_id = cup_round.id
        and finalization.cup_completed
      order by finalization.id desc
      limit 1
    ) run on true
    where cup.status = 'completed'
      and cup.champion_team_id is not null
      and cup.runner_up_team_id is not null
      and not exists (
        select 1
        from public.league_cup_completion_certificates certificate
        where certificate.cup_id = cup.id
      )
  loop
    perform public.certify_league_cup_completion_internal_v1(
      v_item.cup_id,
      v_item.run_id
    );
  end loop;
end;
$block$;

