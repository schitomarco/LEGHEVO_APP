create table if not exists public.league_season_rollover_certificates (
  id bigint generated by default as identity primary key,
  source_league_id uuid not null unique
    references public.leagues(id) on delete restrict,
  renewed_league_id uuid not null unique
    references public.leagues(id) on delete restrict,
  request_id uuid not null unique,
  source_snapshot_id bigint not null
    references public.league_season_official_snapshots(id) on delete restrict,
  source_snapshot_hash text not null,
  source_season text not null,
  renewed_season text not null,
  copied_member_count integer not null,
  copied_team_count integer not null,
  source_member_fingerprint text not null,
  renewed_member_fingerprint text not null,
  source_team_fingerprint text not null,
  renewed_team_fingerprint text not null,
  certification_status text not null,
  certification_reason text not null,
  lineage_hash text not null,
  certified_by uuid references public.profiles(id) on delete set null,
  certified_at timestamptz not null default now(),
  result_payload jsonb not null default '{}'::jsonb,
  constraint league_season_rollover_certificate_distinct_check
    check (source_league_id<>renewed_league_id),
  constraint league_season_rollover_certificate_seasons_check
    check (
      source_season~'^[0-9]{4}$'
      and renewed_season~'^[0-9]{4}$'
      and renewed_season::integer>source_season::integer
    ),
  constraint league_season_rollover_certificate_counts_check
    check (copied_member_count>0 and copied_team_count>0),
  constraint league_season_rollover_certificate_snapshot_hash_check
    check (length(source_snapshot_hash)=32),
  constraint league_season_rollover_certificate_member_hashes_check
    check (
      length(source_member_fingerprint)=32
      and length(renewed_member_fingerprint)=32
    ),
  constraint league_season_rollover_certificate_team_hashes_check
    check (
      length(source_team_fingerprint)=32
      and length(renewed_team_fingerprint)=32
    ),
  constraint league_season_rollover_certificate_status_check
    check (certification_status in ('certified','affected')),
  constraint league_season_rollover_certificate_reason_check
    check (char_length(trim(certification_reason)) between 3 and 180),
  constraint league_season_rollover_certificate_lineage_hash_check
    check (length(lineage_hash)=32),
  constraint league_season_rollover_certificate_payload_check
    check (jsonb_typeof(result_payload)='object')
);

