create or replace function public.renew_league_season_guarded_v2(
  p_league_id uuid,
  p_next_season text,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_league public.leagues%rowtype;
  v_existing public.league_season_rollovers%rowtype;
  v_existing_certificate public.league_season_rollover_certificates%rowtype;
  v_snapshot public.league_season_official_snapshots%rowtype;
  v_snapshot_head public.league_season_official_snapshot_heads%rowtype;
  v_new_league_id uuid;
  v_invite_code text;
  v_next_season text:=trim(coalesce(p_next_season,''));
  v_member_count integer;
  v_team_count integer;
  v_new_member_count integer;
  v_new_team_count integer;
  v_source_member_fingerprint text;
  v_new_member_fingerprint text;
  v_source_team_fingerprint text;
  v_new_team_fingerprint text;
  v_member_user_id uuid;
  v_result jsonb;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;
  if p_request_id is null then
    raise exception 'Request ID del rinnovo non valido.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'provider-season-completion-chain:'||p_league_id::text,0
    )
  );
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'league-season-official-snapshot:'||p_league_id::text,0
    )
  );
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'league-season-rollover-lineage:'||p_league_id::text,0
    )
  );

  select league.* into v_league
  from public.leagues league
  where league.id=p_league_id
  for update;
  if not found then
    raise exception 'Lega non trovata.';
  end if;
  if v_league.owner_id<>auth.uid() then
    raise exception 'Solo il Presidente può preparare la nuova stagione.';
  end if;

  select certificate.* into v_existing_certificate
  from public.league_season_rollover_certificates certificate
  where certificate.request_id=p_request_id;
  if found then
    if v_existing_certificate.source_league_id<>p_league_id
      or v_existing_certificate.renewed_season<>v_next_season then
      raise exception
        'Request ID già utilizzato per un rinnovo differente.';
    end if;
    return v_existing_certificate.result_payload
      ||public.reconcile_league_season_rollover_v1(p_league_id,false);
  end if;

  select rollover.* into v_existing
  from public.league_season_rollovers rollover
  where rollover.source_league_id=p_league_id;
  if found then
    if v_existing.renewed_season<>v_next_season then
      raise exception
        'La nuova stagione è già stata preparata per il %.',
        v_existing.renewed_season;
    end if;

    select certificate.* into v_existing_certificate
    from public.league_season_rollover_certificates certificate
    where certificate.source_league_id=p_league_id;

    if not found then
      return public.certify_league_season_rollover_v1(
        p_league_id,p_request_id,true
      );
    end if;

    return v_existing_certificate.result_payload
      ||public.reconcile_league_season_rollover_v1(p_league_id,false);
  end if;

  if v_league.status<>'completed'
    or v_league.competition_completed_at is null then
    raise exception
      'Prima devi chiudere e ufficializzare la stagione corrente.';
  end if;

  perform public.reconcile_league_season_official_snapshot_v1(
    p_league_id,true
  );

  select snapshot_row.* into v_snapshot
  from public.league_season_official_snapshots snapshot_row
  where snapshot_row.league_id=p_league_id
  for share;
  select snapshot_head.* into v_snapshot_head
  from public.league_season_official_snapshot_heads snapshot_head
  where snapshot_head.league_id=p_league_id
  for update;

  if v_snapshot.id is null or v_snapshot_head.snapshot_id is null then
    raise exception
      'Rinnovo bloccato: snapshot ufficiale della stagione assente.';
  end if;
  if v_snapshot_head.snapshot_status<>'official' then
    raise exception
      'Rinnovo bloccato [season_rollover.source_snapshot_affected]: %',
      v_snapshot_head.reason_code;
  end if;
  if not coalesce(
    public.is_league_season_official_snapshot_row_valid_v1(v_snapshot.id),
    false
  ) then
    raise exception
      'Rinnovo bloccato: integrità dello snapshot ufficiale non valida.';
  end if;

  if v_next_season!~'^[0-9]{4}$'
    or v_next_season::integer<2000
    or v_next_season::integer>2100 then
    raise exception
      'La nuova stagione deve avere quattro cifre tra 2000 e 2100.';
  end if;
  if v_snapshot.season!~'^[0-9]{4}$'
    or v_next_season::integer<>v_snapshot.season::integer+1 then
    raise exception
      'La nuova stagione deve essere esattamente successiva al %.',
      v_snapshot.season;
  end if;

  select count(*)::integer into v_member_count
  from public.league_members member
  where member.league_id=p_league_id;
  select count(*)::integer into v_team_count
  from public.fantasy_teams team
  where team.league_id=p_league_id;

  if v_member_count=0 or v_team_count<>v_member_count then
    raise exception
      'Partecipanti e squadre della stagione conclusa non sono allineati.';
  end if;

  v_source_member_fingerprint :=
    public.compute_league_member_identity_fingerprint_v1(p_league_id);
  v_source_team_fingerprint :=
    public.compute_league_team_identity_fingerprint_v1(p_league_id);

  loop
    v_invite_code:=upper(substr(
      replace(gen_random_uuid()::text,'-',''),1,10
    ));
    exit when not exists (
      select 1 from public.leagues league
      where league.invite_code=v_invite_code
    );
  end loop;

  perform set_config('leghevo.season_rollover_writer_context','on',true);

  insert into public.leagues(
    owner_id,name,invite_code,mode,status,team_limit,starting_credits,
    roster_size,scoring_rules,invites_open,calendar_season,
    previous_league_id
  ) values (
    v_league.owner_id,v_league.name,v_invite_code,v_league.mode,'draft',
    v_league.team_limit,v_league.starting_credits,v_league.roster_size,
    (coalesce(v_league.scoring_rules,'{}'::jsonb)-'market_open')
      ||jsonb_build_object('market_open',false),
    false,v_next_season,p_league_id
  ) returning id into v_new_league_id;

  insert into public.league_members(league_id,user_id,role,joined_at)
  select v_new_league_id,member.user_id,member.role,now()
  from public.league_members member
  where member.league_id=p_league_id;

  insert into public.fantasy_teams(
    league_id,manager_id,name,crest_url,credits_remaining
  )
  select v_new_league_id,team.manager_id,team.name,team.crest_url,
    v_league.starting_credits
  from public.fantasy_teams team
  where team.league_id=p_league_id;

  select count(*)::integer into v_new_member_count
  from public.league_members member
  where member.league_id=v_new_league_id;
  select count(*)::integer into v_new_team_count
  from public.fantasy_teams team
  where team.league_id=v_new_league_id;

  v_new_member_fingerprint :=
    public.compute_league_member_identity_fingerprint_v1(v_new_league_id);
  v_new_team_fingerprint :=
    public.compute_league_team_identity_fingerprint_v1(v_new_league_id);

  if v_new_member_count<>v_member_count
    or v_new_team_count<>v_team_count
    or v_new_member_fingerprint<>v_source_member_fingerprint
    or v_new_team_fingerprint<>v_source_team_fingerprint then
    raise exception
      'Rinnovo annullato: copia atomica di partecipanti e squadre non coerente.';
  end if;

  insert into public.league_season_rollovers(
    source_league_id,renewed_league_id,source_season,renewed_season,
    copied_member_count,copied_team_count,renewed_at,renewed_by
  ) values (
    p_league_id,v_new_league_id,v_snapshot.season,v_next_season,
    v_member_count,v_team_count,now(),auth.uid()
  );

  perform set_config('leghevo.season_rollover_writer_context','',true);

  v_result := public.certify_league_season_rollover_v1(
    p_league_id,p_request_id,false
  );

  update public.leagues
  set status='archived',updated_at=now()
  where id=p_league_id;

  for v_member_user_id in
    select member.user_id
    from public.league_members member
    where member.league_id=v_new_league_id
  loop
    perform public.create_user_notification(
      v_member_user_id,v_new_league_id,'league',
      'Nuova stagione certificata',
      v_league.name||' riparte nel '||v_next_season
        ||'. La continuità con lo snapshot ufficiale è certificata.',
      'league',
      jsonb_build_object(
        'event','season_renewed_certified',
        'source_league_id',p_league_id,
        'renewed_league_id',v_new_league_id,
        'source_season',v_snapshot.season,
        'renewed_season',v_next_season,
        'lineage_hash',v_result->>'lineageHash'
      ),
      'season:renewed-certified:'||p_league_id::text||':'
        ||v_member_user_id::text
    );
  end loop;

  return v_result;
end;
$function$;

