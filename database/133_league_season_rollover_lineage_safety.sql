create or replace function public.certify_league_season_rollover_v1(
  p_source_league_id uuid,
  p_request_id uuid,
  p_allow_affected_adoption boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_rollover public.league_season_rollovers%rowtype;
  v_snapshot public.league_season_official_snapshots%rowtype;
  v_snapshot_head public.league_season_official_snapshot_heads%rowtype;
  v_certificate public.league_season_rollover_certificates%rowtype;
  v_head public.league_season_rollover_heads%rowtype;
  v_renewed public.leagues%rowtype;
  v_source_member_count integer;
  v_renewed_member_count integer;
  v_source_team_count integer;
  v_renewed_team_count integer;
  v_source_member_fingerprint text;
  v_renewed_member_fingerprint text;
  v_source_team_fingerprint text;
  v_renewed_team_fingerprint text;
  v_status text;
  v_reason text;
  v_lineage_hash text;
  v_certificate_id bigint;
  v_payload jsonb;
  v_adoption_issue text;
begin
  if p_request_id is null then
    raise exception 'Request ID del rinnovo non valido.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'provider-season-completion-chain:'||p_source_league_id::text,0
    )
  );
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'league-season-official-snapshot:'||p_source_league_id::text,0
    )
  );
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'league-season-rollover-lineage:'||p_source_league_id::text,0
    )
  );

  select certificate.* into v_certificate
  from public.league_season_rollover_certificates certificate
  where certificate.source_league_id=p_source_league_id;

  if found then
    select head.* into v_head
    from public.league_season_rollover_heads head
    where head.certificate_id=v_certificate.id;

    return v_certificate.result_payload || jsonb_build_object(
      'certificateId',v_certificate.id,
      'rolloverStatus',coalesce(v_head.rollover_status,
        v_certificate.certification_status),
      'rolloverReason',coalesce(v_head.reason_code,
        v_certificate.certification_reason),
      'rolloverAffected',coalesce(v_head.rollover_status='affected',
        v_certificate.certification_status='affected')
    );
  end if;

  select rollover.* into v_rollover
  from public.league_season_rollovers rollover
  where rollover.source_league_id=p_source_league_id
  for update;
  if not found then
    raise exception 'Rinnovo stagione da certificare non trovato.';
  end if;

  select snapshot_row.* into v_snapshot
  from public.league_season_official_snapshots snapshot_row
  where snapshot_row.league_id=p_source_league_id
  for share;
  if not found then
    raise exception
      'Rinnovo rifiutato: snapshot ufficiale della stagione assente.';
  end if;

  select snapshot_head.* into v_snapshot_head
  from public.league_season_official_snapshot_heads snapshot_head
  where snapshot_head.snapshot_id=v_snapshot.id
  for share;
  if not found then
    raise exception
      'Rinnovo rifiutato: testa dello snapshot ufficiale assente.';
  end if;

  if not coalesce(
    public.is_league_season_official_snapshot_row_valid_v1(v_snapshot.id),
    false
  ) then
    raise exception
      'Rinnovo rifiutato: hash dello snapshot ufficiale non valido.';
  end if;

  select league.* into v_renewed
  from public.leagues league
  where league.id=v_rollover.renewed_league_id
  for share;
  if not found then
    raise exception
      'Rinnovo rifiutato: stagione rinnovata non trovata.';
  end if;

  if v_renewed.previous_league_id is distinct from p_source_league_id then
    if not p_allow_affected_adoption then
      raise exception
        'Rinnovo rifiutato: collegamento tra le stagioni non coerente.';
    end if;
    v_adoption_issue:='season_rollover.renewed_lineage_mismatch';
  end if;

  if v_rollover.source_season<>v_snapshot.season
    or v_rollover.renewed_season::integer
      <=v_rollover.source_season::integer
    or v_renewed.calendar_season<>v_rollover.renewed_season then
    if not p_allow_affected_adoption then
      raise exception
        'Rinnovo rifiutato: continuità delle stagioni non coerente.';
    end if;
    v_adoption_issue:=coalesce(
      v_adoption_issue,'season_rollover.legacy_season_linkage_mismatch'
    );
  end if;

  select count(*)::integer into v_source_member_count
  from public.league_members member
  where member.league_id=p_source_league_id;
  select count(*)::integer into v_renewed_member_count
  from public.league_members member
  where member.league_id=v_rollover.renewed_league_id;
  select count(*)::integer into v_source_team_count
  from public.fantasy_teams team
  where team.league_id=p_source_league_id;
  select count(*)::integer into v_renewed_team_count
  from public.fantasy_teams team
  where team.league_id=v_rollover.renewed_league_id;

  v_source_member_fingerprint :=
    public.compute_league_member_identity_fingerprint_v1(p_source_league_id);
  v_renewed_member_fingerprint :=
    public.compute_league_member_identity_fingerprint_v1(
      v_rollover.renewed_league_id
    );
  v_source_team_fingerprint :=
    public.compute_league_team_identity_fingerprint_v1(p_source_league_id);
  v_renewed_team_fingerprint :=
    public.compute_league_team_identity_fingerprint_v1(
      v_rollover.renewed_league_id
    );

  v_status := 'certified';
  v_reason := 'season_rollover.lineage_certified';

  if v_adoption_issue is not null then
    v_status := 'affected';
    v_reason := v_adoption_issue;
  elsif v_rollover.renewed_season::integer
      <>v_rollover.source_season::integer+1 then
    v_status := 'affected';
    v_reason := 'season_rollover.legacy_season_gap';
  elsif v_snapshot_head.snapshot_id is null
    or v_snapshot_head.snapshot_status<>'official' then
    v_status := 'affected';
    v_reason := 'season_rollover.source_snapshot_affected';
  elsif v_source_member_count<>v_rollover.copied_member_count
    or v_renewed_member_count<>v_rollover.copied_member_count then
    v_status := 'affected';
    v_reason := 'season_rollover.member_count_drift';
  elsif v_source_team_count<>v_rollover.copied_team_count
    or v_renewed_team_count<>v_rollover.copied_team_count then
    v_status := 'affected';
    v_reason := 'season_rollover.team_count_drift';
  elsif v_source_member_fingerprint<>v_renewed_member_fingerprint then
    v_status := 'affected';
    v_reason := 'season_rollover.member_identity_drift';
  elsif v_source_team_fingerprint<>v_renewed_team_fingerprint then
    v_status := 'affected';
    v_reason := 'season_rollover.team_identity_drift';
  end if;

  if v_status<>'certified' and not p_allow_affected_adoption then
    raise exception 'Rinnovo rifiutato [%]: %',v_reason,v_status;
  end if;

  v_lineage_hash :=
    public.compute_league_season_rollover_lineage_hash_v1(
      p_source_league_id,v_rollover.renewed_league_id,v_snapshot.id,
      v_snapshot.snapshot_hash,v_rollover.source_season,
      v_rollover.renewed_season,v_rollover.copied_member_count,
      v_rollover.copied_team_count,v_source_member_fingerprint,
      v_renewed_member_fingerprint,v_source_team_fingerprint,
      v_renewed_team_fingerprint
    );

  v_certificate_id := pg_catalog.nextval(
    pg_catalog.pg_get_serial_sequence(
      'public.league_season_rollover_certificates','id'
    )::regclass
  );

  v_payload := jsonb_build_object(
    'sourceLeagueId',p_source_league_id,
    'renewedLeagueId',v_rollover.renewed_league_id,
    'sourceSeason',v_rollover.source_season,
    'renewedSeason',v_rollover.renewed_season,
    'certificateId',v_certificate_id,
    'sourceSnapshotId',v_snapshot.id,
    'sourceSnapshotHash',v_snapshot.snapshot_hash,
    'lineageHash',v_lineage_hash,
    'rolloverStatus',v_status,
    'rolloverReason',v_reason,
    'rolloverAffected',v_status='affected',
    'copiedMemberCount',v_rollover.copied_member_count,
    'copiedTeamCount',v_rollover.copied_team_count,
    'certifiedAt',v_rollover.renewed_at
  );

  perform set_config(
    'leghevo.season_rollover_certificate_context','on',true
  );

  insert into public.league_season_rollover_certificates(
    id,source_league_id,renewed_league_id,request_id,
    source_snapshot_id,source_snapshot_hash,source_season,renewed_season,
    copied_member_count,copied_team_count,source_member_fingerprint,
    renewed_member_fingerprint,source_team_fingerprint,
    renewed_team_fingerprint,certification_status,certification_reason,
    lineage_hash,certified_by,certified_at,result_payload
  ) values (
    v_certificate_id,p_source_league_id,v_rollover.renewed_league_id,
    p_request_id,v_snapshot.id,v_snapshot.snapshot_hash,
    v_rollover.source_season,v_rollover.renewed_season,
    v_rollover.copied_member_count,v_rollover.copied_team_count,
    v_source_member_fingerprint,v_renewed_member_fingerprint,
    v_source_team_fingerprint,v_renewed_team_fingerprint,
    v_status,v_reason,v_lineage_hash,v_rollover.renewed_by,
    v_rollover.renewed_at,v_payload
  ) returning * into v_certificate;

  insert into public.league_season_rollover_heads(
    source_league_id,certificate_id,renewed_league_id,rollover_status,
    reason_code,observed_snapshot_status,observed_snapshot_hash,
    affected_at,last_assessed_at,updated_at
  ) values (
    p_source_league_id,v_certificate.id,v_rollover.renewed_league_id,
    v_status,v_reason,v_snapshot_head.snapshot_status,
    v_snapshot.snapshot_hash,
    case when v_status='affected' then now() else null end,
    now(),now()
  );

  insert into public.league_season_rollover_events(
    source_league_id,renewed_league_id,certificate_id,event_type,
    rollover_status,reason_code,source_snapshot_hash,lineage_hash,
    event_payload
  ) values (
    p_source_league_id,v_rollover.renewed_league_id,v_certificate.id,
    case when v_status='certified' then 'certified' else 'affected' end,
    v_status,v_reason,v_snapshot.snapshot_hash,v_lineage_hash,
    jsonb_build_object(
      'adoptedExisting',p_allow_affected_adoption,
      'sourceSnapshotStatus',v_snapshot_head.snapshot_status,
      'requestId',p_request_id
    )
  );

  perform set_config(
    'leghevo.season_rollover_certificate_context','',true
  );

  return v_payload;
end;
$function$;

