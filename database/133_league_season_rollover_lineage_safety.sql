create or replace function public.compute_league_member_identity_fingerprint_v1(
  p_league_id uuid
)
returns text
language sql
stable
security definer
set search_path=''
as $function$
  select pg_catalog.md5(
    coalesce(
      jsonb_agg(
        jsonb_build_object(
          'userId',member.user_id,
          'role',member.role
        ) order by member.user_id,member.role
      ),
      '[]'::jsonb
    )::text
  )
  from public.league_members member
  where member.league_id=p_league_id
$function$;

