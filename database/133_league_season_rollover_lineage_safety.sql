create or replace function public.reconcile_league_season_rollover_v1(
  p_source_league_id uuid,
  p_emit_event boolean default true
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_certificate public.league_season_rollover_certificates%rowtype;
  v_head public.league_season_rollover_heads%rowtype;
  v_rollover public.league_season_rollovers%rowtype;
  v_snapshot public.league_season_official_snapshots%rowtype;
  v_snapshot_head public.league_season_official_snapshot_heads%rowtype;
  v_renewed public.leagues%rowtype;
  v_expected_hash text;
  v_status text;
  v_reason text;
  v_changed boolean;
  v_previous_status text;
  v_previous_reason text;
begin
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'provider-season-completion-chain:'||p_source_league_id::text,0
    )
  );
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'league-season-official-snapshot:'||p_source_league_id::text,0
    )
  );
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'league-season-rollover-lineage:'||p_source_league_id::text,0
    )
  );

  select certificate.* into v_certificate
  from public.league_season_rollover_certificates certificate
  where certificate.source_league_id=p_source_league_id;
  if not found then
    return jsonb_build_object(
      'protected',true,'certified',false,'healthy',true,
      'status','pending','reasonCode','season_rollover.not_created'
    );
  end if;

  select head.* into v_head
  from public.league_season_rollover_heads head
  where head.certificate_id=v_certificate.id
  for update;
  if not found then
    raise exception 'Testa del rinnovo stagione non trovata.';
  end if;

  select rollover.* into v_rollover
  from public.league_season_rollovers rollover
  where rollover.source_league_id=p_source_league_id;
  select snapshot_row.* into v_snapshot
  from public.league_season_official_snapshots snapshot_row
  where snapshot_row.id=v_certificate.source_snapshot_id;
  select snapshot_head.* into v_snapshot_head
  from public.league_season_official_snapshot_heads snapshot_head
  where snapshot_head.snapshot_id=v_certificate.source_snapshot_id;
  select league.* into v_renewed
  from public.leagues league
  where league.id=v_certificate.renewed_league_id;

  v_expected_hash :=
    public.compute_league_season_rollover_lineage_hash_v1(
      v_certificate.source_league_id,v_certificate.renewed_league_id,
      v_certificate.source_snapshot_id,v_certificate.source_snapshot_hash,
      v_certificate.source_season,v_certificate.renewed_season,
      v_certificate.copied_member_count,v_certificate.copied_team_count,
      v_certificate.source_member_fingerprint,
      v_certificate.renewed_member_fingerprint,
      v_certificate.source_team_fingerprint,
      v_certificate.renewed_team_fingerprint
    );

  v_status := 'certified';
  v_reason := 'season_rollover.lineage_certified';

  if v_certificate.lineage_hash<>v_expected_hash then
    v_status := 'affected';
    v_reason := 'season_rollover.certificate_hash_mismatch';
  elsif v_rollover.source_league_id is null
    or v_rollover.renewed_league_id<>v_certificate.renewed_league_id
    or v_rollover.source_season<>v_certificate.source_season
    or v_rollover.renewed_season<>v_certificate.renewed_season then
    v_status := 'affected';
    v_reason := 'season_rollover.linkage_mismatch';
  elsif v_renewed.id is null
    or v_renewed.previous_league_id is distinct from p_source_league_id then
    v_status := 'affected';
    v_reason := 'season_rollover.renewed_lineage_mismatch';
  elsif v_snapshot.id is null
    or v_snapshot.snapshot_hash<>v_certificate.source_snapshot_hash
    or not coalesce(
      public.is_league_season_official_snapshot_row_valid_v1(v_snapshot.id),
      false
    ) then
    v_status := 'affected';
    v_reason := 'season_rollover.source_snapshot_integrity_failed';
  elsif v_snapshot_head.snapshot_id is null
    or v_snapshot_head.snapshot_status<>'official' then
    v_status := 'affected';
    v_reason := 'season_rollover.source_snapshot_affected';
  elsif v_certificate.certification_status='affected' then
    v_status := 'affected';
    v_reason := v_certificate.certification_reason;
  end if;

  v_previous_status:=v_head.rollover_status;
  v_previous_reason:=v_head.reason_code;
  v_changed := v_previous_status is distinct from v_status
    or v_previous_reason is distinct from v_reason
    or v_head.observed_snapshot_status
      is distinct from coalesce(v_snapshot_head.snapshot_status,'affected')
    or v_head.observed_snapshot_hash
      is distinct from v_certificate.source_snapshot_hash;

  perform set_config(
    'leghevo.season_rollover_certificate_context','on',true
  );

  update public.league_season_rollover_heads
  set rollover_status=v_status,
      reason_code=v_reason,
      observed_snapshot_status=coalesce(
        v_snapshot_head.snapshot_status,'affected'
      ),
      observed_snapshot_hash=v_certificate.source_snapshot_hash,
      affected_at=case
        when v_status='affected' then coalesce(affected_at,now())
        else null
      end,
      last_assessed_at=now(),updated_at=now()
  where source_league_id=p_source_league_id
  returning * into v_head;

  if p_emit_event and v_changed then
    insert into public.league_season_rollover_events(
      source_league_id,renewed_league_id,certificate_id,event_type,
      rollover_status,reason_code,source_snapshot_hash,lineage_hash,
      event_payload
    ) values (
      p_source_league_id,v_certificate.renewed_league_id,v_certificate.id,
      case
        when v_status='affected' then 'affected'
        else 'revalidated'
      end,
      v_status,v_reason,v_certificate.source_snapshot_hash,
      v_certificate.lineage_hash,
      jsonb_build_object(
        'previousStatus',v_previous_status,
        'previousReason',v_previous_reason,
        'sourceSnapshotStatus',coalesce(
          v_snapshot_head.snapshot_status,'affected'
        )
      )
    );
  end if;

  perform set_config(
    'leghevo.season_rollover_certificate_context','',true
  );

  return jsonb_build_object(
    'protected',true,
    'certified',true,
    'healthy',v_status='certified',
    'status',v_status,
    'reasonCode',v_reason,
    'affected',v_status='affected',
    'certificateId',v_certificate.id,
    'sourceLeagueId',v_certificate.source_league_id,
    'renewedLeagueId',v_certificate.renewed_league_id,
    'sourceSeason',v_certificate.source_season,
    'renewedSeason',v_certificate.renewed_season,
    'sourceSnapshotId',v_certificate.source_snapshot_id,
    'sourceSnapshotHash',v_certificate.source_snapshot_hash,
    'lineageHash',v_certificate.lineage_hash,
    'certifiedAt',v_certificate.certified_at,
    'affectedAt',v_head.affected_at
  );
end;
$function$;

