create or replace function public.get_league_season_rollover_gate_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $function$
declare
  v_out_certificate public.league_season_rollover_certificates%rowtype;
  v_in_certificate public.league_season_rollover_certificates%rowtype;
  v_out_head public.league_season_rollover_heads%rowtype;
  v_in_head public.league_season_rollover_heads%rowtype;
  v_out_latest jsonb;
  v_in_latest jsonb;
  v_outgoing jsonb;
  v_incoming jsonb;
  v_primary jsonb;
  v_has_outgoing boolean:=false;
  v_has_incoming boolean:=false;
  v_healthy boolean:=true;
  v_status text:='pending';
  v_reason text:='season_rollover.not_created';
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;
  if not public.is_league_member(p_league_id)
    and not public.is_league_admin(p_league_id) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  select certificate.* into v_out_certificate
  from public.league_season_rollover_certificates certificate
  where certificate.source_league_id=p_league_id;
  v_has_outgoing:=found;

  if v_has_outgoing then
    select head.* into v_out_head
    from public.league_season_rollover_heads head
    where head.certificate_id=v_out_certificate.id;
    if not found then
      raise exception 'Testa del rinnovo uscente certificato non trovata.';
    end if;

    select jsonb_build_object(
      'id',event_row.id,
      'eventType',event_row.event_type,
      'status',event_row.rollover_status,
      'reasonCode',event_row.reason_code,
      'createdAt',event_row.created_at
    ) into v_out_latest
    from public.league_season_rollover_events event_row
    where event_row.certificate_id=v_out_certificate.id
    order by event_row.created_at desc,event_row.id desc
    limit 1;

    v_outgoing:=jsonb_build_object(
      'relation','outgoing',
      'healthy',v_out_head.rollover_status='certified',
      'status',v_out_head.rollover_status,
      'reasonCode',v_out_head.reason_code,
      'affected',v_out_head.rollover_status='affected',
      'certificateId',v_out_certificate.id,
      'sourceLeagueId',v_out_certificate.source_league_id,
      'renewedLeagueId',v_out_certificate.renewed_league_id,
      'sourceSeason',v_out_certificate.source_season,
      'renewedSeason',v_out_certificate.renewed_season,
      'sourceSnapshotId',v_out_certificate.source_snapshot_id,
      'sourceSnapshotHash',v_out_certificate.source_snapshot_hash,
      'lineageHash',v_out_certificate.lineage_hash,
      'copiedMemberCount',v_out_certificate.copied_member_count,
      'copiedTeamCount',v_out_certificate.copied_team_count,
      'certifiedAt',v_out_certificate.certified_at,
      'affectedAt',v_out_head.affected_at,
      'latestEvent',v_out_latest
    );
  end if;

  select certificate.* into v_in_certificate
  from public.league_season_rollover_certificates certificate
  where certificate.renewed_league_id=p_league_id;
  v_has_incoming:=found;

  if v_has_incoming then
    select head.* into v_in_head
    from public.league_season_rollover_heads head
    where head.certificate_id=v_in_certificate.id;
    if not found then
      raise exception 'Testa del rinnovo entrante certificato non trovata.';
    end if;

    select jsonb_build_object(
      'id',event_row.id,
      'eventType',event_row.event_type,
      'status',event_row.rollover_status,
      'reasonCode',event_row.reason_code,
      'createdAt',event_row.created_at
    ) into v_in_latest
    from public.league_season_rollover_events event_row
    where event_row.certificate_id=v_in_certificate.id
    order by event_row.created_at desc,event_row.id desc
    limit 1;

    v_incoming:=jsonb_build_object(
      'relation','incoming',
      'healthy',v_in_head.rollover_status='certified',
      'status',v_in_head.rollover_status,
      'reasonCode',v_in_head.reason_code,
      'affected',v_in_head.rollover_status='affected',
      'certificateId',v_in_certificate.id,
      'sourceLeagueId',v_in_certificate.source_league_id,
      'renewedLeagueId',v_in_certificate.renewed_league_id,
      'sourceSeason',v_in_certificate.source_season,
      'renewedSeason',v_in_certificate.renewed_season,
      'sourceSnapshotId',v_in_certificate.source_snapshot_id,
      'sourceSnapshotHash',v_in_certificate.source_snapshot_hash,
      'lineageHash',v_in_certificate.lineage_hash,
      'copiedMemberCount',v_in_certificate.copied_member_count,
      'copiedTeamCount',v_in_certificate.copied_team_count,
      'certifiedAt',v_in_certificate.certified_at,
      'affectedAt',v_in_head.affected_at,
      'latestEvent',v_in_latest
    );
  end if;

  if not v_has_outgoing and not v_has_incoming then
    return jsonb_build_object(
      'protected',true,'certified',false,'healthy',true,
      'status','pending','reasonCode','season_rollover.not_created',
      'affected',false,'isSource',false,
      'incoming',null,'outgoing',null
    );
  end if;

  v_primary:=coalesce(v_outgoing,v_incoming);
  v_healthy:=(not v_has_outgoing or v_out_head.rollover_status='certified')
    and (not v_has_incoming or v_in_head.rollover_status='certified');
  v_status:=case when v_healthy then 'certified' else 'affected' end;
  v_reason:=case
    when v_has_outgoing and v_out_head.rollover_status='affected'
      then v_out_head.reason_code
    when v_has_incoming and v_in_head.rollover_status='affected'
      then v_in_head.reason_code
    else coalesce(v_primary->>'reasonCode','season_rollover.lineage_certified')
  end;

  return v_primary||jsonb_build_object(
    'protected',true,
    'certified',true,
    'relation',case
      when v_has_outgoing and v_has_incoming then 'bidirectional'
      when v_has_outgoing then 'outgoing'
      else 'incoming'
    end,
    'isSource',v_has_outgoing,
    'healthy',v_healthy,
    'status',v_status,
    'reasonCode',v_reason,
    'affected',not v_healthy,
    'incoming',v_incoming,
    'outgoing',v_outgoing
  );
end;
$function$;
revoke all on function public.get_league_season_rollover_gate_v1(uuid)
from public,anon,service_role;
grant execute on function public.get_league_season_rollover_gate_v1(uuid)
to authenticated;

