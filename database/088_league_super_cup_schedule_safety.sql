create or replace function public.create_league_super_cup_guarded_v1(
  p_league_id uuid,
  p_matchday_number smallint,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_league public.leagues%rowtype;
  v_existing_run public.league_super_cup_schedule_runs%rowtype;
  v_existing_super_cup_id uuid;
  v_qualifiers jsonb;
  v_source_league_id uuid;
  v_source_season text;
  v_source_summary public.league_season_summaries%rowtype;
  v_source_cup public.league_cups%rowtype;
  v_source_certificate public.league_cup_completion_certificates%rowtype;
  v_source_home_manager_id uuid;
  v_source_challenger_team_id uuid;
  v_source_challenger_manager_id uuid;
  v_home_team public.fantasy_teams%rowtype;
  v_away_team public.fantasy_teams%rowtype;
  v_matchday public.matchdays%rowtype;
  v_super_cup_id uuid;
  v_qualifiers_hash text;
  v_schedule_hash text;
  v_result_hash text;
  v_member_user_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if p_request_id is null then
    raise exception 'Identificativo richiesta mancante.';
  end if;

  if p_matchday_number is null or p_matchday_number < 1 then
    raise exception 'Giornata della Supercoppa non valida.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      'leghevo:league-super-cup-schedule:' || p_league_id::text,
      0
    )
  );

  select run.*
  into v_existing_run
  from public.league_super_cup_schedule_runs run
  where run.league_id = p_league_id
    and run.request_id = p_request_id;

  if found then
    return public.get_league_super_cup_state_v2(p_league_id)
      || jsonb_build_object(
        'idempotentReplay', true,
        'scheduleRunId', v_existing_run.id
      );
  end if;

  select league.*
  into v_league
  from public.leagues league
  where league.id = p_league_id
  for update;

  if not found then
    raise exception 'Lega non trovata.';
  end if;

  if v_league.owner_id <> auth.uid() then
    raise exception 'Solo il Presidente può programmare la Supercoppa.';
  end if;

  select super_cup.id
  into v_existing_super_cup_id
  from public.league_super_cups super_cup
  where super_cup.league_id = p_league_id;

  if found then
    return public.get_league_super_cup_state_v2(p_league_id)
      || jsonb_build_object(
        'idempotentReplay', true,
        'alreadyExists', true
      );
  end if;

  if v_league.status <> 'active'
    or v_league.competition_started_at is null then
    raise exception 'La Supercoppa si programma durante una stagione attiva.';
  end if;

  v_qualifiers := public.resolve_league_super_cup_qualifiers(p_league_id);

  if coalesce((v_qualifiers ->> 'eligible')::boolean, false) is false then
    raise exception '%', coalesce(
      v_qualifiers ->> 'reason',
      'La Supercoppa non è disponibile.'
    );
  end if;

  v_source_league_id := nullif(v_qualifiers ->> 'sourceLeagueId', '')::uuid;
  v_source_season := nullif(v_qualifiers ->> 'sourceSeason', '');

  select summary.*
  into v_source_summary
  from public.league_season_summaries summary
  where summary.league_id = v_source_league_id;

  if not found or v_source_summary.champion_team_id is null then
    raise exception 'Campione certificato della stagione precedente non disponibile.';
  end if;

  select cup.*
  into v_source_cup
  from public.league_cups cup
  where cup.league_id = v_source_league_id
    and cup.status = 'completed';

  if not found then
    raise exception 'Coppa precedente conclusa non disponibile.';
  end if;

  select certificate.*
  into v_source_certificate
  from public.league_cup_completion_certificates certificate
  where certificate.cup_id = v_source_cup.id;

  if not found
    or v_source_certificate.champion_team_id is distinct from v_source_cup.champion_team_id
    or v_source_certificate.runner_up_team_id is distinct from v_source_cup.runner_up_team_id then
    raise exception 'La Coppa precedente non possiede una certificazione coerente.';
  end if;

  select team.manager_id
  into v_source_home_manager_id
  from public.fantasy_teams team
  where team.id = v_source_summary.champion_team_id;

  if v_source_home_manager_id is null then
    raise exception 'Manager campione della stagione precedente non identificabile.';
  end if;

  if v_qualifiers ->> 'challengerQualification' = 'cup_runner_up' then
    v_source_challenger_team_id := v_source_cup.runner_up_team_id;
  else
    v_source_challenger_team_id := v_source_cup.champion_team_id;
  end if;

  select team.manager_id
  into v_source_challenger_manager_id
  from public.fantasy_teams team
  where team.id = v_source_challenger_team_id;

  if v_source_challenger_manager_id is null then
    raise exception 'Manager sfidante della stagione precedente non identificabile.';
  end if;

  select team.*
  into v_home_team
  from public.fantasy_teams team
  where team.id = (v_qualifiers -> 'leagueChampion' ->> 'teamId')::uuid
    and team.league_id = p_league_id;

  select team.*
  into v_away_team
  from public.fantasy_teams team
  where team.id = (v_qualifiers -> 'challenger' ->> 'teamId')::uuid
    and team.league_id = p_league_id;

  if v_home_team.id is null or v_away_team.id is null then
    raise exception 'Finalisti della Supercoppa non presenti nella stagione corrente.';
  end if;

  if v_home_team.manager_id is distinct from v_source_home_manager_id
    or v_away_team.manager_id is distinct from v_source_challenger_manager_id then
    raise exception 'Continuità dei manager tra le due stagioni non coerente.';
  end if;

  select matchday.*
  into v_matchday
  from public.matchdays matchday
  where matchday.number = p_matchday_number
    and matchday.locks_at > now()
    and exists (
      select 1
      from public.fantasy_fixtures fixture
      where fixture.league_id = p_league_id
        and fixture.matchday_id = matchday.id
    )
  order by matchday.starts_at
  limit 1;

  if v_matchday.id is null then
    raise exception 'La giornata scelta non è disponibile.';
  end if;

  v_qualifiers_hash := public.leghevo_sha256_hex_v1(
    p_league_id::text || '#'
    || v_source_league_id::text || '#'
    || coalesce(v_source_season, '-') || '#'
    || v_source_summary.champion_team_id::text || '#'
    || v_source_home_manager_id::text || '#'
    || v_source_cup.id::text || '#'
    || v_source_certificate.completion_fingerprint || '#'
    || v_source_challenger_team_id::text || '#'
    || v_source_challenger_manager_id::text || '#'
    || (v_qualifiers ->> 'challengerQualification') || '#'
    || v_home_team.id::text || '#'
    || v_away_team.id::text
  );

  v_schedule_hash := public.leghevo_sha256_hex_v1(
    v_matchday.id::text || '#'
    || v_matchday.number::text || '#'
    || v_matchday.starts_at::text || '#'
    || v_matchday.locks_at::text || '#'
    || coalesce(v_matchday.ends_at::text, '-')
  );

  insert into public.league_super_cups (
    league_id,
    source_league_id,
    matchday_id,
    league_champion_team_id,
    challenger_team_id,
    challenger_qualification,
    created_by
  ) values (
    p_league_id,
    v_source_league_id,
    v_matchday.id,
    v_home_team.id,
    v_away_team.id,
    v_qualifiers ->> 'challengerQualification',
    auth.uid()
  ) returning id into v_super_cup_id;

  v_result_hash := public.compute_league_super_cup_schedule_result_hash_v1(
    v_super_cup_id,
    v_qualifiers_hash,
    v_schedule_hash
  );

  insert into public.league_super_cup_schedule_runs (
    league_id,
    super_cup_id,
    source_league_id,
    request_id,
    requested_by,
    matchday_id,
    matchday_number,
    league_champion_team_id,
    challenger_team_id,
    challenger_qualification,
    qualifiers_hash,
    schedule_hash,
    result_hash
  ) values (
    p_league_id,
    v_super_cup_id,
    v_source_league_id,
    p_request_id,
    auth.uid(),
    v_matchday.id,
    v_matchday.number,
    v_home_team.id,
    v_away_team.id,
    v_qualifiers ->> 'challengerQualification',
    v_qualifiers_hash,
    v_schedule_hash,
    v_result_hash
  );

  if to_regprocedure(
    'public.create_user_notification(uuid,uuid,text,text,text,text,jsonb,text)'
  ) is not null then
    for v_member_user_id in
      select member.user_id
      from public.league_members member
      where member.league_id = p_league_id
    loop
      perform public.create_user_notification(
        v_member_user_id,
        p_league_id,
        'league',
        'Supercoppa programmata',
        pg_catalog.format(
          '%s contro %s alla giornata %s.',
          v_home_team.name,
          v_away_team.name,
          v_matchday.number
        ),
        'leagueSuperCup',
        jsonb_build_object(
          'superCupId', v_super_cup_id,
          'matchdayNumber', v_matchday.number,
          'schedulePolicy', 'guarded_v1'
        ),
        pg_catalog.format('league-super-cup-created:%s', v_super_cup_id)
      );
    end loop;
  end if;

  return public.get_league_super_cup_state_v2(p_league_id)
    || jsonb_build_object(
      'idempotentReplay', false,
      'alreadyExists', false
    );
end;
$$;

