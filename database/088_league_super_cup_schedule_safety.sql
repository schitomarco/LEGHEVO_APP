create or replace function public.get_league_super_cup_schedule_integrity_v1(
  p_league_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_run public.league_super_cup_schedule_runs%rowtype;
  v_hash_matches boolean := false;
  v_source_certified boolean := false;
begin
  if auth.uid() is null then
    raise exception 'Devi effettuare l''accesso.';
  end if;

  if not public.is_league_member(p_league_id)
    and not public.is_league_admin(p_league_id) then
    raise exception 'Non fai parte di questa lega.';
  end if;

  select run.*
  into v_run
  from public.league_super_cup_schedule_runs run
  where run.league_id = p_league_id
  order by run.created_at desc, run.id desc
  limit 1;

  if v_run.id is not null then
    v_hash_matches := v_run.result_hash =
      public.compute_league_super_cup_schedule_result_hash_v1(
        v_run.super_cup_id,
        v_run.qualifiers_hash,
        v_run.schedule_hash
      );

    select exists (
      select 1
      from public.league_cups cup
      join public.league_cup_completion_certificates certificate
        on certificate.cup_id = cup.id
