-- Certifica senza modificarle eventuali Supercoppe già programmate.
with candidates as (
  select
    super_cup.*,
    matchday.number::smallint as matchday_number,
    matchday.starts_at,
    matchday.locks_at,
    matchday.ends_at,
    coalesce(certificate.completion_fingerprint, '-') as source_certificate_hash
  from public.league_super_cups super_cup
  join public.matchdays matchday on matchday.id = super_cup.matchday_id
  left join public.league_cups source_cup
    on source_cup.league_id = super_cup.source_league_id
    and source_cup.status = 'completed'
  left join public.league_cup_completion_certificates certificate
    on certificate.cup_id = source_cup.id
  where not exists (
    select 1
    from public.league_super_cup_schedule_runs run
    where run.super_cup_id = super_cup.id
  )
), hashes as (
  select
    candidate.*,
    public.leghevo_sha256_hex_v1(
      candidate.league_id::text || '#'
      || candidate.source_league_id::text || '#'
      || candidate.source_certificate_hash || '#'
      || candidate.league_champion_team_id::text || '#'
      || candidate.challenger_team_id::text || '#'
      || candidate.challenger_qualification
    ) as qualifiers_hash,
    public.leghevo_sha256_hex_v1(
      candidate.matchday_id::text || '#'
      || candidate.matchday_number::text || '#'
      || candidate.starts_at::text || '#'
      || candidate.locks_at::text || '#'
      || coalesce(candidate.ends_at::text, '-')
    ) as schedule_hash
  from candidates candidate
)
insert into public.league_super_cup_schedule_runs (
  league_id,
  super_cup_id,
  source_league_id,
  request_id,
  requested_by,
  matchday_id,
  matchday_number,
  league_champion_team_id,
  challenger_team_id,
  challenger_qualification,
  qualifiers_hash,
  schedule_hash,
  result_hash,
  created_at
)
select
  hashes.league_id,
  hashes.id,
  hashes.source_league_id,
  public.leghevo_stable_request_uuid(
    'league-super-cup-schedule-backfill:' || hashes.id::text
  ),
  hashes.created_by,
  hashes.matchday_id,
  hashes.matchday_number,
  hashes.league_champion_team_id,
  hashes.challenger_team_id,
  hashes.challenger_qualification,
  hashes.qualifiers_hash,
  hashes.schedule_hash,
  public.compute_league_super_cup_schedule_result_hash_v1(
    hashes.id,
    hashes.qualifiers_hash,
    hashes.schedule_hash
  ),
  hashes.created_at
from hashes
on conflict do nothing;

