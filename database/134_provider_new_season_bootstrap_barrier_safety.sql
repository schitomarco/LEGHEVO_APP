create or replace function public.get_league_provider_sync_health_v29(p_league_id uuid)
returns jsonb language plpgsql stable security definer set search_path='' as $function$
declare v_base jsonb;v_gate jsonb;v_healthy boolean;
begin
  v_base:=public.get_league_provider_sync_health_v28(p_league_id);
  v_gate:=public.compute_provider_season_bootstrap_gate_v1(p_league_id);
  v_healthy:=coalesce((v_base->>'healthy')::boolean,false)
    and coalesce((v_gate->>'healthy')::boolean,true)
    and not coalesce((v_gate->>'affected')::boolean,false);
  return v_base||jsonb_build_object(
    'protected',coalesce((v_base->>'protected')::boolean,false)
      and coalesce((v_gate->>'protected')::boolean,false),
    'healthy',v_healthy,
    'status',case when v_healthy then coalesce(v_base->>'status','idle')
      else 'attention' end,
    'providerSeasonBootstrap',v_gate
  );
end;
$function$;
revoke all on function public.get_league_provider_sync_health_v29(uuid)
from public,anon,service_role;
grant execute on function public.get_league_provider_sync_health_v29(uuid)
to authenticated;

-- Backfill non distruttivo: nessuna lega viene modificata o riaperta.
do $backfill$
declare v_league_id uuid;
begin
  for v_league_id in select league.id from public.leagues league
    where league.previous_league_id is not null
  loop
    perform public.reconcile_provider_season_bootstrap_v1(v_league_id,true);
  end loop;
end;
$backfill$;

do $realtime$
begin
  if not exists(select 1 from pg_publication_tables
    where pubname='supabase_realtime' and schemaname='public'
      and tablename='provider_season_bootstrap_events') then
    alter publication supabase_realtime
      add table public.provider_season_bootstrap_events;
  end if;
end;
$realtime$;

create or replace function public.get_provider_season_bootstrap_integrity_v1()
returns jsonb language plpgsql stable security definer set search_path='' as $function$
declare
  v_certify text:=coalesce(pg_catalog.pg_get_functiondef(
    to_regprocedure('public.certify_provider_season_bootstrap_v1(uuid)')),'');
  v_reconcile text:=coalesce(pg_catalog.pg_get_functiondef(
    to_regprocedure('public.reconcile_provider_season_bootstrap_v1(uuid,boolean)')),'');
  v_assert text:=coalesce(pg_catalog.pg_get_functiondef(
    to_regprocedure('public.assert_provider_season_bootstrap_ready_v1(uuid,text)')),'');
  v_renew text:=coalesce(pg_catalog.pg_get_functiondef(
    to_regprocedure('public.renew_league_season_guarded_v3(uuid,text,uuid)')),'');
  v_legacy text:=coalesce(pg_catalog.pg_get_functiondef(
    to_regprocedure('public.renew_league_season(uuid,text)')),'');
begin
  return jsonb_build_object(
    'predecessor_ready',
      to_regprocedure('public.get_league_season_rollover_integrity_v1()') is not null
      and (select count(*) from jsonb_each(
        public.get_league_season_rollover_integrity_v1()))=20,
    'certificate_table_ready',
      to_regclass('public.provider_season_bootstrap_certificates') is not null,
    'head_table_ready',
      to_regclass('public.provider_season_bootstrap_heads') is not null,
    'event_table_ready',
      to_regclass('public.provider_season_bootstrap_events') is not null,
    'columns_ready',
      (select count(*)=33 from information_schema.columns column_row
       where column_row.table_schema='public'
         and ((column_row.table_name='provider_season_bootstrap_certificates'
           and column_row.column_name in('id','league_id','rollover_certificate_id',
             'provider','competition_code','season','catalog_head_id',
             'catalog_publication_id','catalog_run_id','catalog_generation',
             'catalog_player_count','fixture_scope_certificate_id',
             'fixture_publication_id','fixture_run_id','fixture_count',
             'matchday_count','fixture_team_count','first_kickoff_at','last_kickoff_at',
             'fixture_fingerprint','bootstrap_hash','certified_by',
             'certified_at','result_payload'))
          or (column_row.table_name='provider_season_bootstrap_heads'
           and column_row.column_name in('league_id','certificate_id',
             'bootstrap_status','reason_code','observed_season','catalog_ready',
             'fixtures_ready','observed_catalog_generation',
             'observed_fixture_team_count')))),
    'constraints_ready',
      (select count(*)>=12 from pg_catalog.pg_constraint c
       where c.conrelid in('public.provider_season_bootstrap_certificates'::regclass,
         'public.provider_season_bootstrap_heads'::regclass,
         'public.provider_season_bootstrap_events'::regclass)),
    'indexes_ready',
      to_regclass('public.provider_season_bootstrap_certificates_created_idx') is not null
      and to_regclass('public.provider_season_bootstrap_heads_status_idx') is not null
      and to_regclass('public.provider_season_bootstrap_events_league_idx') is not null,
    'rls_ready',
      coalesce((select relrowsecurity from pg_catalog.pg_class
        where oid='public.provider_season_bootstrap_certificates'::regclass),false)
      and coalesce((select relrowsecurity from pg_catalog.pg_class
        where oid='public.provider_season_bootstrap_heads'::regclass),false)
      and coalesce((select relrowsecurity from pg_catalog.pg_class
        where oid='public.provider_season_bootstrap_events'::regclass),false),
    'direct_write_blocked',
      has_table_privilege('authenticated',
        'public.provider_season_bootstrap_certificates','SELECT')
      and not has_table_privilege('authenticated',
        'public.provider_season_bootstrap_certificates','INSERT')
      and not has_table_privilege('authenticated',
        'public.provider_season_bootstrap_heads','UPDATE')
      and not has_table_privilege('authenticated',
        'public.provider_season_bootstrap_events','DELETE'),
    'immutable_certificate_ready',
      exists(select 1 from pg_catalog.pg_trigger t
        where t.tgrelid='public.provider_season_bootstrap_certificates'::regclass
          and t.tgname='provider_season_bootstrap_certificates_immutable'
          and t.tgenabled='A'),
    'immutable_events_ready',
      exists(select 1 from pg_catalog.pg_trigger t
        where t.tgrelid='public.provider_season_bootstrap_events'::regclass
          and t.tgname='provider_season_bootstrap_events_immutable'
          and t.tgenabled='A'),
    'head_guard_ready',
      exists(select 1 from pg_catalog.pg_trigger t
        where t.tgrelid='public.provider_season_bootstrap_heads'::regclass
          and t.tgname='provider_season_bootstrap_heads_write_guard'
          and t.tgenabled='A'),
    'assessment_rpc_ready',
      to_regprocedure('public.compute_provider_season_bootstrap_gate_v1(uuid)') is not null
      and to_regprocedure('public.compute_provider_season_fixture_fingerprint_v1(text,integer)') is not null,
    'certify_rpc_ready',
      to_regprocedure('public.certify_provider_season_bootstrap_v1(uuid)') is not null
      and position('provider-new-season-bootstrap' in v_certify)>0
      and position('compute_provider_season_bootstrap_hash_v1' in v_certify)>0,
    'reconcile_rpc_ready',
      to_regprocedure('public.reconcile_provider_season_bootstrap_v1(uuid,boolean)') is not null
      and position('provider-new-season-bootstrap' in v_reconcile)>0,
    'market_guard_ready',
      position('catalog' in v_assert)>0
      and exists(select 1 from pg_catalog.pg_trigger t
        where t.tgrelid='public.roster_entries'::regclass
          and t.tgname='provider_season_bootstrap_roster_guard' and t.tgenabled='A')
      and exists(select 1 from pg_catalog.pg_trigger t
        where t.tgrelid='public.auction_items'::regclass
          and t.tgname='provider_season_bootstrap_auction_item_guard' and t.tgenabled='A'),
    'calendar_guard_ready',
      position('fixtures' in v_assert)>0
      and exists(select 1 from pg_catalog.pg_trigger t
        where t.tgrelid='public.fantasy_fixtures'::regclass
          and t.tgname='provider_season_bootstrap_calendar_guard' and t.tgenabled='A'),
    'renewal_v3_ready',
      to_regprocedure('public.renew_league_season_guarded_v3(uuid,text,uuid)') is not null
      and position('reconcile_provider_season_bootstrap_v1' in v_renew)>0
      and position('renew_league_season_guarded_v3' in v_legacy)>0,
    'state_and_health_ready',
      to_regprocedure('public.get_league_season_state_v8(uuid)') is not null
      and to_regprocedure('public.get_league_management_state_v18(uuid)') is not null
      and to_regprocedure('public.get_league_provider_sync_health_v29(uuid)') is not null,
    'backfill_and_realtime_ready',
      not exists(select 1 from public.leagues league
        left join public.provider_season_bootstrap_heads head
          on head.league_id=league.id
        where league.previous_league_id is not null and head.league_id is null)
      and not exists(select 1
        from public.provider_season_bootstrap_certificates certificate
        where certificate.bootstrap_hash<>public.compute_provider_season_bootstrap_hash_v1(
          certificate.league_id,certificate.rollover_certificate_id,
          certificate.provider,certificate.season,certificate.catalog_head_id,
          certificate.catalog_generation,certificate.catalog_player_count,
          certificate.fixture_scope_certificate_id,certificate.fixture_count,
          certificate.matchday_count,certificate.fixture_team_count,
          certificate.fixture_fingerprint
        ))
      and exists(select 1 from pg_publication_tables
        where pubname='supabase_realtime' and schemaname='public'
          and tablename='provider_season_bootstrap_events')
  );
end;
$function$;
