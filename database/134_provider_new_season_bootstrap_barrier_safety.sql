create or replace function public.certify_provider_season_bootstrap_v1(
  p_league_id uuid
)
returns jsonb language plpgsql security definer set search_path='' as $function$
declare
  v_gate jsonb;
  v_existing public.provider_season_bootstrap_certificates%rowtype;
  v_certificate_id bigint;
  v_hash text;
  v_payload jsonb;
begin
  if auth.uid() is not null and not(
    public.is_league_admin(p_league_id)
    or exists(select 1 from public.leagues league
      where league.id=p_league_id and league.owner_id=auth.uid())
  ) then
    raise exception 'Solo la Direzione può certificare il bootstrap provider.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
    'league-season-rollover-lineage:'||p_league_id::text,0));
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
    'provider-new-season-bootstrap:'||p_league_id::text,0));

  select certificate.* into v_existing
  from public.provider_season_bootstrap_certificates certificate
  where certificate.league_id=p_league_id;
  if found then
    return public.compute_provider_season_bootstrap_gate_v1(p_league_id)
      ||jsonb_build_object('certified',true,'certificateId',v_existing.id,
        'bootstrapHash',v_existing.bootstrap_hash);
  end if;

  v_gate:=public.compute_provider_season_bootstrap_gate_v1(p_league_id);
  if not coalesce((v_gate->>'applicable')::boolean,false) then return v_gate; end if;
  if coalesce(v_gate->>'status','waiting')<>'ready'
    or not coalesce((v_gate->>'catalogReady')::boolean,false)
    or not coalesce((v_gate->>'fixturesReady')::boolean,false)
    or coalesce((v_gate->>'affected')::boolean,false) then
    raise exception 'Bootstrap provider non certificabile [%].',v_gate->>'reasonCode';
  end if;

  v_hash:=public.compute_provider_season_bootstrap_hash_v1(
    p_league_id,(v_gate->>'rolloverCertificateId')::bigint,v_gate->>'provider',
    (v_gate->>'season')::integer,(v_gate->>'catalogHeadId')::uuid,
    (v_gate->>'catalogGeneration')::bigint,
    (v_gate->>'catalogPlayerCount')::integer,
    (v_gate->>'fixtureScopeCertificateId')::uuid,
