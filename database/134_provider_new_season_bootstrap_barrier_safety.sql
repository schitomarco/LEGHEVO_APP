create or replace function public.compute_provider_season_bootstrap_gate_v1(
  p_league_id uuid
)
returns jsonb language plpgsql stable security definer set search_path='' as $function$
declare
  v_league public.leagues%rowtype;
  v_rollover public.league_season_rollover_certificates%rowtype;
  v_rollover_head public.league_season_rollover_heads%rowtype;
  v_catalog public.provider_player_catalog_heads%rowtype;
  v_catalog_publication public.provider_sync_publications%rowtype;
  v_catalog_run public.provider_sync_runs%rowtype;
  v_fixture_scope public.provider_sync_scope_certificates%rowtype;
  v_fixture_publication public.provider_sync_publications%rowtype;
  v_fixture_run public.provider_sync_runs%rowtype;
  v_existing public.provider_season_bootstrap_certificates%rowtype;
  v_season integer;
  v_fixture_count integer:=0;
  v_matchday_count integer:=0;
  v_fixture_team_count integer:=0;
  v_unlinked_count integer:=0;
  v_unknown_count integer:=0;
  v_first_kickoff timestamptz;
  v_last_kickoff timestamptz;
  v_fixture_fingerprint text;
  v_catalog_ready boolean:=false;
  v_fixtures_ready boolean:=false;
  v_status text:='waiting';
  v_reason text:='provider_bootstrap.waiting';
  v_affected boolean:=false;
  v_market_activity_exists boolean:=false;
  v_calendar_activity_exists boolean:=false;
begin
  select league.* into v_league from public.leagues league
  where league.id=p_league_id;
  if not found then raise exception 'Lega non trovata.'; end if;

  if v_league.previous_league_id is null then
    return jsonb_build_object(
      'protected',true,'applicable',false,'healthy',true,'affected',false,
      'status','ready','reasonCode','provider_bootstrap.not_required',
      'season',case when coalesce(v_league.calendar_season,'')~'^[0-9]{4}$'
        then v_league.calendar_season::integer else null end,
      'catalogReady',true,'fixturesReady',true,'certified',false
    );
  end if;

  if coalesce(v_league.calendar_season,'')!~'^[0-9]{4}$' then
    return jsonb_build_object(
      'protected',true,'applicable',true,'healthy',false,'affected',true,
      'status','affected','reasonCode','provider_bootstrap.invalid_league_season',
      'season',null,'catalogReady',false,'fixturesReady',false,'certified',false
    );
  end if;
  v_season:=v_league.calendar_season::integer;

  select certificate.* into v_rollover
  from public.league_season_rollover_certificates certificate
  where certificate.renewed_league_id=p_league_id;
  select head.* into v_rollover_head
  from public.league_season_rollover_heads head
  where head.renewed_league_id=p_league_id;

  if v_rollover.id is null or v_rollover_head.certificate_id is null then
    v_status:='affected';v_reason:='provider_bootstrap.rollover_certificate_missing';
    v_affected:=true;
  elsif v_rollover.renewed_season::integer<>v_season then
    v_status:='affected';v_reason:='provider_bootstrap.rollover_season_mismatch';
    v_affected:=true;
  elsif v_rollover_head.rollover_status<>'certified' then
    v_status:='affected';v_reason:='provider_bootstrap.rollover_affected';
    v_affected:=true;
  end if;

  select head.* into v_catalog
  from public.provider_player_catalog_heads head
  where head.competition_code='IT-SA'
  order by case when head.latest_season=v_season then 0 else 1 end,
    head.latest_season desc,head.updated_at desc
  limit 1;

  if not v_affected then
    if v_catalog.id is null then
      v_reason:='provider_bootstrap.catalog_missing';
    elsif v_catalog.latest_season<v_season then
      v_reason:='provider_bootstrap.catalog_previous_season';
    elsif v_catalog.latest_season>v_season then
      v_status:='affected';v_reason:='provider_bootstrap.catalog_season_advanced';
      v_affected:=true;
    elsif v_catalog.active_player_count<300 then
      v_reason:='provider_bootstrap.catalog_incomplete';
    else
      select publication.* into v_catalog_publication
      from public.provider_sync_publications publication
      where publication.id=v_catalog.latest_publication_id;
      select run.* into v_catalog_run from public.provider_sync_runs run
      where run.id=v_catalog.latest_run_id;
      if v_catalog_publication.status<>'published'
        or v_catalog_run.status<>'completed' then
        v_reason:='provider_bootstrap.catalog_not_published';
      elsif not exists(
        select 1 from public.provider_player_catalog_reconciliations reconciliation
        where reconciliation.head_id=v_catalog.id
          and reconciliation.run_id=v_catalog.latest_run_id
          and reconciliation.publication_id=v_catalog.latest_publication_id
          and reconciliation.status='applied'
          and reconciliation.season=v_season
          and reconciliation.generation=v_catalog.generation
      ) then
        v_reason:='provider_bootstrap.catalog_reconciliation_missing';
      else
        v_catalog_ready:=true;
        v_status:='catalog_ready';
        v_reason:='provider_bootstrap.catalog_ready';
      end if;
    end if;
  end if;

  if v_catalog_ready and not v_affected then
    select scope.* into v_fixture_scope
    from public.provider_sync_scope_certificates scope
    join public.provider_sync_publications publication
      on publication.id=scope.publication_id
    join public.provider_sync_runs run on run.id=scope.run_id
    where scope.provider=v_catalog.provider
      and scope.sync_type='sync-fixtures'
      and scope.scope_kind='date'
      and scope.requested_season=v_season
      and scope.status='certified'
      and publication.status='published'
      and run.status='completed'
    order by scope.certified_at desc nulls last,scope.updated_at desc
    limit 1;

    select count(*)::integer,count(distinct fixture.matchday_id)::integer,
      count(*) filter(where fixture.matchday_id is null)::integer,
      count(*) filter(where fixture.provider_lifecycle_state='unknown')::integer,
      min(fixture.kickoff_at),max(fixture.kickoff_at)
    into v_fixture_count,v_matchday_count,v_unlinked_count,v_unknown_count,
      v_first_kickoff,v_last_kickoff
    from public.provider_fixtures fixture
    where fixture.provider=v_catalog.provider
      and fixture.competition_code='IT-SA'
      and fixture.season=v_season::text;

    select count(distinct team_id)::integer into v_fixture_team_count
    from (
      select fixture.home_team_provider_id as team_id
      from public.provider_fixtures fixture
      where fixture.provider=v_catalog.provider
        and fixture.competition_code='IT-SA'
        and fixture.season=v_season::text
      union
      select fixture.away_team_provider_id as team_id
      from public.provider_fixtures fixture
      where fixture.provider=v_catalog.provider
        and fixture.competition_code='IT-SA'
        and fixture.season=v_season::text
    ) provider_teams;

    v_fixture_fingerprint:=public.compute_provider_season_fixture_fingerprint_v1(
      v_catalog.provider,v_season
    );

    if v_fixture_scope.id is null then
      v_reason:='provider_bootstrap.fixture_scope_missing';
    elsif v_fixture_count<380 or v_matchday_count<38
      or v_fixture_team_count<20 then
      v_reason:='provider_bootstrap.fixture_coverage_incomplete';
    elsif v_unlinked_count>0 then
      v_reason:='provider_bootstrap.fixtures_unlinked';
    elsif v_unknown_count>0 then
      v_reason:='provider_bootstrap.fixture_lifecycle_unknown';
    elsif exists(
      select 1 from public.provider_fixtures fixture
      join public.matchdays matchday on matchday.id=fixture.matchday_id
      where fixture.provider=v_catalog.provider
        and fixture.competition_code='IT-SA'
        and fixture.season=v_season::text
        and (matchday.competition_code<>'IT-SA' or matchday.season<>v_season::text)
    ) then
      v_status:='affected';v_reason:='provider_bootstrap.fixture_scope_mismatch';
      v_affected:=true;
    else
      select publication.* into v_fixture_publication
      from public.provider_sync_publications publication
      where publication.id=v_fixture_scope.publication_id;
      select run.* into v_fixture_run from public.provider_sync_runs run
      where run.id=v_fixture_scope.run_id;
      v_fixtures_ready:=true;
      v_status:='ready';
      v_reason:='provider_bootstrap.ready';
    end if;
  end if;

  select certificate.* into v_existing
  from public.provider_season_bootstrap_certificates certificate
  where certificate.league_id=p_league_id;

  if v_existing.id is not null then
    if v_existing.bootstrap_hash<>public.compute_provider_season_bootstrap_hash_v1(
      v_existing.league_id,v_existing.rollover_certificate_id,
      v_existing.provider,v_existing.season,v_existing.catalog_head_id,
      v_existing.catalog_generation,v_existing.catalog_player_count,
      v_existing.fixture_scope_certificate_id,v_existing.fixture_count,
      v_existing.matchday_count,v_existing.fixture_team_count,
      v_existing.fixture_fingerprint
    ) then
      v_status:='affected';v_reason:='provider_bootstrap.certificate_hash_mismatch';
      v_affected:=true;
    elsif not v_catalog_ready or not v_fixtures_ready then
      v_status:='affected';v_reason:='provider_bootstrap.certified_scope_regressed';
      v_affected:=true;
    elsif v_existing.season<>v_season
      or v_existing.provider<>v_catalog.provider
      or v_existing.catalog_head_id<>v_catalog.id
      or v_existing.catalog_generation<>v_catalog.generation
      or v_existing.catalog_player_count<>v_catalog.active_player_count
      or v_existing.fixture_fingerprint<>v_fixture_fingerprint then
      v_status:='affected';v_reason:='provider_bootstrap.generation_or_scope_changed';
      v_affected:=true;
    end if;
  else
    select
      exists(select 1 from public.roster_entries roster
        where roster.league_id=p_league_id)
      or exists(select 1 from public.auction_items item
        join public.auctions auction on auction.id=item.auction_id
        where auction.league_id=p_league_id),
      exists(select 1 from public.fantasy_fixtures fixture
        where fixture.league_id=p_league_id)
    into v_market_activity_exists,v_calendar_activity_exists;

    if v_market_activity_exists and not v_catalog_ready then
      v_status:='affected';
      v_reason:='provider_bootstrap.market_before_catalog_ready';
      v_affected:=true;
    elsif v_calendar_activity_exists
      and (not v_catalog_ready or not v_fixtures_ready) then
      v_status:='affected';
      v_reason:='provider_bootstrap.calendar_before_certification';
      v_affected:=true;
    end if;
  end if;

  return jsonb_build_object(
    'protected',true,'applicable',true,
    'healthy',not v_affected and v_catalog_ready,
    'affected',v_affected,'status',v_status,'reasonCode',v_reason,
    'leagueId',p_league_id,'season',v_season,
    'rolloverCertificateId',v_rollover.id,
    'catalogReady',v_catalog_ready,'fixturesReady',v_fixtures_ready,
    'provider',v_catalog.provider,'catalogHeadId',v_catalog.id,
    'catalogPublicationId',v_catalog.latest_publication_id,
    'catalogRunId',v_catalog.latest_run_id,
    'catalogSeason',v_catalog.latest_season,
    'catalogGeneration',v_catalog.generation,
    'catalogPlayerCount',coalesce(v_catalog.active_player_count,0),
    'fixtureScopeCertificateId',v_fixture_scope.id,
    'fixturePublicationId',v_fixture_scope.publication_id,
    'fixtureRunId',v_fixture_scope.run_id,
    'fixtureCount',v_fixture_count,'matchdayCount',v_matchday_count,
    'fixtureTeamCount',v_fixture_team_count,'firstKickoffAt',v_first_kickoff,'lastKickoffAt',v_last_kickoff,
    'fixtureFingerprint',v_fixture_fingerprint,
    'certified',v_existing.id is not null,'certificateId',v_existing.id,
    'bootstrapHash',v_existing.bootstrap_hash
  );
end;
