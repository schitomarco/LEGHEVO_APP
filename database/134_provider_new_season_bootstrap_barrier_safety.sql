create or replace function public.assert_provider_season_bootstrap_ready_v1(
  p_league_id uuid,p_requirement text
)
returns void language plpgsql security definer set search_path='' as $function$
declare v_gate jsonb;v_requirement text:=lower(trim(coalesce(p_requirement,'')));
begin
  v_gate:=public.compute_provider_season_bootstrap_gate_v1(p_league_id);
  if not coalesce((v_gate->>'applicable')::boolean,false) then return; end if;
  if coalesce((v_gate->>'affected')::boolean,false) then
    raise exception 'Operazione bloccata [%].',v_gate->>'reasonCode';
  end if;
  if v_requirement='catalog' and not coalesce(
    (v_gate->>'catalogReady')::boolean,false) then
    raise exception 'Catalogo provider nuova stagione non pronto [%].',
      v_gate->>'reasonCode';
  elsif v_requirement='fixtures' and not(
    coalesce((v_gate->>'catalogReady')::boolean,false)
    and coalesce((v_gate->>'fixturesReady')::boolean,false)
    and coalesce((v_gate->>'certified')::boolean,false)
  ) then
    raise exception 'Calendario provider nuova stagione non certificato [%].',
      v_gate->>'reasonCode';
  elsif v_requirement not in('catalog','fixtures') then
    raise exception 'Requisito bootstrap provider sconosciuto.';
  end if;
end;
