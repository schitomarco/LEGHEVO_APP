create or replace function public.reconcile_provider_season_bootstrap_v1(
  p_league_id uuid,p_auto_certify boolean default true
)
returns jsonb language plpgsql security definer set search_path='' as $function$
declare
  v_gate jsonb;
  v_head public.provider_season_bootstrap_heads%rowtype;
  v_status text;
  v_reason text;
  v_event_type text;
  v_catalog_ready boolean;
  v_fixtures_ready boolean;
  v_certificate_id bigint;
begin
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
    'provider-new-season-bootstrap:'||p_league_id::text,0));
  v_gate:=public.compute_provider_season_bootstrap_gate_v1(p_league_id);
  if not coalesce((v_gate->>'applicable')::boolean,false) then return v_gate; end if;

  if p_auto_certify and coalesce(v_gate->>'status','waiting')='ready'
    and not coalesce((v_gate->>'certified')::boolean,false) then
    return public.certify_provider_season_bootstrap_v1(p_league_id);
  end if;

  v_status:=coalesce(v_gate->>'status','waiting');
  v_reason:=coalesce(v_gate->>'reasonCode','provider_bootstrap.waiting');
  v_catalog_ready:=coalesce((v_gate->>'catalogReady')::boolean,false);
  v_fixtures_ready:=coalesce((v_gate->>'fixturesReady')::boolean,false);
  v_certificate_id:=nullif(v_gate->>'certificateId','')::bigint;

  select head.* into v_head from public.provider_season_bootstrap_heads head
  where head.league_id=p_league_id for update;
  if found and v_head.bootstrap_status=v_status
    and v_head.reason_code=v_reason
    and v_head.catalog_ready=v_catalog_ready
    and v_head.fixtures_ready=v_fixtures_ready
    and v_head.observed_catalog_generation is not distinct from
      nullif(v_gate->>'catalogGeneration','')::bigint
    and v_head.observed_fixture_fingerprint is not distinct from
      v_gate->>'fixtureFingerprint' then
    return v_gate;
  end if;

  v_event_type:=case
    when v_status='affected' then 'affected'
    when v_status='ready' and v_certificate_id is not null
      and found and v_head.bootstrap_status='affected' then 'revalidated'
    when v_status='catalog_ready' then 'catalog_ready'
    when v_status='ready' then 'certified'
    else 'waiting' end;

  perform set_config('leghevo.provider_season_bootstrap_context','on',true);
  insert into public.provider_season_bootstrap_heads(
    league_id,certificate_id,bootstrap_status,reason_code,observed_season,
    catalog_ready,fixtures_ready,observed_provider,observed_catalog_season,
    observed_catalog_generation,observed_catalog_player_count,
    observed_fixture_count,observed_matchday_count,observed_fixture_team_count,
    observed_fixture_fingerprint,affected_at,last_assessed_at,updated_at
  ) values(
    p_league_id,v_certificate_id,v_status,v_reason,(v_gate->>'season')::integer,
    v_catalog_ready,v_fixtures_ready,v_gate->>'provider',
    nullif(v_gate->>'catalogSeason','')::integer,
    nullif(v_gate->>'catalogGeneration','')::bigint,
    coalesce(nullif(v_gate->>'catalogPlayerCount','')::integer,0),
    coalesce(nullif(v_gate->>'fixtureCount','')::integer,0),
    coalesce(nullif(v_gate->>'matchdayCount','')::integer,0),
    coalesce(nullif(v_gate->>'fixtureTeamCount','')::integer,0),
    v_gate->>'fixtureFingerprint',case when v_status='affected' then now() end,
    now(),now()
  ) on conflict(league_id) do update set
    certificate_id=coalesce(excluded.certificate_id,
      public.provider_season_bootstrap_heads.certificate_id),
    bootstrap_status=excluded.bootstrap_status,reason_code=excluded.reason_code,
    observed_season=excluded.observed_season,
    catalog_ready=excluded.catalog_ready,fixtures_ready=excluded.fixtures_ready,
    observed_provider=excluded.observed_provider,
    observed_catalog_season=excluded.observed_catalog_season,
    observed_catalog_generation=excluded.observed_catalog_generation,
    observed_catalog_player_count=excluded.observed_catalog_player_count,
    observed_fixture_count=excluded.observed_fixture_count,
    observed_matchday_count=excluded.observed_matchday_count,
    observed_fixture_team_count=excluded.observed_fixture_team_count,
    observed_fixture_fingerprint=excluded.observed_fixture_fingerprint,
    affected_at=case when excluded.bootstrap_status='affected'
      then coalesce(public.provider_season_bootstrap_heads.affected_at,now())
      else null end,last_assessed_at=now(),updated_at=now();

  select head.* into v_head from public.provider_season_bootstrap_heads head
  where head.league_id=p_league_id;
  insert into public.provider_season_bootstrap_events(
    league_id,certificate_id,event_type,bootstrap_status,reason_code,
    observed_season,catalog_ready,fixtures_ready,observed_catalog_generation,
    observed_catalog_player_count,observed_fixture_count,
    observed_matchday_count,observed_fixture_team_count,
    observed_fixture_fingerprint,event_payload
  ) values(
    p_league_id,v_head.certificate_id,v_event_type,v_head.bootstrap_status,
    v_head.reason_code,v_head.observed_season,v_head.catalog_ready,
    v_head.fixtures_ready,v_head.observed_catalog_generation,
    v_head.observed_catalog_player_count,v_head.observed_fixture_count,
    v_head.observed_matchday_count,v_head.observed_fixture_team_count,
    v_head.observed_fixture_fingerprint,
    jsonb_build_object('assessment',v_gate)
  );
  perform set_config('leghevo.provider_season_bootstrap_context','',true);
  return v_gate||jsonb_build_object('certificateId',v_head.certificate_id);
end;
