    catalog_head_id,catalog_publication_id,catalog_run_id,catalog_generation,
    catalog_player_count,fixture_scope_certificate_id,fixture_publication_id,
    fixture_run_id,fixture_count,matchday_count,fixture_team_count,
    first_kickoff_at,last_kickoff_at,
    fixture_fingerprint,bootstrap_hash,certified_by,result_payload
  ) values(
    v_certificate_id,p_league_id,(v_gate->>'rolloverCertificateId')::bigint,
    v_gate->>'provider','IT-SA',(v_gate->>'season')::integer,
    (v_gate->>'catalogHeadId')::uuid,(v_gate->>'catalogPublicationId')::uuid,
    (v_gate->>'catalogRunId')::uuid,(v_gate->>'catalogGeneration')::bigint,
    (v_gate->>'catalogPlayerCount')::integer,
    (v_gate->>'fixtureScopeCertificateId')::uuid,
    (v_gate->>'fixturePublicationId')::uuid,(v_gate->>'fixtureRunId')::uuid,
    (v_gate->>'fixtureCount')::integer,(v_gate->>'matchdayCount')::integer,
    (v_gate->>'fixtureTeamCount')::integer,(v_gate->>'firstKickoffAt')::timestamptz,
    (v_gate->>'lastKickoffAt')::timestamptz,
    v_gate->>'fixtureFingerprint',v_hash,auth.uid(),v_payload
  );

  insert into public.provider_season_bootstrap_heads(
    league_id,certificate_id,bootstrap_status,reason_code,observed_season,
    catalog_ready,fixtures_ready,observed_provider,observed_catalog_season,
    observed_catalog_generation,observed_catalog_player_count,
    observed_fixture_count,observed_matchday_count,observed_fixture_team_count,
    observed_fixture_fingerprint,last_assessed_at,updated_at
  ) values(
    p_league_id,v_certificate_id,'ready','provider_bootstrap.certified',
    (v_gate->>'season')::integer,true,true,v_gate->>'provider',
    (v_gate->>'catalogSeason')::integer,(v_gate->>'catalogGeneration')::bigint,
    (v_gate->>'catalogPlayerCount')::integer,(v_gate->>'fixtureCount')::integer,
    (v_gate->>'matchdayCount')::integer,(v_gate->>'fixtureTeamCount')::integer,
    v_gate->>'fixtureFingerprint',now(),now()
  ) on conflict(league_id) do update set
    certificate_id=excluded.certificate_id,bootstrap_status='ready',
    reason_code='provider_bootstrap.certified',catalog_ready=true,
    fixtures_ready=true,observed_provider=excluded.observed_provider,
    observed_catalog_season=excluded.observed_catalog_season,
    observed_catalog_generation=excluded.observed_catalog_generation,
    observed_catalog_player_count=excluded.observed_catalog_player_count,
    observed_fixture_count=excluded.observed_fixture_count,
    observed_matchday_count=excluded.observed_matchday_count,
    observed_fixture_team_count=excluded.observed_fixture_team_count,
    observed_fixture_fingerprint=excluded.observed_fixture_fingerprint,
    affected_at=null,last_assessed_at=now(),updated_at=now();

  insert into public.provider_season_bootstrap_events(
    league_id,certificate_id,event_type,bootstrap_status,reason_code,
    observed_season,catalog_ready,fixtures_ready,observed_catalog_generation,
    observed_catalog_player_count,observed_fixture_count,
    observed_matchday_count,observed_fixture_team_count,
    observed_fixture_fingerprint,event_payload
  ) values(
    p_league_id,v_certificate_id,'certified','ready',
    'provider_bootstrap.certified',(v_gate->>'season')::integer,true,true,
    (v_gate->>'catalogGeneration')::bigint,
    (v_gate->>'catalogPlayerCount')::integer,(v_gate->>'fixtureCount')::integer,
    (v_gate->>'matchdayCount')::integer,(v_gate->>'fixtureTeamCount')::integer,
    v_gate->>'fixtureFingerprint',v_payload
  );
  perform set_config('leghevo.provider_season_bootstrap_context','',true);
  return v_payload;
end;
