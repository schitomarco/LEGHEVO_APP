  fixtures_ready boolean not null default false,
  observed_provider text,
  observed_catalog_season integer,
  observed_catalog_generation bigint,
  observed_catalog_player_count integer not null default 0,
  observed_fixture_count integer not null default 0,
  observed_matchday_count integer not null default 0,
  observed_fixture_team_count integer not null default 0,
  observed_fixture_fingerprint text,
  affected_at timestamptz,
  last_assessed_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint provider_season_bootstrap_heads_status_check
    check(bootstrap_status in ('waiting','catalog_ready','ready','affected')),
  constraint provider_season_bootstrap_heads_reason_check
    check(char_length(trim(reason_code)) between 3 and 180),
  constraint provider_season_bootstrap_heads_season_check
    check(observed_season between 2000 and 2200),
  constraint provider_season_bootstrap_heads_provider_check
    check(observed_provider is null or (
      char_length(trim(observed_provider)) between 1 and 100
      and observed_provider!~E'[\r\n]'
    )),
  constraint provider_season_bootstrap_heads_catalog_check
    check(
      observed_catalog_season is null
      or observed_catalog_season between 2000 and 2200
    ),
  constraint provider_season_bootstrap_heads_generation_check
    check(observed_catalog_generation is null or observed_catalog_generation>0),
  constraint provider_season_bootstrap_heads_counts_check
    check(
      observed_catalog_player_count>=0
      and observed_fixture_count>=0
      and observed_matchday_count>=0
      and observed_fixture_team_count>=0
    ),
  constraint provider_season_bootstrap_heads_fixture_hash_check
    check(
      observed_fixture_fingerprint is null
      or observed_fixture_fingerprint~'^[0-9a-f]{32}$'
    ),
  constraint provider_season_bootstrap_heads_state_check
    check(
      (bootstrap_status='waiting' and not catalog_ready and not fixtures_ready
        and certificate_id is null and affected_at is null)
      or (bootstrap_status='catalog_ready' and catalog_ready and not fixtures_ready
        and certificate_id is null and affected_at is null)
      or (bootstrap_status='ready' and catalog_ready and fixtures_ready
        and certificate_id is not null and affected_at is null)
      or (bootstrap_status='affected' and affected_at is not null)
    )
);

