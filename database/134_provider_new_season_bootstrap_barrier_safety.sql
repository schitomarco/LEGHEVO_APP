create or replace function public.compute_provider_season_fixture_fingerprint_v1(
  p_provider text,p_season integer
)
returns text language sql stable security definer set search_path='' as $function$
  select pg_catalog.md5(coalesce(pg_catalog.string_agg(
    fixture.provider_fixture_id||'|'||fixture.season||'|'||
    coalesce(fixture.matchday_id::text,'')||'|'||
    fixture.home_team_provider_id||'|'||fixture.away_team_provider_id,
    E'\n' order by fixture.provider_fixture_id
  ),''))
  from public.provider_fixtures fixture
  where fixture.provider=p_provider
    and fixture.competition_code='IT-SA'
    and fixture.season=p_season::text;
$function$;
